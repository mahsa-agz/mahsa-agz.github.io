// small numbers for LaTeX: up to 4 significant digits, plain digits; NB_rel gives '=' or '\approx' (when rounded)
const NB_t = x => {
  if (!x) return '0';
  const d = Math.min(14, Math.max(0, 3 - Math.floor(Math.log10(x))));
  let t = x.toFixed(d);
  if (t.includes('.')) t = t.replace(/0+$/, '').replace(/\.$/, '');
  return t;
};
const NB_rel = x => Math.abs(+NB_t(x) - x) > 1e-12 * Math.max(1, x) ? String.raw`\approx` : '=';
const NB_pct = p => fa(Math.round(p * 1000) / 10) + '٪';

// shared drawing: rows of word bars (spam red, normal blue) + the final split bar
// rows: [{w, a, b, la, lb, on, zero}] ; a/b = bar values, la/lb = their labels
const NB_rowY = (n, i) => 2.95 + (n - 1 - i) * 1.15;
const NB_drawRows = (g, rows, max, heads) => {
  const n = rows.length, L = 3.0;
  g.text(5.8, NB_rowY(n, 0) + 0.9, heads[0], 'red', 'center', 0);
  g.text(1.7, NB_rowY(n, 0) + 0.9, heads[1], 'blue', 'center', 0);
  rows.forEach((r, i) => {
    const y = NB_rowY(n, i), al = r.on ? 0.9 : 0.22;
    g.text(9.8, y, r.w, r.on ? 'ink' : 'muted', 'right', 0);
    const ea = 4.3 + L * r.a / max, eb = 0.2 + L * r.b / max;
    g.rect(4.3, y - 0.32, ea, y + 0.32, 'red', al);
    g.rect(0.2, y - 0.32, eb, y + 0.32, 'blue', al);
    g.text(ea + 0.1, y, r.la, r.on ? 'red' : 'muted', 'left', 0);
    g.text(eb + 0.1, y, r.zero && r.on ? 'صفر!' : r.lb, r.zero && r.on ? 'red' : (r.on ? 'blue' : 'muted'), 'left', 0);
  });
};
const NB_drawFinal = (g, p) => {
  const cut = 9.8 - 9.6 * p;
  g.rect(cut, 0.4, 9.8, 1.3, 'red', 0.9);
  g.rect(0.2, 0.4, cut, 1.3, 'blue', 0.9);
  g.text(9.8, 1.75, `اسپم ${NB_pct(p)}`, 'red', 'right', 0);
  g.text(0.2, 1.75, `عادی ${NB_pct(1 - p)}`, 'blue', 'left', 0);
};
// the product as LaTeX, with its result: 0.5 × 0.4 × 0.05 = 0.01 (a zero factor is drawn bold)
const NB_chain = (prior, ps, zeroLast, res) => E([String(prior), ...ps.map((x, k) =>
  zeroLast && k === ps.length - 1 && !x ? String.raw`\mathbf{0}` : NB_t(x))].join(String.raw` \times `) + ` ${NB_rel(res)} ${NB_t(res)}`);
const NB_share = (a, b) => E(String.raw`\frac{${NB_t(a)}}{${NB_t(a)} + ${NB_t(b)}} \approx`);

// ---- Picture 1: a mini spam filter; counts out of 100 spam and 100 normal emails ----
const NB_WORDS = [
  { w: 'رایگان', s: 40, n: 5 },
  { w: 'برنده', s: 30, n: 2 },
  { w: 'پیشنهاد', s: 25, n: 10 },
  { w: 'سلام', s: 50, n: 50 },
  { w: 'جلسه', s: 5, n: 30 },
  { w: 'گزارش', s: 4, n: 25 },
];

const NB_W_FILTER = h => plane(h, {
  x: [0, 10], y: [0, 10.1], ratio: 0.95,
  state: { on: [true, true, false, false, true, false] },
  buttons: NB_WORDS.map((it, k) => ({ label: it.w, on: s => { s.on[k] = !s.on[k]; }, active: s => s.on[k] })),
  draw: (g, s) => {
    const rows = NB_WORDS.map((it, k) => ({ w: it.w, a: it.s, b: it.n, la: fa(it.s), lb: fa(it.n), on: s.on[k] }));
    NB_drawRows(g, rows, 50, ['از ۱۰۰ اسپم', 'از ۱۰۰ عادی']);
    const pick = NB_WORDS.filter((it, k) => s.on[k]);
    const sp = pick.reduce((m, it) => m * it.s / 100, 0.5), nm = pick.reduce((m, it) => m * it.n / 100, 0.5);
    NB_drawFinal(g, sp / (sp + nm));
  },
  read: s => {
    const pick = NB_WORDS.filter((it, k) => s.on[k]);
    if (!pick.length) return 'ایمیل خالی است. فقط پیشین می‌ماند: نیمی اسپم، نیمی عادی ← <b>۵۰٪</b>.';
    const sp = pick.reduce((m, it) => m * it.s / 100, 0.5), nm = pick.reduce((m, it) => m * it.n / 100, 0.5);
    return `<b style="color:var(--red)">امتیازِ اسپم:</b> ${NB_chain(0.5, pick.map(it => it.s / 100), false, sp)}<br>` +
      `<b style="color:var(--blue)">امتیازِ عادی:</b> ${NB_chain(0.5, pick.map(it => it.n / 100), false, nm)}<br>` +
      `<span class="muted">۰٫۵ اول = پیشین (نیمی از ایمیل‌ها اسپم‌اند). هر عددِ بعدی = از هر ۱۰۰ ایمیلِ آن گروه، چندتا این کلمه را داشتند.</span><br>` +
      `شانسِ اسپم = ${NB_share(sp, nm)} <b style="color:var(--green)">${NB_pct(sp / (sp + nm))}</b>`;
  },
});

// ---- Picture 2: Laplace smoothing; "prize" never appeared in normal emails ----
// email: hello, meeting, report, prize. smoothing: (count + 1) / (100 + 2)
const NB_W2 = [
  { w: 'سلام', s: 50, n: 50 },
  { w: 'جلسه', s: 5, n: 30 },
  { w: 'گزارش', s: 4, n: 25 },
  { w: 'جایزه', s: 20, n: 0 },
];
const NB_p = (c, sm) => sm ? (c + 1) / 102 : c / 100;

const NB_W_SMOOTH = h => plane(h, {
  x: [0, 10], y: [0, 7.8], ratio: 0.72,
  state: { sm: false },
  buttons: [
    { label: 'بدون هموارسازی', on: s => { s.sm = false; }, active: s => !s.sm },
    { label: 'با هموارسازی (+۱)', on: s => { s.sm = true; }, active: s => s.sm },
  ],
  draw: (g, s) => {
    const rows = NB_W2.map(it => {
      const a = NB_p(it.s, s.sm), b = NB_p(it.n, s.sm);
      return { w: it.w, a, b, la: fa(a), lb: fa(b), on: true, zero: !b };
    });
    NB_drawRows(g, rows, 0.5, ['شانس در اسپم', 'شانس در عادی']);
    const sp = NB_W2.reduce((m, it) => m * NB_p(it.s, s.sm), 0.5), nm = NB_W2.reduce((m, it) => m * NB_p(it.n, s.sm), 0.5);
    NB_drawFinal(g, sp / (sp + nm));
  },
  read: s => {
    const sp = NB_W2.reduce((m, it) => m * NB_p(it.s, s.sm), 0.5), nm = NB_W2.reduce((m, it) => m * NB_p(it.n, s.sm), 0.5);
    if (!s.sm) return `<b style="color:var(--red)">امتیازِ اسپم:</b> ${NB_chain(0.5, NB_W2.map(it => it.s / 100), false, sp)}<br>` +
      `<b style="color:var(--blue)">امتیازِ عادی:</b> ${NB_chain(0.5, NB_W2.map(it => it.n / 100), true, 0)}<br>` +
      `شانسِ اسپم = <b style="color:var(--red)">۱۰۰٪</b>. یک کلمه‌ی ندیده، «جلسه» و «گزارش» را بی‌اثر کرد.`;
    return `هر شمارش + ۱، هر مخرج + ۲:<br>` +
      `<b style="color:var(--red)">امتیازِ اسپم:</b> ${E(String.raw`0.5 \times ` + NB_W2.map(it => String.raw`\frac{${it.s + 1}}{102}`).join(String.raw` \times `) + ` ${NB_rel(sp)} ${NB_t(sp)}`)}<br>` +
      `<b style="color:var(--blue)">امتیازِ عادی:</b> ${E(String.raw`0.5 \times ` + NB_W2.map(it => String.raw`\frac{${it.n + 1}}{102}`).join(String.raw` \times `) + ` ${NB_rel(nm)} ${NB_t(nm)}`)}<br>` +
      `شانسِ اسپم ${NB_share(sp, nm)} <b style="color:var(--green)">${NB_pct(sp / (sp + nm))}</b>. حالا «جایزه» فقط یک رأیِ قوی است، نه حکمِ قطعی.`;
  },
});

