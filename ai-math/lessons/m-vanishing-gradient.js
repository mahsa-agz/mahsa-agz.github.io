// whole numbers with Persian digits and thousands separators: 1048576 -> ۱٬۰۴۸٬۵۷۶
const MVG_int = n => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, '٬').replace(/\d/g, d => '۰۱۲۳۴۵۶۷۸۹'[d]);

// picture: n layers in a row; the blame that reaches layer k (1 = first, n = next to the error).
// sigmoid: each layer multiplies by at most 0.25 (weights taken as 1) -> layer k gets 0.25^(n − k + 1); layer 1 gets 1 / 4^n
// ReLU: slope 1 while the neuron is on -> every layer gets 1
// residual: y = x + F(x), slope = 1 + slope of F; we draw only the skip path's share (1 × 1 × … = 1)
// checked: n = 10 -> 0.25^10 = 1 / 1,048,576 ≈ 9.5e-7; n = 12 -> 1 / 16,777,216
const MVG_MODES = ['سیگموید', 'ReLU', 'اتصالِ میان‌بر'];
const MVG_val = (s, k) => (s.m === 0 ? 0.25 ** (s.n - k + 1) : 1);

const MVG_W_DEPTH = h => plane(h, {
  x: [0, 13.4], y: [-0.25, 1.4], ratio: 0.66,
  state: { n: 6, m: 0 },
  sliders: [{ key: 'n', label: 'تعداد لایه‌ها (n):', min: 1, max: 12, step: 1 }],
  buttons: MVG_MODES.map((label, i) => ({ label, on: s => { s.m = i; }, active: s => s.m === i })),
  draw: (g, s) => {
    g.line(0.3, 0, 13.1, 0, 'line', 2);
    g.line(0.3, 1, 13.1, 1, 'muted', 1, [4, 4]);
    g.text(13.1, 1, '۱', 'muted', 'right', -9);
    for (let k = 1; k <= s.n; k++) {
      const v = MVG_val(s, k);
      g.rect(k - 0.3, 0, k + 0.3, v, s.m === 2 ? 'accent' : 'green', 0.85);
      if (s.n <= 6 || k === 1 || k === s.n) g.text(k, v, v >= 0.005 ? fa(v) : '≈۰', 'green', 'center', -9);
      g.text(k, 0, fa(k), 'muted', 'center', 12);
    }
    g.text(s.n + 0.75, 0.5, 'خطا', 'red', 'left', 0);
    g.arrow(s.n + 0.5, 1.25, 0.6, 1.25, 'red', 2);
    g.text(Math.max(1.8, (s.n + 1) / 2), 1.25, 'جهتِ پس‌انتشار', 'red', 'center', -11);
  },
  read: s => {
    if (s.m === 1) return `ReLU: وقتی نورون روشن است (عددش مثبت)، شیبش <b>۱</b> است.<br>${E('1 × 1 × … × 1 = 1')}: لایه‌ی ۱ هم <b style="color:var(--green)">تمامِ</b> تقصیر را می‌گیرد.`;
    if (s.m === 2) return `اتصالِ میان‌بر: ${E('y = x + F(x)')}، پس شیبِ هر بلوک «۱ + شیبِ F» است.<br>حتی اگر سهمِ خودِ بلوک‌ها نزدیکِ صفر باشد، راهِ میان‌بر ${E('1 × 1 × … = 1')} را تا لایه‌ی ۱ می‌رساند. میله‌ها فقط همین سهمِ راهِ میان‌بر را نشان می‌دهند.`;
    return `سیگموید: هر لایه تقصیر را حداکثر در <b>۰٫۲۵</b> ضرب می‌کند.<br>لایه‌ی ۱ (اولِ شبکه) می‌گیرد: ${E(`0.25<sup>${s.n}</sup>`)} = ۱ ÷ <b style="color:var(--red)">${MVG_int(4 ** s.n)}</b>` +
      (s.n >= 10 ? '<br>یعنی حدودِ یک‌میلیونیم. وزن‌های اولِ شبکه تقریباً تکان نمی‌خورند.' : '');
  },
});

