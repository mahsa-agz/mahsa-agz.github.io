// ---------- Deep Learning: Convolutional Neural Network ----------
// (names start with CNN_ because all lesson files share one global scope)

const CNN_clamp = (v, a, b) => Math.max(a, Math.min(b, v));
const CNN_SPAN = (c, t) => `<span style="color:var(--${c})">${t}</span>`;

// the 8×8 picture: a filled rectangle (1 = colored, 0 = empty), rows 1–6, columns 2–5
const CNN_IMG = ['00000000', '00111100', '00111100', '00111100', '00111100', '00111100', '00111100', '00000000']
  .map(r => r.split('').map(Number));

const CNN_K = {
  v: { name: 'لبه‌ی عمودی', k: [[-1, 0, 1], [-1, 0, 1], [-1, 0, 1]] },
  h: { name: 'لبه‌ی افقی', k: [[-1, -1, -1], [0, 0, 0], [1, 1, 1]] },
  b: { name: 'محو کردن', k: [[1, 1, 1], [1, 1, 1], [1, 1, 1]].map(r => r.map(x => x / 9)) },
};

// slide a 3×3 kernel over the image (no padding): 8 − 3 + 1 = 6, so a 6×6 map
const CNN_conv = (img, k) => {
  const n = img.length - 2, out = [];
  for (let i = 0; i < n; i++) {
    out.push([]);
    for (let j = 0; j < n; j++) {
      let s = 0;
      for (let a = 0; a < 3; a++) for (let b = 0; b < 3; b++) s += img[i + a][j + b] * k[a][b];
      out[i].push(Math.round(s * 1e9) / 1e9);
    }
  }
  return out;
};
const CNN_reluMap = m => m.map(r => r.map(v => Math.max(0, v)));
// max of each 2×2 block: 6×6 → 3×3
const CNN_pool = m => [0, 1, 2].map(bi => [0, 1, 2].map(bj =>
  Math.max(m[2 * bi][2 * bj], m[2 * bi][2 * bj + 1], m[2 * bi + 1][2 * bj], m[2 * bi + 1][2 * bj + 1])));

// ---- drawing helpers (one unit = one cell; (x0, top) = top-left corner of the grid) ----
const CNN_cell = g => g.X(1) - g.X(0);
const CNN_box = (g, x, top, w, h, color, lw) => {
  const c = g.ctx; c.strokeStyle = g.css(color); c.lineWidth = lw; c.setLineDash([]);
  c.strokeRect(g.X(x), g.Y(top), g.X(x + w) - g.X(x), g.Y(top - h) - g.Y(top));
};
const CNN_gridLines = (g, x0, top, n) => {
  const c = g.ctx; c.strokeStyle = g.css('line'); c.lineWidth = 1; c.setLineDash([]); c.beginPath();
  for (let t = 0; t <= n; t++) {
    c.moveTo(g.X(x0 + t), g.Y(top)); c.lineTo(g.X(x0 + t), g.Y(top - n));
    c.moveTo(g.X(x0), g.Y(top - t)); c.lineTo(g.X(x0 + n), g.Y(top - t));
  }
  c.stroke();
};
// the image: colored cells in blue
const CNN_drawImg = (g, x0, top) => {
  CNN_IMG.forEach((r, i) => r.forEach((v, j) => { if (v) g.rect(x0 + j, top - i, x0 + j + 1, top - i - 1, 'blue', 0.75); }));
  CNN_gridLines(g, x0, top, 8);
};
// a map of numbers: green = positive, red = negative, stronger = bigger; the number written inside
const CNN_drawMap = (g, x0, top, m, big) => {
  const c = g.ctx, cs = CNN_cell(g);
  m.forEach((r, i) => r.forEach((v, j) => {
    if (v) g.rect(x0 + j, top - i, x0 + j + 1, top - i - 1, v > 0 ? 'green' : 'red', 0.15 + 0.6 * Math.min(1, Math.abs(v) / big));
    c.font = `600 ${Math.max(9, Math.round(cs * 0.46))}px Vazirmatn, Tahoma, sans-serif`;
    c.fillStyle = g.css(v ? 'ink' : 'muted'); c.textAlign = 'center'; c.textBaseline = 'middle';
    c.fillText(fa(Math.round(v * 10) / 10), g.X(x0 + j + 0.5), g.Y(top - i - 0.5));
  }));
  CNN_gridLines(g, x0, top, m.length);
};
const CNN_big = m => Math.max(1e-9, ...m.flat().map(Math.abs));
// a small matrix as LaTeX (Latin digits)
const CNN_MATSTR = m => String.raw`\begin{bmatrix} ${m.map(r => r.map(v => String(Math.round(v * 100) / 100)).join(' & ')).join(' \\\\ ')} \end{bmatrix}`;
// the same matrix drawn by MathJax, in one color
const CNN_TABLE = (m, color) => `<span style="color:var(--${color});display:inline-block;margin:4px 6px">${E(CNN_MATSTR(m))}</span>`;

// ---- Picture 1: slide a 3×3 filter over the 8×8 image ----
const CNN_W_CONV = h => plane(h, {
  x: [-0.55, 15.55], y: [-0.3, 8.9], equal: true,
  state: { f: 'v', i: 1, j: 0 },
  handles: [{ get: s => [s.j + 1.5, 6.5 - s.i], set: (s, x, y) => { s.j = CNN_clamp(Math.round(x - 1.5), 0, 5); s.i = CNN_clamp(Math.round(6.5 - y), 0, 5); }, color: 'orange' }],
  buttons: [
    ...['v', 'h', 'b'].map(k => ({ label: CNN_K[k].name, on: s => { s.f = k; }, active: s => s.f === k })),
    { label: 'یک خانه جلو', on: s => { if (++s.j > 5) { s.j = 0; s.i = (s.i + 1) % 6; } } },
  ],
  draw: (g, s) => {
    const m = CNN_conv(CNN_IMG, CNN_K[s.f].k);
    CNN_drawImg(g, 0, 8);
    CNN_drawMap(g, 9, 7, m, CNN_big(m));
    CNN_box(g, s.j, 8 - s.i, 3, 3, 'orange', 3);
    CNN_box(g, 9 + s.j, 7 - s.i, 1, 1, 'orange', 3);
    g.text(4, 8.45, `عکس ${fa(8)} × ${fa(8)}`, 'muted', 'center', 0);
    g.text(12, 7.45, `نقشه‌ی ویژگی ${fa(6)} × ${fa(6)}`, 'muted', 'center', 0);
  },
  read: s => {
    const K = CNN_K[s.f].k, P = [0, 1, 2].map(a => [0, 1, 2].map(b => CNN_IMG[s.i + a][s.j + b]));
    const v = CNN_conv(CNN_IMG, K)[s.i][s.j];
    let calc;
    if (s.f === 'b') {
      const n = P.flat().reduce((x, y) => x + y, 0);
      calc = `میانگینِ ۹ خانه: ${E(String.raw`\frac{${n}}{9} \approx ${Math.round(v * 100) / 100}`)}`;
    } else {
      const terms = [];
      P.forEach((r, a) => r.forEach((p, b) => { if (p && K[a][b]) terms.push(K[a][b] > 0 ? '+1' : '-1'); }));
      calc = `هر خانه ضرب در خانه‌ی فیلتر، بعد جمع. حاصل‌ضرب‌های غیرصفر: ${E(terms.length ? `${terms.join(' ')} = ${v}` : `\\text{none} = 0`)} ← <b style="color:var(--${v > 0 ? 'green' : v < 0 ? 'red' : 'ink'})">${fa(v)}</b>`;
    }
    const note = s.f === 'b' ? 'محو کردن: هر خانه میانگینِ ۹ همسایه‌اش می‌شود؛ مرزها نرم می‌شوند.'
      : v === 0 ? (P.flat().every(x => x === P[0][0]) ? 'زیرِ فیلتر همه‌جا یکسان است: لبه‌ای نیست، پس ۰.' : 'تکه‌ی زیرِ فیلتر با این الگو جور نیست، پس ۰.')
      : 'اینجا یک لبه است، پس عدد بزرگ است.';
    return `ردیف ${fa(s.i + 1)}، ستون ${fa(s.j + 1)} · فیلتر «${CNN_K[s.f].name}»<br>` +
      `زیرِ فیلتر: ${E(CNN_MATSTR(P))}<br>${calc}<br>${note}`;
  },
});

// ---- Picture 2: max pooling on the feature map, with or without ReLU first ----
const CNN_W_POOL = h => plane(h, {
  x: [-0.5, 11.5], y: [-0.3, 7], equal: true,
  state: { f: 'v', relu: true, p: 0 },
  buttons: [
    ...['v', 'h'].map(k => ({ label: CNN_K[k].name, on: s => { s.f = k; }, active: s => s.f === k })),
    { label: 'ReLU اول', on: s => { s.relu = !s.relu; }, active: s => s.relu },
    { label: 'پنجره‌ی بعد', on: s => { s.p = (s.p + 1) % 9; } },
  ],
  draw: (g, s) => {
    const raw = CNN_conv(CNN_IMG, CNN_K[s.f].k), m = s.relu ? CNN_reluMap(raw) : raw, big = CNN_big(raw);
    const bi = Math.floor(s.p / 3), bj = s.p % 3;
    CNN_drawMap(g, 0, 6, m, big);
    CNN_drawMap(g, 8, 4.5, CNN_pool(m), big);
    const c = g.ctx; c.strokeStyle = g.css('ink'); c.lineWidth = 2; c.setLineDash([]); c.beginPath();
    [2, 4].forEach(t => { c.moveTo(g.X(t), g.Y(6)); c.lineTo(g.X(t), g.Y(0)); c.moveTo(g.X(0), g.Y(6 - t)); c.lineTo(g.X(6), g.Y(6 - t)); });
    c.stroke();
    CNN_box(g, 2 * bj, 6 - 2 * bi, 2, 2, 'orange', 3);
    CNN_box(g, 8 + bj, 4.5 - bi, 1, 1, 'orange', 3);
    g.text(3, 6.45, `نقشه ${fa(6)} × ${fa(6)}`, 'muted', 'center', 0);
    g.text(9.5, 4.95, `${fa(3)} × ${fa(3)}`, 'muted', 'center', 0);
  },
  read: s => {
    const raw = CNN_conv(CNN_IMG, CNN_K[s.f].k), m = s.relu ? CNN_reluMap(raw) : raw;
    const bi = Math.floor(s.p / 3), bj = s.p % 3;
    const w = [m[2 * bi][2 * bj], m[2 * bi][2 * bj + 1], m[2 * bi + 1][2 * bj], m[2 * bi + 1][2 * bj + 1]];
    const mx = Math.max(...w);
    const note = s.relu ? 'با ReLU منفی‌ها صفر شده‌اند: نقشه فقط می‌گوید «الگو اینجا هست» (مثبت) یا «نیست» (۰).'
      : mx < 0 ? 'بدونِ ReLU، عددِ منفی هم بیشینه شده و به لایه‌ی بعد می‌رود. معمولاً اول ReLU می‌زنند، بعد ادغام.'
      : 'بدونِ ReLU، منفی‌ها هم در نقشه می‌مانند. «ReLU اول» را بزنید و فرقش را ببینید.';
    return `پنجره‌ی ${fa(s.p + 1)} از ۹، بزرگ‌ترینِ ۴ خانه: ${E(String.raw`\max(${w.join(', ')}) = ${mx}`)}<br>` +
      `۳۶ عدد ← ۹ عدد؛ ولی جای لبه‌ها هنوز پیداست.<br>${note}`;
  },
});

