// ---------- How Models Learn: Overfitting ----------
// (names start with OVER_ because all lesson files share one global scope)

// 10 training points and 10 new points from the gentle hill 1 + 1.2x − 0.12x², plus fixed noise, rounded to 0.1.
// Polynomials of degree 1…9 are fitted to the training points by least squares (normal equations),
// with x scaled to u = (x − 5) / 5 in [−0.9, 0.9] so the numbers stay stable.
// Results (MSE; shown to 2 decimals in the lesson):  degree: train / new
//   1: 0.692 / 1.005   2: 0.135 / 0.224   3: 0.133 / 0.230   4: 0.127 / 0.281   5: 0.100 / 0.294
//   6: 0.069 / 0.377   7: 0.051 / 0.403   8: 0.004 / 0.585   9: 0.000 / 1.099   (new-data error lowest at degree 2)
const OVER_XT = [0.5, 1.5, 2.5, 3.5, 4.5, 5.5, 6.5, 7.5, 8.5, 9.5];
const OVER_YT = [1.7, 2.8, 3.6, 3.8, 3.3, 3.5, 4.4, 2.9, 2.3, 1.8];
const OVER_XN = [1, 2, 3, 4, 5, 5.5, 6, 7, 8, 9];
const OVER_YN = [2.3, 2.4, 3.6, 4.5, 3.8, 4.5, 4.6, 3.2, 2.6, 2];
const OVER_u = x => (x - 5) / 5;

// least squares: solve (AᵀA) w = Aᵀy by Gauss–Jordan elimination with partial pivoting
const OVER_fit = d => {
  const n = d + 1, A = [...Array(n)].map(() => Array(n + 1).fill(0));
  OVER_XT.forEach((x, k) => {
    const p = []; let t = 1;
    for (let i = 0; i < n; i++) { p.push(t); t *= OVER_u(x); }
    for (let i = 0; i < n; i++) { for (let j = 0; j < n; j++) A[i][j] += p[i] * p[j]; A[i][n] += p[i] * OVER_YT[k]; }
  });
  for (let c = 0; c < n; c++) {
    let m = c;
    for (let r = c + 1; r < n; r++) if (Math.abs(A[r][c]) > Math.abs(A[m][c])) m = r;
    [A[c], A[m]] = [A[m], A[c]];
    for (let r = 0; r < n; r++) if (r !== c) { const q = A[r][c] / A[c][c]; for (let j = c; j <= n; j++) A[r][j] -= q * A[c][j]; }
  }
  return A.map((r, i) => r[n] / r[i]);
};
const OVER_ev = (w, x) => { let s = 0, t = 1; for (const c of w) { s += c * t; t *= OVER_u(x); } return s; };
const OVER_mse = (w, xs, ys) => xs.reduce((s, x, i) => s + (ys[i] - OVER_ev(w, x)) ** 2, 0) / xs.length;
const OVER_W = [null], OVER_TR = [null], OVER_TE = [null];
for (let d = 1; d <= 9; d++) { const w = OVER_fit(d); OVER_W.push(w); OVER_TR.push(OVER_mse(w, OVER_XT, OVER_YT)); OVER_TE.push(OVER_mse(w, OVER_XN, OVER_YN)); }
const OVER_f3 = v => v.toFixed(2).replace('-', '−').replace('.', '٫').replace(/\d/g, d => '۰۱۲۳۴۵۶۷۸۹'[d]);
const OVER_say = d => d === 1 ? '<b>کم‌برازش</b>: خط صاف خمِ داده را نمی‌گیرد.'
  : d <= 3 ? '<b style="color:var(--green)">برازش خوب</b>: شکلِ کلی را گرفته، نه سروصدا را.'
  : d <= 7 ? 'کم‌کم دارد سروصدای نقطه‌ها را هم یاد می‌گیرد.'
  : '<b style="color:var(--red)">بیش‌برازش</b>: از روی همه‌ی نقطه‌ها رد می‌شود و وسطشان پیچ و تاب می‌خورد.';

// picture 1: degree slider; the curve with the smallest training MSE; a button reveals the new points
const W_OVER_FIT = h => plane(h, {
  x: [-0.3, 10.3], y: [-0.3, 6.3], step: [1, 1], labels: true, ratio: 0.75,
  state: { d: 1, show: false },
  sliders: [{ key: 'd', label: 'پیچیدگی مدل (درجه):', min: 1, max: 9, step: 1 }],
  buttons: [{ label: 'داده‌ی تازه را نشان بده', on: s => { s.show = !s.show; }, active: s => s.show }],
  draw: (g, s) => {
    g.grid();
    const w = OVER_W[s.d];
    if (s.show) OVER_XN.forEach((x, i) => g.line(x, OVER_YN[i], x, OVER_ev(w, x), 'red', 3));
    g.fn(x => OVER_ev(w, x), 'orange', 3, 0.5, 9.5);
    OVER_XT.forEach((x, i) => g.dot(x, OVER_YT[i], 'blue', 7));
    if (s.show) OVER_XN.forEach((x, i) => g.dot(x, OVER_YN[i], 'ink', 6));
  },
  read: s => `درجه‌ی ${fa(s.d)} = ${fa(s.d + 1)} پیچِ تنظیم<br>` +
    `خطای آموزش (MSE روی نقطه‌های <b style="color:var(--blue)">آبی</b>) = <b style="color:var(--blue)">${OVER_f3(OVER_TR[s.d])}</b><br>` +
    `خطای داده‌ی تازه (نقطه‌های سیاه) = ${s.show ? `<b style="color:var(--red)">${OVER_f3(OVER_TE[s.d])}</b>` : '؟ (دکمه را بزنید)'}<br>${OVER_say(s.d)}`,
});

// picture 2: training error and new-data error against degree; a draggable marker picks the degree
