const FE_CITIES = ['تهران', 'تبریز', 'شیراز'];
const FE_W_ONEHOT = h => {
  const rows = [];
  const btns = document.createElement('div');
  btns.className = 'btns';
  const box = document.createElement('div');
  box.style.cssText = 'max-width:360px;margin:10px auto;overflow-x:hidden';
  const read = document.createElement('div');
  read.className = 'read';
  const td = (x, css = '') => `<td style="padding:4px 3px;border-bottom:1px solid var(--soft);${css}">${x}</td>`;
  const draw = () => {
    const head = `<tr>${td('<b>شهر</b>')}${FE_CITIES.map(c => td(`<b style="color:var(--blue)">${c}؟</b>`)).join('')}${td('<b style="color:var(--red)">کد ۱،۲،۳</b>')}</tr>`;
    const body = rows.length ? rows.map(i => `<tr>${td(FE_CITIES[i])}${FE_CITIES.map((c, j) => i === j
      ? td('<b>۱</b>', 'color:var(--green);background:color-mix(in srgb, var(--green) 18%, var(--card))')
      : td('۰', 'color:var(--muted)')).join('')}${td(fa(i + 1), 'color:var(--red)')}</tr>`).join('')
      : '<tr><td colspan="5" style="padding:8px"><span class="muted">هنوز ردیفی نیست؛ یک دکمه بزنید.</span></td></tr>';
    box.innerHTML = `<table dir="rtl" style="border-collapse:collapse;width:100%;table-layout:fixed;margin:0 auto;text-align:center;font-size:13px">${head}${body}</table>`;
    if (!rows.length) { read.innerHTML = 'هر دکمه یک ردیف (یک مشتری) با آن شهر اضافه می‌کند.'; return; }
    const last = rows[rows.length - 1], v = FE_CITIES.map((c, j) => (j === last ? 1 : 0));
    read.innerHTML = `ردیفِ آخر: ${FE_CITIES[last]} ← ${N(`[${v.join(', ')}]`)}؛ در هر ردیف دقیقاً <b>یک</b> خانه ۱ است.<br>` +
      `<span style="color:var(--red)">کدِ ساده</span> می‌گوید شیراز (۳) «بزرگ‌تر» از تهران (۱) است و تبریز درست وسطشان؛ این ترتیب دروغ است. در one-hot فاصله‌ی هر دو شهرِ متفاوت یکی است: ${E(String.raw`\sqrt{1^2 + 1^2} = \sqrt{2}`)}.`;
  };
  FE_CITIES.forEach((c, i) => {
    const b = document.createElement('button');
    b.textContent = '+ ' + c;
    b.onclick = () => { rows.push(i); if (rows.length > 6) rows.shift(); draw(); };
    btns.appendChild(b);
  });
  const clr = document.createElement('button');
  clr.textContent = 'پاک کردن';
  clr.onclick = () => { rows.length = 0; draw(); };
  btns.appendChild(clr);
  h.append(btns, box, read);
  draw();
  return () => {};
};

