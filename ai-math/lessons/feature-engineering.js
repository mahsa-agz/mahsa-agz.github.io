// ---- Picture 1: two features with very different ranges; raw / standardized / min-max ----
// 8 known houses [size m², rooms] (the "training" data) and one new house (red).
// The scaler is fitted on the 8 houses only. Both axes use the SAME scale on the canvas, so distances are honest.
// Checked in node: raw → nearest = 100 m², 3 rooms, size makes 96% of the squared distance;
// z-score and min-max → nearest = 160 m², 4 rooms, size makes about 49% / 50%.
const FE_HOUSES = [[50, 1], [80, 2], [100, 3], [130, 3], [160, 4], [200, 5], [250, 5], [300, 6]];
const FE_NEW = [110, 5];
const FE_MODES = { raw: 'خام', z: 'استانداردسازی (z)', mm: 'کمینه–بیشینه' };
const FE_FIT = mode => [0, 1].map(j => {
  const a = FE_HOUSES.map(h => h[j]);
  if (mode === 'z') return [ST.mean(a), ST.std(a)];
  if (mode === 'mm') { const lo = Math.min(...a); return [lo, Math.max(...a) - lo]; }
  return [0, 1];
});
const FE_SCALE = mode => {
  const f = FE_FIT(mode), t = p => p.map((v, j) => (v - f[j][0]) / f[j][1]);
  const T = FE_HOUSES.map(t), n = t(FE_NEW);
  let best = 0, bd = Infinity;
  T.forEach((p, i) => { const d = (p[0] - n[0]) ** 2 + (p[1] - n[1]) ** 2; if (d < bd) { bd = d; best = i; } });
  const all = [...T, n], lo = [0, 1].map(j => Math.min(...all.map(p => p[j]))), hi = [0, 1].map(j => Math.max(...all.map(p => p[j])));
  return { T, n, best, share: (T[best][0] - n[0]) ** 2 / bd, lo, hi,
    rng: [0, 1].map(j => [Math.min(...T.map(p => p[j])), Math.max(...T.map(p => p[j]))]) };
};

const FE_W_SCALE = h => plane(h, {
  x: [0, 10], y: [0, 7], equal: true,
  state: { mode: 'raw' },
  buttons: Object.keys(FE_MODES).map(m => ({ label: FE_MODES[m], on: s => { s.mode = m; }, active: s => s.mode === m })),
  draw: (g, s) => {
    const c = FE_SCALE(s.mode);
    const k = Math.min(8.6 / (c.hi[0] - c.lo[0]), 5.6 / (c.hi[1] - c.lo[1]));   // one scale for both axes
    const P = p => [0.8 + (p[0] - c.lo[0]) * k, 0.8 + (p[1] - c.lo[1]) * k];
    g.arrow(0.4, 0.4, 9.8, 0.4, 'line', 2); g.arrow(0.4, 0.4, 0.4, 6.9, 'line', 2);
    g.text(9.7, 0.4, 'متراژ', 'muted', 'right', 14);
    g.text(0.6, 6.7, 'اتاق', 'muted', 'left', 0);
    const [nx, ny] = P(c.n), [bx, by] = P(c.T[c.best]);
    g.line(nx, ny, bx, by, 'green', 3, [6, 5]);
    c.T.forEach(p => { const [x, y] = P(p); g.dot(x, y, 'blue', 6); });
    g.dot(bx, by, 'green', 8);
    g.dot(nx, ny, 'red', 8);
    g.text(nx, ny, 'خانه‌ی نو', 'red', 'center', -16);
  },
  read: s => {
    const c = FE_SCALE(s.mode), b = FE_HOUSES[c.best];
    return `بازه‌ها: متراژ از <b>${fa(c.rng[0][0])}</b> تا <b>${fa(c.rng[0][1])}</b> · اتاق از <b>${fa(c.rng[1][0])}</b> تا <b>${fa(c.rng[1][1])}</b><br>` +
      `<b style="color:var(--green)">شبیه‌ترین خانه</b> به خانه‌ی نو (${fa(FE_NEW[0])} متر، ${fa(FE_NEW[1])} اتاق): <b>${fa(b[0])} متر، ${fa(b[1])} اتاق</b><br>` +
      `سهمِ فرقِ متراژ در این فاصله (با مجذورها): <b>${fa(Math.round(c.share * 100))}٪</b>` +
      (s.mode === 'raw' ? ' <span class="muted">؛ تعدادِ اتاق تقریباً دیده نمی‌شود.</span>' : ' <span class="muted">؛ حالا هر دو ستون حرف می‌زنند.</span>');
  },
});

