// ---------- How Models Learn: Bias–Variance ----------
// (names start with BV_ because all lesson files share one global scope)
// model variance = variance of the predictions of models retrained on different samples (divides by n, like ST.variance)

// small seeded random generator so every picture is the same each time
const BV_rng = seed => () => { seed |= 0; seed = seed + 0x6D2B79F5 | 0; let t = Math.imul(seed ^ seed >>> 15, 1 | seed); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; };
const BV_gauss = r => Math.sqrt(-2 * Math.log(1 - r())) * Math.cos(2 * Math.PI * r());
// two decimals; says «حدود» when the value was rounded
const BV_n = v => String(Math.round(v * 10000) / 10000); // Latin digits, for inside LaTeX
const BV_fa2 = v => { const r = Math.round(v * 100) / 100; return (Math.abs(r - v) > 1e-9 ? 'حدود ' : '') + fa(r); };

// ----- picture 1: a target. 20 fixed shot offsets, centred (mean 0) and scaled so their mean squared distance is 1 -----
const BV_OFF = (() => {
  const r = BV_rng(7), p = Array.from({ length: 20 }, () => [BV_gauss(r), BV_gauss(r)]);
  const mx = ST.mean(p.map(q => q[0])), my = ST.mean(p.map(q => q[1]));
  const c = p.map(([x, y]) => [x - mx, y - my]);
  const rms = Math.sqrt(ST.mean(c.map(([x, y]) => x * x + y * y)));
  return c.map(([x, y]) => [x / rms, y / rms]);
})();
const BV_DIR = Math.SQRT1_2; // the bias pushes the shots up and to the right
const BV_shots = s => BV_OFF.map(([x, y]) => [s.b * BV_DIR + s.v * x, s.b * BV_DIR + s.v * y]);
const BV_ARCHERS = [['کج ولی ثابت', 2, 0.25], ['دقیق ولی لرزان', 0, 1.25], ['کج و لرزان', 2, 1.25], ['دقیق و ثابت', 0, 0.25]];

const W_BV_TARGET = h => plane(h, {
  x: [-4, 4], y: [-4, 4], equal: true,
  state: { b: 2, v: 0.25 },
  sliders: [{ key: 'b', label: 'سوگیری:', min: 0, max: 3, step: 0.5 }, { key: 'v', label: 'پراکندگی:', min: 0, max: 1.5, step: 0.25 }],
  buttons: BV_ARCHERS.map(([label, b, v]) => ({ label, on: s => { s.b = b; s.v = v; }, active: s => s.b === b && s.v === v })),
  draw: (g, s) => {
    const c = g.ctx, u = g.X(1) - g.X(0);
    [3.6, 2.7, 1.8, 0.9].forEach(r => { c.beginPath(); c.arc(g.X(0), g.Y(0), r * u, 0, 7); c.strokeStyle = g.css('line'); c.lineWidth = 2; c.stroke(); });
    g.dot(0, 0, 'red', 7);
    BV_shots(s).forEach(([x, y]) => g.dot(x, y, 'orange', 5));
    const cx = s.b * BV_DIR;
    if (s.b) g.line(0, 0, cx, cx, 'red', 2, [5, 4]);
    g.dot(cx, cx, 'green', 6);
  },
  read: s => {
    const p = BV_shots(s), cx = ST.mean(p.map(q => q[0])), cy = ST.mean(p.map(q => q[1]));
    const bias = Math.hypot(cx, cy), vr = ST.mean(p.map(([x, y]) => (x - cx) ** 2 + (y - cy) ** 2)), tot = ST.mean(p.map(([x, y]) => x * x + y * y));
    return `<b style="color:var(--red)">سوگیری</b> (فاصله‌ی مرکزِ سبز تا خال) = <b>${BV_fa2(bias)}</b><br>` +
      `<b style="color:var(--orange)">واریانس</b> (میانگینِ فاصله‌ی به توان ۲ هر تیر تا مرکزِ سبز) = <b>${BV_fa2(vr)}</b><br>` +
      `خطای کل (میانگینِ فاصله‌ی به توان ۲ تیرها تا خال) = <b>${BV_fa2(tot)}</b><br>` +
      `<span class="muted">دقیقاً برابر با سوگیری² + واریانس: ${E(String.raw`${BV_n(bias)}^2 + ${BV_n(vr)} = ${BV_n(tot)}`)}</span>`;
  },
});

// ----- picture 2: 5 random samples of a curved dataset, the same model type fitted to each -----
const BV_TRUE = x => Math.cos(Math.PI * x) + 0.5 * x;
const BV_NOISE = 0.5, BV_N = 12, BV_R = 0.8; // noise σ, points per sample, readout region −0.8…0.8
const BV_SAMPLES = [11, 22, 33, 44, 55].map(seed => {
  const r = BV_rng(seed);
  return Array.from({ length: BV_N }, (_, i) => { const x = -1 + (i + r()) * 2 / BV_N; return [x, BV_TRUE(x) + BV_NOISE * BV_gauss(r)]; });
});
// least squares polynomial of degree d (normal equations + Gaussian elimination with pivoting); x already in [−1, 1]
const BV_fit = (pts, d) => {
  const n = d + 1, A = Array.from({ length: n }, () => Array(n + 1).fill(0));
  pts.forEach(([x, y]) => { for (let i = 0; i < n; i++) { for (let j = 0; j < n; j++) A[i][j] += x ** (i + j); A[i][n] += y * x ** i; } });
  for (let c = 0; c < n; c++) {
    let p = c;
    for (let r = c + 1; r < n; r++) if (Math.abs(A[r][c]) > Math.abs(A[p][c])) p = r;
    [A[c], A[p]] = [A[p], A[c]];
    for (let r = 0; r < n; r++) if (r !== c) { const f = A[r][c] / A[c][c]; for (let k = c; k <= n; k++) A[r][k] -= f * A[c][k]; }
  }
  const w = A.map((row, i) => row[n] / row[i]);
  return x => w.reduce((s, wi, i) => s + wi * x ** i, 0);
};
const BV_FITS = {};
const BV_fits = d => BV_FITS[d] || (BV_FITS[d] = BV_SAMPLES.map(p => BV_fit(p, d)));
const BV_avg = d => x => ST.mean(BV_fits(d).map(f => f(x)));
// bias² and variance at each x of the range −0.8…0.8, then averaged over it
const BV_parts = d => {
  let b = 0, v = 0;
  for (let i = 0; i <= 40; i++) {
    const x = -BV_R + 2 * BV_R * i / 40, p = BV_fits(d).map(f => f(x));
    b += (ST.mean(p) - BV_TRUE(x)) ** 2 / 41; v += ST.variance(p) / 41;
  }
  return [b, v];
};
const BV_BEST = (() => { let k = 1; for (let d = 2; d <= 9; d++) { const [b, v] = BV_parts(d), [bk, vk] = BV_parts(k); if (b + v < bk + vk) k = d; } return k; })();

const W_BV_FIT = h => plane(h, {
  x: [-1.05, 1.05], y: [-2.2, 2.2], ratio: 0.8,
  state: { d: 1 },
  sliders: [{ key: 'd', label: 'پیچیدگی (درجه):', min: 1, max: 9, step: 1 }],
  draw: (g, s) => {
    g.line(-1.05, 0, 1.05, 0, 'line', 1);
    [-BV_R, BV_R].forEach(x => g.line(x, -2.2, x, 2.2, 'muted', 1, [4, 4]));
    g.ctx.globalAlpha = 0.5;
    BV_SAMPLES.forEach(p => p.forEach(([x, y]) => g.dot(x, y, 'blue', 2.5)));
    g.ctx.globalAlpha = 1;
    BV_fits(s.d).forEach(f => g.fn(f, 'orange', 1.5, -1, 1));
    for (let i = 0; i < 60; i += 2) g.line(-1 + i / 30, BV_TRUE(-1 + i / 30), -1 + (i + 1) / 30, BV_TRUE(-1 + (i + 1) / 30), 'ink', 2.5); // dashed true curve
    g.fn(BV_avg(s.d), 'green', 3.5, -1, 1);
  },
  read: s => {
    const [b, v] = BV_parts(s.d);
    const note = s.d === BV_BEST ? 'این‌جا جمع از همه کمتر است: بهترین تعادل.' : b > v ? 'سوگیری سهمِ بیشتری دارد: مدل زیادی ساده است.' : s.d >= 7 ? 'واریانس غالب است: منحنی‌ها از هم دور شده‌اند.' : 'واریانس کم‌کم بیشتر می‌شود.';
    return `درجه‌ی ${fa(s.d)}؛ میانگین روی بازه‌ی x از ${fa(-BV_R)} تا ${fa(BV_R)} (بین دو خطِ عمودی):<br>` +
      `<b style="color:var(--red)">سوگیری²</b> = ${BV_fa2(b)} &nbsp;|&nbsp; <b style="color:var(--orange)">واریانس</b> = ${BV_fa2(v)} &nbsp;|&nbsp; جمع = <b>${BV_fa2(b + v)}</b><br>` +
      `<span class="muted">به‌علاوه‌ی سروصدای ثابتِ ${fa(BV_NOISE ** 2)}.</span> ${note}`;
  },
});

