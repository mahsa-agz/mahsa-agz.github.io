// ---- Picture 1: throw a coin (count heads) or a die (count sixes); plot the running share ----
const PROB_RATE = 60;      // throws per second when animating 10 / 100 throws
const PROB_MAX = 20000;    // stop counting after this many throws
const PROB_reset = (s, die) => { s.die = die; s.n = 0; s.hits = 0; s.hist = []; s.pending = 0; s.clock = 0; s.last = null; };
const PROB_throw = s => {
  if (s.n >= PROB_MAX) return;
  const r = s.die ? 1 + Math.floor(Math.random() * 6) : (Math.random() < 0.5 ? 'شیر' : 'خط');
  s.last = r; s.n++;
  if (s.die ? r === 6 : r === 'شیر') s.hits++;
  s.hist.push(s.hits / s.n);
};

const W_PROB_THROW = h => {
  const st = {};
  PROB_reset(st, false);
  return plane(h, {
    x: [-1.5, 10.4], y: [-0.2, 1.08], ratio: 0.75,
    state: st,
    buttons: [
      { label: 'سکه', on: s => PROB_reset(s, false), active: s => !s.die },
      { label: 'تاس', on: s => PROB_reset(s, true), active: s => s.die },
      { label: '۱۰ پرتاب', on: s => { s.pending += 10; } },
      { label: '۱۰۰۰ پرتاب', on: s => { for (let i = 0; i < 1000; i++) PROB_throw(s); } },
    ],
    tick: (s, dt) => {
      if (s.pending > 0) {
        s.clock += dt;
        while (s.clock >= 1 / PROB_RATE && s.pending > 0) { PROB_throw(s); s.pending--; s.clock -= 1 / PROB_RATE; }
      } else s.clock = 0;
    },
    draw: (g, s) => {
      const N = Math.max(10, s.n), p = s.die ? 1 / 6 : 0.5, c = g.ctx;
      // horizontal guide lines with share labels
      [0, 0.25, 0.5, 0.75, 1].forEach(y => { g.line(0, y, 10, y, y ? 'soft' : 'line', y ? 1 : 2); g.text(-0.2, y, fa(y), 'muted', 'right', 0); });
      g.line(0, 0, 0, 1.02, 'line', 2);
      g.text(0, 0, '۰', 'muted', 'center', 13);
      g.text(10, 0, fa(N), 'muted', 'right', 13);
      g.text(5, 0, 'تعداد پرتاب', 'muted', 'center', 13);
      // the true probability (dashed)
      g.line(0, p, 10, p, 'orange', 2.5, [8, 6]);
      // running share after each throw (at most ~600 points drawn)
      if (s.n) {
        const step = Math.max(1, Math.floor(s.n / 600));
        c.strokeStyle = g.css('blue'); c.lineWidth = 2.5; c.setLineDash([]); c.lineJoin = 'round';
        c.beginPath();
        for (let i = 0; i < s.n; i += step) { const x = g.X(10 * (i + 1) / N), y = g.Y(s.hist[i]); i ? c.lineTo(x, y) : c.moveTo(x, y); }
        c.lineTo(g.X(10 * s.n / N), g.Y(s.hist[s.n - 1]));
        c.stroke();
        g.dot(10 * s.n / N, s.hist[s.n - 1], 'blue', 5);
      }
    },
    read: s => {
      const name = s.die ? '۶' : 'شیر', p = s.die ? 1 / 6 : 0.5;
      const head = s.die ? `تاس: «۶» را می‌شماریم. احتمالِ واقعی: ${E(String.raw`\frac{1}{6} \approx 0.17`)}.<br>` : 'سکه: «شیر» را می‌شماریم. احتمالِ واقعی: ۰٫۵.<br>';
      if (!s.n) return head + (s.pending ? 'در حالِ پرتاب...' : 'هنوز پرتابی نشده. «۱۰ پرتاب» را بزنید.');
      const share = s.hits / s.n;
      return head + `آخرین پرتاب: <b>${s.die ? fa(s.last) : s.last}</b>. تا حالا <b>${fa(s.n)}</b> پرتاب، <b>${fa(s.hits)}</b> بار «${name}».<br>` +
        `سهمِ دیده‌شده = ${fa(s.hits)} ÷ ${fa(s.n)} ≈ <b style="color:var(--blue)">${fa(share)}</b>؛ یعنی حدودِ ${fa(Math.round(share * 100))} بار از هر ۱۰۰ پرتاب. فاصله تا احتمالِ واقعی: ${fa(Math.abs(share - p))}.` +
        (s.n >= PROB_MAX ? '<br>به سقفِ ۲۰٬۰۰۰ پرتاب رسیدیم.' : '') +
        (s.n >= 1000 ? '<br><span class="muted">اولش آبی بالا و پایین می‌پرید؛ حالا نزدیکِ نقطه‌چینِ نارنجی آرام گرفته.</span>' : '');
    },
  });
};

