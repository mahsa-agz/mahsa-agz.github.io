const W_PROB_GRID = h => plane(h, {
  x: [-1.1, 6.3], y: [-1.2, 6.9], equal: true,
  state: { ev: 0 },
  buttons: PROB_EVENTS.map((e, k) => ({ label: e.label, on: s => { s.ev = k; }, active: s => s.ev === k })),
  draw: (g, s) => {
    const ev = PROB_EVENTS[s.ev];
    for (let a = 1; a <= 6; a++) for (let b = 1; b <= 6; b++) {
      const on = ev.f(a, b);
      g.rect(a - 0.95, b - 0.95, a - 0.05, b - 0.05, on ? 'green' : 'soft', on ? 0.85 : 1);
      g.text(a - 0.5, b - 0.5, fa(a + b), on ? 'card' : 'muted', 'center', 0);
    }
    for (let k = 1; k <= 6; k++) { g.text(k - 0.5, -0.45, fa(k), 'blue', 'center', 0); g.text(-0.45, k - 0.5, fa(k), 'blue', 'center', 0); }
    g.text(3, -0.95, 'تاسِ اول', 'blue', 'center', 0);
    g.text(0, 6.45, 'تاسِ دوم', 'blue', 'left', 0);
  },
  read: s => {
    const ev = PROB_EVENTS[s.ev];
    let c = 0;
    for (let a = 1; a <= 6; a++) for (let b = 1; b <= 6; b++) if (ev.f(a, b)) c++;
    return `«${ev.label}»: <b style="color:var(--green)">${fa(c)}</b> خانه از ۳۶.<br>${E(String.raw`P = \frac{${c}}{36} \approx ${(c / 36).toFixed(2)}`)}<br>${ev.note}`;
  },
});

