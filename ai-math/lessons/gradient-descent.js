// ---------- How Models Learn: Gradient Descent ----------
// (names start with GD_ because all lesson files share one global scope)

// like fa() but keeps up to 3 decimals
const GD_fa3 = n => String(+n.toFixed(3)).replace('-', '−').replace('.', '٫').replace(/\d/g, d => '۰۱۲۳۴۵۶۷۸۹'[d]);

// picture 1: loss L(θ) = (θ − 3)², slope 2(θ − 3). Each step multiplies the distance to 3 by (1 − 2η):
// η < 0.5 slides in, η = 0.5 lands in one step, 0.5 < η < 1 bounces but settles, η = 1 bounces forever, η > 1 explodes.
// From θ = 0 with η = 0.1: 0 → 0.6 → 1.08 → 1.464 (the worked example in part 2).
const GD_L = t => (t - 3) * (t - 3);
const GD_dL = t => 2 * (t - 3);
const GD_reset = s => { s.t = 0; s.n = 0; s.trail = [0]; s.boom = false; };
const GD_step = s => {
  if (s.boom) return;
  s.t -= s.eta * GD_dL(s.t);
  s.n++;
  s.trail.push(s.t);
  if (s.trail.length > 16) s.trail.shift();
  if (Math.abs(s.t - 3) > 4.4) s.boom = true; // the ball has left the picture
};

const W_GD_BALL = h => plane(h, {
  x: [-2, 8], y: [-1.5, 21], step: [1, 2], labels: true, names: ['پیچ', 'خطا'], ratio: 0.85,
  state: { t: 0, eta: 0.1, n: 0, trail: [0], boom: false },
  sliders: [{ key: 'eta', label: 'نرخ یادگیری:', min: 0.01, max: 1.1, step: 0.01 }],
  onSlide: GD_reset,
  buttons: [
    { label: 'یک قدم', on: GD_step },
    { label: '۱۰ قدم', on: s => { for (let i = 0; i < 10; i++) GD_step(s); } },
    { label: 'از نو', on: GD_reset },
  ],
  draw: (g, s) => {
    g.grid();
    g.fn(GD_L, 'orange', 4);
    g.dot(3, 0, 'green', 5);
    const tr = s.trail;
    for (let i = 1; i < tr.length; i++) g.arrow(tr[i - 1], GD_L(tr[i - 1]), tr[i], GD_L(tr[i]), 'green', 2);
    tr.slice(0, -1).forEach(t => g.dot(t, GD_L(t), 'muted', 4));
    if (!s.boom) {
      const y = GD_L(s.t), m = GD_dL(s.t);
      g.fn(x => y + m * (x - s.t), 'ink', 2, s.t - 0.8, s.t + 0.8);
      g.dot(s.t, y, 'red', 8);
    }
  },
  read: s => {
    if (s.boom) return `بعد از ${fa(s.n)} قدم، توپ از تصویر بیرون پرید و خطا هر بار بیشتر شد. <b style="color:var(--red)">منفجر شد!</b><br>قدم آن‌قدر بلند است که از کف رد می‌شود و بالاتر از قبل فرود می‌آید. «از نو» را بزنید و نرخ را کمتر کنید.`;
    const m = GD_dL(s.t), st = -s.eta * m;
    let say = '';
    if (Math.abs(s.t - 3) < 0.0005) say = '<br><b style="color:var(--green)">به کف رسیدید!</b> شیب صفر است، پس قدم هم صفر است و توپ می‌ایستد.';
    else if (Math.abs(s.eta - 1) < 1e-9 && s.n > 0) say = '<br>توپ همیشه بین دو دیواره می‌پرد: نه پایین‌تر می‌رود، نه بالاتر.';
    return `قدم‌ها: ${fa(s.n)} &nbsp;|&nbsp; جای پیچ = <b>${GD_fa3(s.t)}</b> &nbsp;|&nbsp; خطا = <b style="color:var(--orange)">${GD_fa3(GD_L(s.t))}</b><br>` +
      `شیبِ این‌جا = ${E(`۲ × (${GD_fa3(s.t)} − ۳) = ${GD_fa3(m)}`)}<br>` +
      `قدمِ بعدی = − نرخ × شیب = ${E(`− ${fa(s.eta)} × (${GD_fa3(m)}) = ${GD_fa3(st)}`)}` +
      (Math.abs(st) > 1e-9 ? ` (به ${st > 0 ? 'راست' : 'چپ'})` : '') + say;
  },
});

// picture 2: two knobs, loss L(a, b) = a² + 4b², seen from above as ellipses (contour lines).
// Slopes: 2a and 8b. Per step a is multiplied by (1 − 2η) and b by (1 − 8η):
// zig-zag in b once η > 0.125, b bounces forever at η = 0.25, explodes for η > 0.25.
// From (−4, 2), steps until loss < 0.01: η 0.05 → 36, 0.1 → 17, 0.2 → 8, 0.24 → 45; 0.26 explodes.
const GD_L2 = (a, b) => a * a + 4 * b * b;
const GD_path = s => {
  const pts = [[s.a, s.b]];
  let st = 'slow';
  while (pts.length <= 60) {
    const [a, b] = pts[pts.length - 1];
    if (GD_L2(a, b) < 0.01) { st = 'done'; break; }
    if (Math.abs(a) > 50 || Math.abs(b) > 50) { st = 'boom'; break; }
    pts.push([a - s.eta * 2 * a, b - s.eta * 8 * b]);
  }
  return { pts, st };
};
const GD_LEVELS = [0.3, 1.2, 3, 6, 10, 15, 22, 30, 40];

const W_GD_MAP = h => plane(h, {
  x: [-5, 5], y: [-3, 3], equal: true, snap: 0.5, names: ['پیچ ۱', 'پیچ ۲'],
  state: { a: -4, b: 2, eta: 0.05 },
  sliders: [{ key: 'eta', label: 'نرخ یادگیری:', min: 0.02, max: 0.27, step: 0.01 }],
  handles: [{ get: s => [s.a, s.b], set: (s, x, y) => { s.a = Math.max(-4.5, Math.min(4.5, x)); s.b = Math.max(-2.5, Math.min(2.5, y)); }, color: 'blue' }],
  draw: (g, s) => {
    g.grid();
    const c = g.ctx, ux = g.X(1) - g.X(0), uy = g.Y(0) - g.Y(1);
    c.strokeStyle = g.css('orange'); c.lineWidth = 1.5; c.globalAlpha = 0.55;
    GD_LEVELS.forEach(v => { const r = Math.sqrt(v); c.beginPath(); c.ellipse(g.X(0), g.Y(0), r * ux, r / 2 * uy, 0, 0, 2 * Math.PI); c.stroke(); });
    c.globalAlpha = 1;
    g.dot(0, 0, 'red', 6);
    g.text(0, 0, 'کف', 'red', 'center', 16);
    const { pts } = GD_path(s);
    for (let i = 1; i < pts.length; i++) g.line(pts[i - 1][0], pts[i - 1][1], pts[i][0], pts[i][1], 'green', 2);
    pts.slice(1).forEach(([a, b]) => g.dot(a, b, 'green', 3));
  },
  read: s => {
    const { pts, st } = GD_path(s), n = pts.length - 1;
    const zig = 1 - 8 * s.eta < -0.2 ? ' مسیر <b>زیگزاگ</b> است: در جهتِ تند (پیچ ۲) هر قدم از کف رد می‌شود و برمی‌گردد.' : '';
    const say = st === 'done' ? `بعد از <b>${fa(n)}</b> قدم به کف رسید (خطا کمتر از ۰٫۰۱).${zig}`
      : st === 'boom' ? `<b style="color:var(--red)">منفجر شد!</b> در جهتِ تند (پیچ ۲)، قدم هر بار بلندتر می‌شود.`
      : Math.abs(s.eta - 0.25) < 1e-9 ? 'پیچ ۲ همیشه بین دو دیواره می‌پرد؛ بعد از ۶۰ قدم هنوز نرسیده.'
      : `بعد از ۶۰ قدم هنوز نرسیده. قدم‌ها زیادی کوچک‌اند.${zig}`;
    return `شروع: خطا = ${fa(GD_L2(s.a, s.b))} &nbsp;|&nbsp; شیب‌ها: پیچ ۱ = ${E(fa(2 * s.a))}، پیچ ۲ = ${E(fa(8 * s.b))}<br>${say}`;
  },
});

