// fixed pseudo-random numbers (mulberry32), so every learner sees the same picture
const ENS_rng = seed => () => {
  seed |= 0; seed = seed + 0x6D2B79F5 | 0;
  let t = Math.imul(seed ^ seed >>> 15, 1 | seed);
  t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
  return ((t ^ t >>> 14) >>> 0) / 4294967296;
};

// picture 1: 100 guesses of a jar with 500 beans; each guess = 500 + noise (std 150), kept in 100…950, rounded; the actual spread (std) of the 100 guesses is 137 ≈ "about 140".
// With seed 8:  first 10 → average 544 (44 off),  20 → 482 (18 off),  50 → 502 (2 off),  100 → 505 (5 off).
// A single guesser is off by about 101–107 on average (mean absolute error).
const ENS_TRUE = 500;
const ENS_G = (() => {
  const r = ENS_rng(8);
  return [...Array(100)].map(() => Math.max(100, Math.min(950,
    Math.round(500 + 150 * Math.sqrt(-2 * Math.log(1 - r())) * Math.cos(2 * Math.PI * r())))));
})();
// running average after 1, 2, …, 100 guessers
const ENS_RA = ENS_G.map((g, i) => ENS_G.slice(0, i + 1).reduce((a, b) => a + b, 0) / (i + 1));

