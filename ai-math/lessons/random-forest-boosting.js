// picture 2: boosting with stumps (one-question trees) on 14 noisy points from 3 + 1.5 sin(0.7x), noise std 0.6, rounded to 0.1.
// F₀ = mean of y; each round fits the best stump to the residuals (least squared error) and adds η × stump.
// MSE train / new (14 other points from the same curve):
//   η = 1:   round 0: 1.40/1.00   4: 0.27/0.53 (new best)   10: 0.06/0.73   30: 0.01/0.77
//   η = 0.3: round 0: 1.40/1.00   10: 0.46/0.61   17: 0.29/0.52 (new best)   30: 0.14/0.56
//   η = 0.1: round 30: 0.49/0.59 (still learning)
const ENS_XT = [0.4, 1.1, 1.8, 2.5, 3.2, 3.9, 4.6, 5.4, 6.1, 6.8, 7.5, 8.2, 8.9, 9.6];
const ENS_YT = [2.8, 3.6, 4.1, 5.4, 5.2, 4.1, 3.9, 1.9, 2.2, 1.4, 1.8, 2.8, 3.7, 3.7];
const ENS_XN = [0.7, 1.4, 2.1, 2.8, 3.5, 4.2, 4.9, 5.7, 6.4, 7.1, 7.8, 8.5, 9.2, 9.9];
const ENS_YN = [3.6, 4.5, 4.3, 4.6, 4.1, 2.8, 2.1, 2.7, 1.5, 1.8, 2.4, 3.3, 2.6, 3.7];
const ENS_F0 = ENS_YT.reduce((a, b) => a + b, 0) / ENS_YT.length;

// best stump for residuals r: try every midpoint between neighbouring x's, keep the smallest squared error
const ENS_stump = r => {
  let b = null;
  for (let i = 0; i < ENS_XT.length - 1; i++) {
    const t = (ENS_XT[i] + ENS_XT[i + 1]) / 2;
    let sl = 0, nl = 0, sr = 0, nr = 0;
    r.forEach((v, k) => { if (ENS_XT[k] < t) { sl += v; nl++; } else { sr += v; nr++; } });
    const ml = sl / nl, mr = sr / nr;
    const e = r.reduce((a, v, k) => a + (v - (ENS_XT[k] < t ? ml : mr)) ** 2, 0);
    if (!b || e < b.e - 1e-12) b = { t, ml, mr, e };
  }
  return b;
};
// all stumps for a given η (30 rounds), cached
const ENS_CACHE = {};
const ENS_model = eta => {
  const key = eta.toFixed(1);
  if (ENS_CACHE[key]) return ENS_CACHE[key];
  const S = [], pred = (x, m) => S.slice(0, m).reduce((a, s) => a + eta * (x < s.t ? s.ml : s.mr), ENS_F0);
  for (let m = 0; m < 30; m++) S.push(ENS_stump(ENS_YT.map((y, k) => y - pred(ENS_XT[k], m))));
  return (ENS_CACHE[key] = pred);
};
const ENS_mse = (pred, m, X, Y) => X.reduce((a, x, k) => a + (Y[k] - pred(x, m)) ** 2, 0) / X.length;

const W_ENS_BOOST = h => plane(h, {
  x: [0, 10], y: [0, 6], labels: true, ratio: 0.7,
  state: { m: 0, eta: 1, show: false },
  sliders: [{ key: 'm', label: 'تعدادِ دورها:', min: 0, max: 30, step: 1 }, { key: 'eta', label: 'η (نرخ یادگیری):', min: 0.1, max: 1, step: 0.1 }],
  buttons: [{ label: 'داده‌ی تازه را نشان بده', on: s => { s.show = !s.show; }, active: s => s.show }],
  draw: (g, s) => {
    g.grid();
    const pred = ENS_model(s.eta), X = s.show ? ENS_XN : ENS_XT, Y = s.show ? ENS_YN : ENS_YT;
    X.forEach((x, k) => g.line(x, Y[k], x, pred(x, s.m), 'red', 1.5));
    g.fn(x => pred(x, s.m), 'orange', 3);
    X.forEach((x, k) => g.dot(x, Y[k], s.show ? 'accent' : 'blue', 6));
  },
  read: s => {
    const pred = ENS_model(s.eta), a = ENS_mse(pred, s.m, ENS_XT, ENS_YT), b = ENS_mse(pred, s.m, ENS_XN, ENS_YN);
    const say = s.m === 0 ? 'دورِ ۰: فقط میانگینِ همه‌ی yها؛ یک خطِ صاف.'
      : b > a + 0.45 ? '<b style="color:var(--red)">بیش‌برازش</b>: روی آموزش عالی، روی داده‌ی تازه نه. کُنده‌ها دارند سروصدا را حفظ می‌کنند.'
        : 'هر دور، پله‌ها کمی بیشتر به نقطه‌ها نزدیک می‌شوند.';
    return `بعد از ${fa(s.m)} دور، با ${E(String.raw`\eta = ${Math.round(s.eta * 10) / 10}`)} (هر کُنده ضربدر این عدد اضافه می‌شود)<br>` +
      `خطای آموزش (MSE): <b style="color:var(--blue)">${fa(a)}</b><br>` +
      `خطای داده‌ی تازه (MSE): <b style="color:var(--red)">${fa(b)}</b><br>${say}`;
  },
});

