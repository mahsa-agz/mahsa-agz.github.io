// ---------- Interview mission: How to detect overfitting? ----------
// (names start with MOVF_ because all lesson files share one global scope)

// Learning curves over 100 epochs (made-up but smooth):
//   train(t) = 0.10 + 0.90·e^(−t/15)      val(t) = 0.15 + 0.85·e^(−t/15) + 0.00006·t²
// Checked in node (train / val / gap):
//   t 0: 1.00 / 1.00 / 0.00   t 10: 0.56 / 0.59 / 0.03   t 20: 0.34 / 0.40 / 0.06
//   t 38: 0.17 / 0.30 / 0.13 (lowest validation error)   t 60: 0.12 / 0.38 / 0.27   t 100: 0.10 / 0.75 / 0.65
const MOVF_tr = t => 0.10 + 0.90 * Math.exp(-t / 15);
const MOVF_va = t => 0.15 + 0.85 * Math.exp(-t / 15) + 0.00006 * t * t;
const MOVF_BEST = (() => { let b = 0; for (let t = 0; t <= 100; t++) if (MOVF_va(t) < MOVF_va(b)) b = t; return b; })(); // 38
const MOVF_f2 = v => v.toFixed(2).replace('-', '−').replace('.', '٫').replace(/\d/g, d => '۰۱۲۳۴۵۶۷۸۹'[d]);
const MOVF_say = t => {
  if (MOVF_va(t) - MOVF_va(MOVF_BEST) <= 0.02) return '<b style="color:var(--green)">نزدیکِ بهترین جا</b>: خطای اعتبارسنجی تقریباً کمترین است. این‌جا بایستید.';
  if (t < MOVF_BEST) return 'هر دو خطا هنوز دارند پایین می‌آیند: مدل هنوز یاد می‌گیرد (<b>کم‌برازش</b>). ادامه بدهید.';
  return '<b style="color:var(--red)">بیش‌برازش</b>: خطای آموزش هنوز کم می‌شود، ولی خطای اعتبارسنجی بالا رفته. دارد حفظ می‌کند.';
};

// ---- Picture: learning curves with a draggable "stop here" marker (early stopping) ----
const MOVF_W_CURVE = h => plane(h, {
  x: [-6, 104], y: [-0.1, 1.08], step: [20, 0.25], labels: true, names: ['دور', 'خطا'], ratio: 0.75,
  state: { t: 80 },
  handles: [{ get: s => [s.t, MOVF_va(s.t)], set: (s, x) => { s.t = Math.max(0, Math.min(100, Math.round(x))); }, color: 'ink' }],
  draw: (g, s) => {
    g.grid();
    g.rect(s.t, -0.1, 104, 1.08, 'soft', 0.5);
    g.line(s.t, -0.1, s.t, 1.08, 'ink', 2, [6, 4]);
    g.fn(MOVF_tr, 'blue', 3, 0, 100);
    g.fn(MOVF_va, 'red', 3, 0, 100);
    g.line(s.t, MOVF_tr(s.t), s.t, MOVF_va(s.t), 'green', 4);
    g.dot(MOVF_BEST, MOVF_va(MOVF_BEST), 'green', 8);
    g.text(MOVF_BEST, MOVF_va(MOVF_BEST), 'کمترین', 'green', 'center', -18);
    g.text(s.t, 1.08, 'اینجا بایست', 'ink', s.t > 80 ? 'right' : s.t < 20 ? 'left' : 'center', 12);
  },
  read: s => {
    const tr = MOVF_tr(s.t), va = MOVF_va(s.t);
    return `دورِ ${fa(s.t)}: آموزش <b style="color:var(--blue)">${MOVF_f2(tr)}</b> &nbsp;|&nbsp; اعتبارسنجی <b style="color:var(--red)">${MOVF_f2(va)}</b> &nbsp;|&nbsp; ` +
      `فاصله <b style="color:var(--green)">${MOVF_f2(+va.toFixed(2) - +tr.toFixed(2))}</b><br>${MOVF_say(s.t)}<br>` +
      `<span class="muted">کمترین خطای اعتبارسنجی: دورِ ${fa(MOVF_BEST)} (${MOVF_f2(MOVF_va(MOVF_BEST))})</span>`;
  },
});

