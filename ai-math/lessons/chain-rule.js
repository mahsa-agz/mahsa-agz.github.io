// ---------- Foundations: Chain Rule ----------
const CHAIN_clamp = (v, a, b) => Math.max(a, Math.min(b, v));
// numbers inside LaTeX use Latin digits (2 or 4 decimals)
const CHAIN_n = n => String(Math.round(n * 100) / 100);
const CHAIN_n4 = n => String(+n.toFixed(4));
// picture 2: inner g(x) = 0.5x + 1, outer f(u) = u², so y = f(g(x)) = (0.5x + 1)²
const CHAIN_g = x => 0.5 * x + 1;
const CHAIN_f = u => u * u;
const CHAIN_y = x => CHAIN_f(CHAIN_g(x));
const CHAIN_c = (color, html) => `<span style="color:var(--${color})">${html}</span>`;

// three linked number lines: x -> u = 3x -> y = 2u. Nudge x; u moves 3x as much, y moves 2x as much as u.
const CHAIN_W_LINKS = h => plane(h, {
  x: [-0.6, 12.8], y: [0, 3.3], ratio: 0.6,
  state: { d: 0.5 },
  sliders: [{ key: 'd', label: 'تکانِ x (Δx):', min: 0.1, max: 1, step: 0.1 }],
  draw: (g, s) => {
    const rows = [[2.7, 1, 1, 'blue', 'x'], [1.65, 3, 3, 'orange', 'u = 3x'], [0.6, 6, 6, 'green', 'y = 2u']];
    rows.forEach(([L, , , c, name]) => {
      g.line(0, L, 12.4, L, 'line', 2);
      for (let k = 0; k <= 12; k += 2) { g.line(k, L - 0.07, k, L + 0.07, 'muted', 1.5); g.text(k, L, fa(k), 'muted', 'center', 14); }
      g.text(12.4, L, name, c, 'right', -16);
    });
    // dashed links: start points and moved points
    for (let i = 0; i < 2; i++) {
      const [La, a0, ka] = rows[i], [Lb, b0, kb] = rows[i + 1];
      g.line(a0, La, b0, Lb, 'muted', 1.5, [4, 4]);
      g.line(a0 + ka * s.d, La, b0 + kb * s.d, Lb, 'muted', 1.5, [4, 4]);
    }
    rows.forEach(([L, b, k, c]) => {
      g.line(b, L, b + k * s.d, L, c, 6);
      g.dot(b, L, 'muted', 5);
      g.dot(b + k * s.d, L, c, 7);
    });
    g.text(0.2, (2.7 + 1.65) / 2, '×۳', 'orange', 'left', 0);
    g.text(0.2, (1.65 + 0.6) / 2, '×۲', 'green', 'left', 0);
  },
  read: s => {
    const d = CHAIN_n(s.d), du = CHAIN_n(3 * s.d), dy = CHAIN_n(6 * s.d);
    return `${CHAIN_c('blue', E(String.raw`\Delta x = ${d}`))} ← x این‌قدر جلو رفت<br>` +
      `${CHAIN_c('orange', E(String.raw`\Delta u = 3 \times ${d} = ${du}`))} ← u سه برابر تکان خورد<br>` +
      `${CHAIN_c('green', E(String.raw`\Delta y = 2 \times ${du} = ${dy}`))} ← y دو برابرِ u<br>` +
      `${E(String.raw`\frac{\Delta y}{\Delta x} = \frac{${dy}}{${d}} = 6 = 3 \times 2`)}؛ تکان هرچقدر باشد، این نسبت ۶ است.`;
  },
});

// y = (0.5x + 1)²: drag x; slope = f′(g(x)) · g′(x) = 2u · 0.5, plus the tangent line and a tiny-h check
const CHAIN_W_NEST = h => plane(h, {
  x: [-4.5, 3.5], y: [-1, 7], step: [1, 1], labels: true, ratio: 0.85,
  state: { p: 1 },
  handles: [{ get: s => [s.p, CHAIN_y(s.p)], set: (s, x) => { s.p = CHAIN_clamp(Math.round(x * 2) / 2, -4, 3); }, color: 'red' }],
  draw: (g, s) => {
    g.grid();
    g.fn(CHAIN_y, 'orange', 4);
    const u = CHAIN_g(s.p), m = 2 * u * 0.5, y = CHAIN_y(s.p);
    g.fn(x => y + m * (x - s.p), 'ink', 3, s.p - 1.2, s.p + 1.2);
  },
  read: s => {
    const u = CHAIN_g(s.p), fp = 2 * u, m = fp * 0.5;
    const num = (CHAIN_y(s.p + 0.001) - CHAIN_y(s.p)) / 0.001;
    const fpS = fp < 0 ? `(${CHAIN_n(fp)})` : CHAIN_n(fp);
    const zero = Math.abs(u) < 1e-9 ? '<br>این‌جا u = ۰، پس حلقه‌ی بیرونی صفر شد و <b>کل زنجیره صفر</b> است.' : '';
    return `${E('x = ' + CHAIN_n(s.p))} ← حلقه‌ی داخلی: ${CHAIN_c('blue', E('u = 0.5x + 1 = ' + CHAIN_n(u)))}<br>` +
      `شیب بیرونی: ${E(`f'(u) = 2u = ${CHAIN_n(fp)}`)}؛ شیب داخلی: ${E("g'(x) = 0.5")}<br>` +
      `شیب کل: ${CHAIN_c('green', E(String.raw`${fpS} \times 0.5 = ${CHAIN_n(m)}`))} (بررسی با ${E('h = 0.001')}: ${CHAIN_n4(num).replace('-', '−')})${zero}`;
  },
});

