// ---------- Statistics: ANOVA (comparing several groups) ----------
// (names start with ANOVA_ because all lesson files share one global scope)
// MS_between = Σ n·(group mean − grand mean)² / (k − 1);  MS_within = Σ (x − group mean)² / (N − k);  F = MS_between / MS_within

const ANOVA_COL = ['blue', 'orange', 'green'];
const ANOVA_NAME = ['کود الف', 'کود ب', 'کود ج'];
// Persian digits for a ready-made number string (keeps trailing zeros, e.g. 0.008)
const ANOVA_dig = str => str.replace('-', '−').replace('.', '٫').replace(/\d/g, d => '۰۱۲۳۴۵۶۷۸۹'[d]);
// one decimal under 100, whole number above; says «حدود» when rounded
const ANOVA_num = v => { const r = v < 100 ? Math.round(v * 10) / 10 : Math.round(v); return (Math.abs(r - v) > 1e-9 ? 'حدود ' : '') + fa(r); };

// all the pieces of a one-way ANOVA for a list of groups
const ANOVA_calc = groups => {
  const all = groups.flat(), gm = ST.mean(all), k = groups.length, N = all.length;
  const ssb = ST.sum(groups.map(a => a.length * (ST.mean(a) - gm) ** 2));
  const ssw = ST.sum(groups.map(a => { const m = ST.mean(a); return ST.sum(a.map(x => (x - m) ** 2)); }));
  const msb = ssb / (k - 1), msw = ssw / (N - k);
  return { gm, k, N, ssb, ssw, msb, msw, F: msb / msw };
};

// picture 1: three fertilizers, 5 plants each. Fixed offsets (each row sums to 0, so the group mean never moves by noise)
const ANOVA_OFF = [[-1.4, -0.6, 0.1, 0.5, 1.4], [-1.2, -0.8, 0.3, 0.6, 1.1], [-1.6, -0.3, 0.2, 0.4, 1.3]];
const ANOVA_SHIFT = [-2, 0, 3]; // with "difference" = 1 the means are 20, 22, 25 cm (the story)
const ANOVA_plants = s => ANOVA_OFF.map((o, j) => o.map(v => 22 + s.d * ANOVA_SHIFT[j] + s.n * v));

const W_ANOVA_GROUPS = h => plane(h, {
  x: [9.5, 35.5], y: [-1.5, 8], ratio: 0.72,
  state: { d: 1, n: 1 },
  sliders: [{ key: 'd', label: 'فرقِ بینِ گروه‌ها:', min: 0, max: 2, step: 0.25 },
            { key: 'n', label: 'نویزِ درونِ گروه‌ها:', min: 0.25, max: 4, step: 0.25 }],
  draw: (g, s) => {
    const G = ANOVA_plants(s), r = ANOVA_calc(G);
    G.forEach((a, j) => {
      const base = 5.6 - 2.8 * j, col = ANOVA_COL[j];
      g.line(10, base, 35, base, 'line', 1);
      a.forEach(x => g.dot(x, base + 0.5, col, 6));
      drawMarker(g, ST.mean(a), base, col);
      g.text(9.7, base + 1.6, ANOVA_NAME[j], col, 'left', 0);
    });
    for (let t = 10; t <= 35; t += 5) g.text(t, 0, fa(t), 'muted', 'center', 30);
    g.line(r.gm, -0.4, r.gm, 7.3, 'ink', 1.5, [5, 4]);
    g.text(r.gm, 7.3, 'میانگینِ کل', 'muted', 'center', -8);
  },
  read: s => {
    const G = ANOVA_plants(s), r = ANOVA_calc(G);
    const verdict = r.F < 1.5 ? 'این‌قدر فرق را <b>شانس به‌راحتی</b> می‌سازد.'
      : r.F < 4 ? 'شاید فرقی باشد، ولی هنوز <b>قانع‌کننده نیست</b>.'
      : '<b>احتمالاً فرقِ واقعی</b> است؛ شانسِ تنها به‌ندرت این را می‌سازد.';
    return `میانگین‌ها: ${G.map((a, j) => `<b style="color:var(--${ANOVA_COL[j]})">${ANOVA_num(ST.mean(a))}</b>`).join('، ')} سانت<br>` +
      `پراکندگیِ <b>بینِ</b> گروه‌ها: <b>${ANOVA_num(r.msb)}</b> &nbsp;|&nbsp; پراکندگیِ <b>درونِ</b> گروه‌ها: <b>${ANOVA_num(r.msw)}</b><br>` +
      `نسبت: <b style="color:var(--accent)">${E('F')} = ${ANOVA_num(r.F)}</b>${r.F > 0 ? `؛ یعنی فرقِ میانگین‌ها ${ANOVA_num(r.F)} برابرِ نویز است` : ''}.<br>${verdict}`;
  },
});

// picture 2: the worked example (3 groups × 3 plants); slider multiplies the noise, buttons show the pieces
const ANOVA_EX_M = [20, 22, 24];
const ANOVA_ex = k => ANOVA_EX_M.map(m => [m - k, m, m + k]);

const W_ANOVA_PIECES = h => plane(h, {
  x: [13.5, 30.5], y: [-1.4, 6.8], ratio: 0.62,
  state: { k: 1, b: true, w: true },
  sliders: [{ key: 'k', label: 'نویزِ درونِ گروه‌ها:', min: 1, max: 4, step: 1 }],
  buttons: [
    { label: 'تکه‌های بین', on: s => { s.b = !s.b; }, active: s => s.b },
    { label: 'تکه‌های درون', on: s => { s.w = !s.w; }, active: s => s.w },
  ],
  draw: (g, s) => {
    const G = ANOVA_ex(s.k), r = ANOVA_calc(G);
    G.forEach((a, j) => {
      const base = 4.8 - 2.4 * j, col = ANOVA_COL[j], m = ST.mean(a);
      g.line(14, base, 30, base, 'line', 1);
      if (s.w) a.forEach(x => g.line(x, base + 0.5, m, base + 0.5, 'red', 3));
      g.line(m, base, m, base + 1.4, col, 3);
      if (s.b) g.arrow(r.gm, base + 1.2, m, base + 1.2, col, 3);
      a.forEach(x => g.dot(x, base + 0.5, col, 6));
    });
    for (let t = 14; t <= 30; t += 2) g.text(t, 0, fa(t), 'muted', 'center', 22);
    g.line(r.gm, -0.3, r.gm, 6.4, 'ink', 1.5, [5, 4]);
  },
  read: s => {
    const r = ANOVA_calc(ANOVA_ex(s.k)), p = (1 + r.F / 3) ** -3; // exact for 2 and 6 degrees of freedom
    const q = v => Math.round(v * 100) / 100;
    return `گروه‌ها: ${ANOVA_ex(s.k).map((a, j) => `<b style="color:var(--${ANOVA_COL[j]})">${a.map(fa).join('، ')}</b>`).join(' &nbsp;|&nbsp; ')}<br>` +
      `بین: ${E(String.raw`\frac{${q(r.ssb)}}{${r.k - 1}} = ${q(r.msb)}`)} &nbsp;|&nbsp; <span style="color:var(--red)">درون</span>: ${E(String.raw`\frac{${q(r.ssw)}}{${r.N - r.k}} = ${q(r.msw)}`)}<br>` +
      `<b style="color:var(--accent)">${E('F')} = ${ANOVA_num(r.F)}</b> &nbsp;|&nbsp; ${E('p')} = ${ANOVA_dig(p.toFixed(3))}: ` +
      (p <= 0.05 ? 'کمتر از ۰٫۰۵؛ فرق <b>معنادار</b> است.' : 'بیشتر از ۰٫۰۵؛ شانس به‌راحتی این را می‌سازد.');
  },
});

