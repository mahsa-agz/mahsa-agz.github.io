// ---------- Statistics: Correlation ----------
// (names start with CORR_ because all lesson files share one global scope)

const CORR_clamp = (v, a, b) => Math.max(a, Math.min(b, v));
// Pearson r of two lists (null when one list has no spread)
const CORR_r = (x, y) => {
  const mx = ST.mean(x), my = ST.mean(y);
  let sxy = 0, sxx = 0, syy = 0;
  x.forEach((v, i) => { sxy += (v - mx) * (y[i] - my); sxx += (v - mx) ** 2; syy += (y[i] - my) ** 2; });
  return sxx && syy ? sxy / Math.sqrt(sxx * syy) : null;
};
const CORR_word = r0 => {
  const r = Math.round(r0 * 100) / 100;
  const a = Math.abs(r);
  if (a > 0.995) return `کامل و ${r > 0 ? 'هم‌جهت' : 'خلاف‌جهت'}: همه‌ی نقطه‌ها دقیقاً روی یک خط‌اند`;
  if (a < 0.1) return 'تقریباً هیچ الگوی خطی‌ای نیست';
  const k = a >= 0.7 ? 'قوی' : a >= 0.4 ? 'متوسط' : 'ضعیف';
  return `<b>${k}</b> و ${r > 0 ? '<b>هم‌جهت</b>: یکی بالا برود، دیگری هم معمولاً بالا می‌رود' : '<b>خلاف‌جهت</b>: یکی بالا برود، دیگری معمولاً پایین می‌آید'}`;
};

// ---- picture 1: 30 fixed points, y = r·x + √(1 − r²)·noise ----
// x and noise come from a fixed seed, are centred, made uncorrelated and scaled to σ = 1,
// so the r computed from the points equals the slider exactly.
const CORR_BASE = (() => {
  let t = 12345;
  const u = () => { t = (t * 1103515245 + 12345) % 2147483648; return (t + 0.5) / 2147483648; };
  const n = () => Math.sqrt(-2 * Math.log(u())) * Math.cos(2 * Math.PI * u());
  const centre = a => { const m = ST.mean(a); return a.map(v => v - m); };
  const unit = a => { const s = Math.sqrt(ST.mean(a.map(v => v * v))); return a.map(v => v / s); };
  const x = unit(centre(Array.from({ length: 30 }, n)));
  let e = centre(Array.from({ length: 30 }, n));
  const k = ST.mean(e.map((v, i) => v * x[i]));
  e = unit(e.map((v, i) => v - k * x[i]));
  return { x, e };
})();
const CORR_ys = r => CORR_BASE.x.map((x, i) => r * x + Math.sqrt(Math.max(0, 1 - r * r)) * CORR_BASE.e[i]);

const W_CORR_CLOUD = h => plane(h, {
  x: [-3.2, 3.2], y: [-3.2, 3.2], equal: true, names: ['x', 'y'],
  state: { r: 0.6 },
  sliders: [{ key: 'r', label: 'همبستگی (r):', min: -1, max: 1, step: 0.1 }],
  draw: (g, s) => {
    g.grid();
    g.fn(x => s.r * x, 'orange', 2);
    const ys = CORR_ys(s.r);
    CORR_BASE.x.forEach((x, i) => g.dot(x, ys[i], 'blue', 5));
  },
  read: s => {
    const r = CORR_r(CORR_BASE.x, CORR_ys(s.r));
    return `همبستگیِ این ۳۰ نقطه: <b style="color:var(--green)">r = ${fa(r)}</b><br>${CORR_word(r)}.`;
  },
});

// ---- picture 2: 5 draggable points (study hours, grade), means as dashed lines, quadrants ----
const CORR_START = [[1, 11], [2, 15], [3, 13], [4, 19], [5, 17]];
const CORR_sign = (p, i) => {
  const mx = ST.mean(p.map(q => q[0])), my = ST.mean(p.map(q => q[1]));
  const v = (p[i][0] - mx) * (p[i][1] - my);
  return Math.abs(v) < 1e-9 ? 0 : Math.sign(v);
};

const W_CORR_DRAG = h => {
  const st = { p: CORR_START.map(q => [...q]) };
  return plane(h, {
    x: [-1, 8.6], y: [4.6, 21], ratio: 0.85, snap: 1,
    state: st,
    handles: CORR_START.map((_, i) => ({
      get: s => s.p[i],
      set: (s, x, y) => { s.p[i] = [CORR_clamp(x, 0, 8), CORR_clamp(y, 7, 20)]; },
      get color() { const k = CORR_sign(st.p, i); return k > 0 ? 'green' : k < 0 ? 'red' : 'ink'; },
    })),
    buttons: [
      { label: 'یک نقطه‌ی پرت', on: s => { s.p[4] = [5, 9]; } },
      { label: 'از اول', on: s => { s.p = CORR_START.map(q => [...q]); } },
    ],
    draw: (g, s) => {
      const mx = ST.mean(s.p.map(q => q[0])), my = ST.mean(s.p.map(q => q[1]));
      // quadrants: agree (+) green, disagree (−) red
      g.rect(mx, my, 8.6, 21, 'green', 0.12); g.rect(-0.2, 6, mx, my, 'green', 0.12);
      g.rect(-0.2, my, mx, 21, 'red', 0.12); g.rect(mx, 6, 8.6, my, 'red', 0.12);
      g.text(8.3, 20.3, '+', 'green', 'center', 0); g.text(0.1, 6.7, '+', 'green', 'center', 0);
      g.text(0.1, 20.3, '−', 'red', 'center', 0); g.text(8.3, 6.7, '−', 'red', 'center', 0);
      // axes
      g.line(-0.2, 6, 8.6, 6, 'line', 2); g.line(-0.2, 6, -0.2, 21, 'line', 2);
      for (let t = 0; t <= 8; t++) g.text(t, 6, fa(t), 'muted', 'center', 14);
      for (let t = 8; t <= 20; t += 4) g.text(-0.55, t, fa(t), 'muted', 'center', 0);
      // means
      g.line(mx, 6, mx, 21, 'ink', 1.5, [6, 5]); g.line(-0.2, my, 8.6, my, 'ink', 1.5, [6, 5]);
      g.text(mx, 21, 'x̄', 'ink', 'left', 10); g.text(8.6, my, 'ȳ', 'ink', 'right', -10);
    },
    read: s => {
      const xs = s.p.map(q => q[0]), ys = s.p.map(q => q[1]), r = CORR_r(xs, ys);
      const agree = s.p.filter((_, i) => CORR_sign(s.p, i) > 0).length, dis = s.p.filter((_, i) => CORR_sign(s.p, i) < 0).length;
      const head = `${E(`x̄ = ${fa(ST.mean(xs))}`)} ساعت &nbsp;|&nbsp; ${E(`ȳ = ${fa(ST.mean(ys))}`)} نمره<br>`;
      if (r === null) return head + 'همه‌ی نقطه‌ها روی یک خطِ افقی یا عمودی‌اند؛ یکی از دو طرف اصلاً پخش نیست، پس r تعریف نمی‌شود (تقسیم بر صفر).';
      return head + `<b style="color:var(--green)">موافق: ${fa(agree)}</b> نقطه &nbsp;|&nbsp; <b style="color:var(--red)">مخالف: ${fa(dis)}</b> نقطه<br>` +
        `<b>r = ${fa(r)}</b>؛ ${CORR_word(r)}.`;
    },
  });
};

