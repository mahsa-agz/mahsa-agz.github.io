// ---------- Classical ML: k-Nearest Neighbors ----------
// (names start with KNN_ because all lesson files share one global scope)

// 20 known fruits (13 lemons, 7 oranges: lemons are more common, so a very big k shows underfitting honestly): [size, how orange the colour is (0–10), class]  class 0 = lemon (green), 1 = orange (orange)
// two "noisy" fruits on purpose: a lemon at (6.5, 6.5) among the oranges, an orange at (3.5, 2.5) among the lemons.
// Checked in node: training accuracy (each fruit counted as its own neighbour) by k:
//   (see KNN_ACC) k = 1 gives 20, k = 15..19 give 13 (= every fruit called "lemon")
// Start point (3.6, 2.8): k = 1 → orange (the noisy orange is nearest), k = 3, 5, 7 → lemon.
// Point (5.5, 5): k = 1 and 3 → orange, k = 5 and 7 → lemon.
const KNN_PTS = [
  [1.5, 2, 0], [2, 4, 0], [2.5, 1.5, 0], [3, 3, 0], [3.5, 5, 0], [4, 2, 0], [4.5, 3.5, 0], [5, 1.5, 0], [6, 3, 0], [6.5, 6.5, 0], [1, 3, 0], [3, 1, 0], [5.5, 2.5, 0],
  [5, 6, 1], [6, 8, 1], [7, 5, 1], [7.5, 7, 1], [8.5, 8.5, 1], [7.5, 2.5, 1], [3.5, 2.5, 1],
];
const KNN_COL = ['green', 'orange'];
const KNN_NAME = ['لیمو', 'پرتقال'];
const KNN_clamp = (v, a, b) => Math.max(a, Math.min(b, v));
// the k nearest known fruits to (x, y): [[distance, class, px, py], …] sorted by distance
const KNN_near = (x, y, k) => KNN_PTS.map(p => [Math.hypot(p[0] - x, p[1] - y), p[2], p[0], p[1]]).sort((a, b) => a[0] - b[0]).slice(0, k);
// majority vote (k is odd and there are two classes, so there is never a tie)
const KNN_vote = (x, y, k) => (KNN_near(x, y, k).filter(n => n[1] === 1).length * 2 > k ? 1 : 0);
const KNN_ACC = {};
for (let k = 1; k <= 19; k += 2) KNN_ACC[k] = KNN_PTS.filter(p => KNN_vote(p[0], p[1], k) === p[2]).length;
// decision map: 20 × 20 coarse cells, computed once per k (cached so dragging the slider stays fast on a phone)
const KNN_GRID = {};
const KNN_grid = k => KNN_GRID[k] || (KNN_GRID[k] = Array.from({ length: 20 }, (_, i) => Array.from({ length: 20 }, (_, j) => KNN_vote((i + 0.5) / 2, (j + 0.5) / 2, k))));
const KNN_dots = g => KNN_PTS.forEach(p => g.dot(p[0], p[1], KNN_COL[p[2]], 6));

// picture 1: drag the new fruit, choose k; lines and a circle show the k nearest
const KNN_W_VOTE = h => plane(h, {
  x: [0, 10], y: [0, 10], equal: true, labels: true, step: [2, 2], names: ['اندازه', 'نارنجی‌بودنِ رنگ'],
  state: { x: 3.6, y: 2.8, k: 1 },
  sliders: [{ key: 'k', label: 'k (چند همسایه):', min: 1, max: 7, step: 2 }],
  handles: [{ get: s => [s.x, s.y], set: (s, x, y) => { s.x = KNN_clamp(x, 0.2, 9.8); s.y = KNN_clamp(y, 0.2, 9.8); }, color: 'red' }],
  draw: (g, s) => {
    g.grid();
    const nb = KNN_near(s.x, s.y, s.k), r = nb[nb.length - 1][0] * (g.X(1) - g.X(0));
    g.ctx.beginPath(); g.ctx.arc(g.X(s.x), g.Y(s.y), r, 0, 7);
    g.ctx.strokeStyle = g.css('muted'); g.ctx.lineWidth = 2; g.ctx.setLineDash([6, 6]); g.ctx.stroke(); g.ctx.setLineDash([]);
    nb.forEach(n => g.line(s.x, s.y, n[2], n[3], KNN_COL[n[1]], 3));
    KNN_dots(g);
    g.text(s.x, s.y, '؟', 'red', 'center', -22);
  },
  read: s => {
    const nb = KNN_near(s.x, s.y, s.k), o = nb.filter(n => n[1] === 1).length, l = s.k - o, win = o > l ? 1 : 0;
    return `${fa(s.k)} نزدیک‌ترین میوه: <b style="color:var(--green)">${fa(l)} لیمو</b> و <b style="color:var(--orange)">${fa(o)} پرتقال</b><br>` +
      `نزدیک‌ترین‌شان ${fa(nb[0][0])} واحد دور است (${KNN_NAME[nb[0][1]]}).<br>` +
      `رأیِ اکثریت: <b style="color:var(--${KNN_COL[win]})">${KNN_NAME[win]}</b>`;
  },
});

// picture 2: the decision map; every one of 20 × 20 cells is coloured by what k-NN would say there
const KNN_W_MAP = h => plane(h, {
  x: [0, 10], y: [0, 10], equal: true, labels: true, step: [2, 2], names: ['اندازه', 'نارنجی‌بودنِ رنگ'],
  state: { k: 1 },
  sliders: [{ key: 'k', label: 'k:', min: 1, max: 19, step: 2 }],
  draw: (g, s) => {
    const c = 0.5, M = KNN_grid(s.k);
    for (let i = 0; i < 20; i++) for (let j = 0; j < 20; j++) g.rect(i * c, j * c, (i + 1) * c, (j + 1) * c, KNN_COL[M[i][j]], 0.22);
    g.grid();
    KNN_dots(g);
  },
  read: s => {
    const note = s.k === 1 ? 'مرز پر از پیچ و جزیره است: دور هر میوه‌ی «اشتباهی» یک جزیره‌ی کوچک. این <b style="color:var(--red)">بیش‌برازش</b> است.'
      : s.k <= 7 ? 'مرز نرم‌تر شد. جزیره‌های کوچک پاک شدند؛ یک میوه‌ی تنها دیگر تصمیم نمی‌گیرد.'
      : s.k <= 13 ? 'مرز خیلی صاف شده؛ پرتقال‌ها دارند از نقشه بیرون می‌روند.'
      : 'تقریباً همه‌جا <b style="color:var(--green)">لیمو</b>! چون k تقریباً با تعدادِ کلِ میوه‌ها برابر است، همیشه دسته‌ی پرتعدادتر (۱۳ لیمو در برابر ۷ پرتقال) برنده می‌شود. مدل چیزی از رنگ و اندازه یاد نگرفته؛ این <b>کم‌برازش</b> است.';
    return `k = ${fa(s.k)}: روی همین ۲۰ میوه، ${fa(KNN_ACC[s.k])} از ۲۰ درست.<br>${note}` +
      (s.k === 1 ? '<br>۲۰ از ۲۰ عالی به نظر می‌رسد، ولی هر میوه همسایه‌ی خودش است؛ این حفظ کردن است، نه یاد گرفتن.' : '');
  },
});

