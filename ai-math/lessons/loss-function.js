// ---------- How Models Learn: Loss Function ----------
// (names start with LOSS_ because all lesson files share one global scope)

// 6 houses: x = size, y = price. Built as y = x + 1 + r with r = [0, 1, −1, −1, 1, 0]
// (Σr = 0 and Σx·r = 0), so the best line is exactly a = 1, b = 1 with MSE = 4/6 ≈ 0.67.
const LOSS_X = [1, 2, 3, 4, 5, 6];
const LOSS_Y = [2, 4, 3, 4, 7, 7];
const LOSS_errs = (a, b) => LOSS_X.map((x, i) => LOSS_Y[i] - (a * x + b));
const LOSS_mse = (a, b) => LOSS_errs(a, b).reduce((t, e) => t + e * e, 0) / LOSS_X.length;
const LOSS_BEST = 4 / 6;
const LOSS_n = v => String(Math.round(v * 100) / 100); // a plain Latin number for inside LaTeX
const LOSS_list = v => E(v.map(LOSS_n).join(String.raw`,\;\; `));

// picture 1: a line with sliders a and b; red segments = errors; readout = errors, squares, MSE
const W_LOSS_FIT = h => plane(h, {
  x: [-0.6, 7], y: [-1, 9.5], step: [1, 1], labels: true, names: ['متراژ', 'قیمت'], ratio: 0.8,
  state: { a: 0.4, b: 2, best: LOSS_mse(0.4, 2) },
  sliders: [{ key: 'a', label: 'a (شیب):', min: 0, max: 2, step: 0.1 }, { key: 'b', label: 'b (شروع):', min: -1, max: 3, step: 0.5 }],
  onSlide: s => { s.best = Math.min(s.best, LOSS_mse(s.a, s.b)); },
  draw: (g, s) => {
    g.grid();
    g.fn(x => s.a * x + s.b, 'orange', 3);
    LOSS_X.forEach((x, i) => g.line(x, LOSS_Y[i], x, s.a * x + s.b, 'red', 3));
    LOSS_X.forEach((x, i) => g.dot(x, LOSS_Y[i], 'blue', 7));
  },
  read: s => {
    const e = LOSS_errs(s.a, s.b), m = LOSS_mse(s.a, s.b);
    const top = Math.abs(m - LOSS_BEST) < 1e-9 ? '<br><b style="color:var(--green)">آفرین! این کمترین مقدارِ ممکن است: بهترین خط.</b>' : '';
    return `خطاها (واقعی − حدس): ${LOSS_list(e)}<br>` +
      `مربعِ خطاها: ${LOSS_list(e.map(v => v * v))}<br>` +
      `میانگینِ مربعِ خطا (MSE) = جمع ÷ ۶ = <b style="color:var(--green)">${fa(m)}</b><br>` +
      `کمترین تا حالا: <b>${fa(s.best)}</b>${top}`;
  },
});

// picture 2: the same 6 houses, b fixed at 1; MSE as a function of the slope a is a bowl
const LOSS_bowl = a => LOSS_mse(a, 1);
const LOSS_dbowl = a => (LOSS_bowl(a + 1e-4) - LOSS_bowl(a - 1e-4)) / 2e-4; // equals −(91/3)(1 − a)
const W_LOSS_BOWL = h => plane(h, {
  x: [-0.3, 2.3], y: [-2, 18], step: [0.5, 2], labels: true, names: ['a (شیب)', 'MSE'], ratio: 0.85,
  state: { a: 0.2 },
  sliders: [{ key: 'a', label: 'a (شیب):', min: 0, max: 2, step: 0.1 }],
  draw: (g, s) => {
    g.grid();
    g.fn(LOSS_bowl, 'orange', 4);
    const y = LOSS_bowl(s.a), m = LOSS_dbowl(s.a);
    g.fn(x => y + m * (x - s.a), 'ink', 2, s.a - 0.25, s.a + 0.25);
    g.dot(s.a, y, 'red', 8);
    if (Math.abs(m) < 1e-6) g.text(s.a, y, 'کف', 'green', 'center', 22);
  },
  read: s => {
    const y = LOSS_bowl(s.a), m = LOSS_dbowl(s.a), flat = Math.abs(m) < 1e-6;
    const say = flat ? 'شیب صفر: این <b>کفِ کاسه</b> است؛ همان بهترین خطِ تصویر اول (a = ۱، b = ۱).'
      : m < 0 ? 'شیب منفی: به راست، خطا کم می‌شود ← <b>a را بیشتر کن</b>.'
      : 'شیب مثبت: به راست، خطا زیاد می‌شود ← <b>a را کمتر کن</b>.';
    return `خط: ${E(String.raw`\hat{y} = ${LOSS_n(s.a)}x + 1`)} &nbsp;|&nbsp; خطای این خط: MSE = <b style="color:var(--green)">${fa(y)}</b><br>` +
      `شیبِ کاسه زیرِ نقطه‌ی قرمز = <b>${flat ? '۰' : fa(m)}</b><br>${say}`;
  },
});

