// ---------- Classical ML: PCA ----------
// (names start with PCA_ because all lesson files share one global scope)

// a matrix (list of rows) drawn as a small grid with brackets (same look as the eigenvalues lesson)
const PCA_G = rows => `<span class="eq" style="display:inline-grid;grid-template-columns:repeat(${rows[0].length},auto);gap:0 .6em;padding:0 .35em;` +
  `border-left:2px solid currentColor;border-right:2px solid currentColor;border-radius:4px;vertical-align:middle;line-height:1.25;text-align:center">` +
  rows.flat().map(x => `<span>${typeof x === 'number' ? fa(x) : x}</span>`).join('') + '</span>';
const PCA_C = PCA_G([[2, 1], [1, 2]]);
const PCA_rad = d => d * Math.PI / 180;

// ---- the cloud: 40 fixed points, centred at (0, 0), covariance matrix exactly [[2, 1], [1, 2]] ----
// a and b come from a fixed seed, are centred, made uncorrelated and scaled to σ = 1;
// point = √3·a·u1 + b·u2 with u1 = [1, 1]/√2 (λ = 3) and u2 = [1, −1]/√2 (λ = 1).
const PCA_PTS = (() => {
  let t = 2024;
  const u = () => { t = (t * 1103515245 + 12345) % 2147483648; return (t + 0.5) / 2147483648; };
  const n = () => Math.sqrt(-2 * Math.log(u())) * Math.cos(2 * Math.PI * u());
  const centre = a => { const m = ST.mean(a); return a.map(v => v - m); };
  const unit = a => { const s = Math.sqrt(ST.mean(a.map(v => v * v))); return a.map(v => v / s); };
  const a = unit(centre(Array.from({ length: 40 }, n)));
  let b = centre(Array.from({ length: 40 }, n));
  const k = ST.mean(b.map((v, i) => v * a[i]));
  b = unit(b.map((v, i) => v - k * a[i]));
  const r = Math.SQRT1_2, s3 = Math.sqrt(3);
  return a.map((v, i) => [(s3 * v + b[i]) * r, (s3 * v - b[i]) * r]);
})();
// shadow length of point p on the line through (0, 0) at angle deg
const PCA_proj = (p, deg) => p[0] * Math.cos(PCA_rad(deg)) + p[1] * Math.sin(PCA_rad(deg));
// variance (divide by n) of the shadows on that line
const PCA_spread = deg => ST.variance(PCA_PTS.map(p => PCA_proj(p, deg)));
const PCA_dots = (g, pts, color = 'blue', r = 4) => pts.forEach(([x, y]) => g.dot(x, y, color, r));

// picture 1: turn a line through the mean; every point drops a shadow on it; read the spread of the shadows
const PCA_W_TURN = h => plane(h, {
  x: [-4.6, 4.6], y: [-4.2, 4.2], equal: true,
  state: { deg: 0, show: false, best: 0, bestV: PCA_spread(0) },
  sliders: [{ key: 'deg', label: 'زاویه‌ی خط:', min: 0, max: 175, step: 5 }],
  onSlide: s => { const v = PCA_spread(s.deg); if (v > s.bestV + 1e-9) { s.bestV = v; s.best = s.deg; } },
  buttons: [{ label: 'PC1 و PC2 را نشان بده', on: s => { s.show = !s.show; }, active: s => s.show }],
  draw: (g, s) => {
    g.grid();
    const c = Math.cos(PCA_rad(s.deg)), sn = Math.sin(PCA_rad(s.deg));
    g.line(-6 * c, -6 * sn, 6 * c, 6 * sn, 'orange', 3);
    PCA_PTS.forEach(p => { const t = PCA_proj(p, s.deg); g.line(p[0], p[1], t * c, t * sn, 'muted', 1, [3, 4]); });
    PCA_dots(g, PCA_PTS);
    PCA_PTS.forEach(p => { const t = PCA_proj(p, s.deg); g.dot(t * c, t * sn, 'green', 3.5); });
    if (s.show) {
      const a = Math.sqrt(3) * 1.6 * Math.SQRT1_2, b = 1.6 * Math.SQRT1_2;
      g.arrow(0, 0, a, a, 'green', 6); g.text(a, a, 'PC1', 'green', 'left', -10);
      g.arrow(0, 0, -b, b, 'red', 5); g.text(-b, b, 'PC2', 'red', 'right', -10);
    }
    g.dot(0, 0, 'red', 6);
  },
  read: s => {
    const v = PCA_spread(s.deg);
    const head = `پخشِ سایه‌ها (واریانس): <b style="color:var(--green)">${fa(v)}</b> &nbsp;|&nbsp; بیشترین تا حالا: <b>${fa(s.bestV)}</b> در ${fa(s.best)}°<br>`;
    if (s.deg === 45) return head + '<b style="color:var(--green)">بیشترین پخشِ ممکن! این جهت PC1 است.</b> هیچ زاویه‌ای سایه‌ها را بیشتر از این باز نمی‌کند.';
    if (s.deg === 135) return head + '<b style="color:var(--red)">کمترین پخش.</b> این جهت PC2 است: درست عمود بر PC1.';
    return head + (v > 2.8 ? 'خیلی نزدیک شدید؛ کمی دیگر بچرخانید.' : 'خط را بچرخانید تا سایه‌های سبز بیشترین پخش را داشته باشند.');
  },
});

// picture 2: keep 2 components (exact), only PC1, or only PC2; points slide to their rebuilt place
const PCA_U1 = [Math.SQRT1_2, Math.SQRT1_2], PCA_U2 = [Math.SQRT1_2, -Math.SQRT1_2];
const PCA_keep = (p, mode) => {
  if (mode === 'both') return [p[0], p[1]];
  const u = mode === 'pc1' ? PCA_U1 : PCA_U2, t = p[0] * u[0] + p[1] * u[1];
  return [t * u[0], t * u[1]];
};
const PCA_MODES = { both: 'هر دو مؤلفه', pc1: 'فقط PC1', pc2: 'فقط PC2' };
const PCA_W_REBUILD = h => plane(h, {
  x: [-4.6, 4.6], y: [-4.2, 4.2], equal: true,
  state: { mode: 'both', cur: PCA_PTS.map(p => [...p]) },
  buttons: Object.keys(PCA_MODES).map(m => ({ label: PCA_MODES[m], on: s => { s.mode = m; }, active: s => s.mode === m })),
  tick: (s, dt) => {
    const k = Math.min(1, dt * 6);
    s.cur.forEach((c, i) => { const t = PCA_keep(PCA_PTS[i], s.mode); c[0] += (t[0] - c[0]) * k; c[1] += (t[1] - c[1]) * k; });
  },
  draw: (g, s) => {
    g.grid();
    g.line(-6, -6, 6, 6, 'green', 2, [6, 6]); g.text(3.4, 3.4, 'PC1', 'green', 'left', 4);
    g.line(-6, 6, 6, -6, 'red', 2, [6, 6]); g.text(-3.4, 3.4, 'PC2', 'red', 'right', 4);
    if (s.mode !== 'both') {
      g.ctx.globalAlpha = 0.3; PCA_dots(g, PCA_PTS, 'muted', 4); g.ctx.globalAlpha = 1;
      PCA_PTS.forEach((p, i) => g.line(p[0], p[1], s.cur[i][0], s.cur[i][1], 'red', 1));
    }
    PCA_dots(g, s.cur);
    g.dot(0, 0, 'red', 5);
  },
  read: s => {
    const kept = s.mode === 'both' ? 4 : s.mode === 'pc1' ? 3 : 1;
    const mse = ST.mean(PCA_PTS.map(p => { const q = PCA_keep(p, s.mode); return (p[0] - q[0]) ** 2 + (p[1] - q[1]) ** 2; }));
    const nums = s.mode === 'both' ? 'هر نقطه ۲ عدد' : 'هر نقطه فقط <b>۱ عدد</b> (طولِ سایه‌اش)';
    return `${nums} &nbsp;|&nbsp; پخشِ نگه‌داشته: <b style="color:var(--green)">${fa(kept * 25)}٪</b><br>` +
      `میانگینِ مربعِ خطا (MSE): <b style="color:var(--red)">${fa(mse)}</b>` +
      (s.mode === 'both' ? '؛ همه‌چیز دقیقاً سر جایش است.' : s.mode === 'pc1' ? '؛ همان λ₂ = ۱ که دور ریختیم.' : '؛ همان λ₁ = ۳ که دور ریختیم. جهتِ اشتباه را نگه داشتیم!');
  },
});

