// ---------- Interview mission: Why not MSE for classification? ----------
// (names start with MMSE_ because all lesson files share one global scope)

// One example with y = 1. p = σ(z) = the model's probability of "yes".
// log loss −ln p, its push on the score z: |∂/∂z| = 1 − p   (∂/∂z = p − y)
// MSE (1 − p)², its push on z:            |∂/∂z| = 2p(1 − p)²   (∂/∂z = 2(p − y)·p(1 − p))
// Checked in node: p 0.01 → losses 4.605 / 0.980, pushes 0.990 / 0.0196 (×50.5)
//                  p 0.5  → 0.693 / 0.250, pushes 0.5 / 0.25 · p 0.9 → 0.105 / 0.010, pushes 0.1 / 0.018
//                  p 0.001 → 6.908 / 0.998, pushes 0.999 / 0.002 (×500)
// by score z: z −4 → log 4.018, MSE 0.964 · z 0 → 0.693 / 0.25 · z 4 → 0.018 / 0.000
const MMSE_sig = z => 1 / (1 + Math.exp(-z));
// decimal with Persian digits and d places (fa() rounds to 2 places)
const MMSE_dec = (x, d) => x.toFixed(d).replace('-', '−').replace('.', '٫').replace(/\d/g, k => '۰۱۲۳۴۵۶۷۸۹'[k]);
const MMSE_gLog = p => 1 - p, MMSE_gMse = p => 2 * p * (1 - p) ** 2;

// ---- Picture 1: slide p for a y = 1 example; how hard each loss pushes the model ----
const MMSE_W_PUSH = h => plane(h, {
  x: [-0.08, 1.04], y: [-0.12, 1.1], ratio: 0.8,
  state: { p: 0.5 },
  sliders: [{ key: 'p', label: 'p (احتمالی که مدل به «بله» داد):', min: 0.01, max: 0.99, step: 0.01 }],
  draw: (g, s) => {
    [0, 0.25, 0.5, 0.75, 1].forEach(x => { g.line(x, 0, x, 1.05, 'soft', 1); g.text(x, 0, fa(x), 'muted', 'center', 13); });
    [0.5, 1].forEach(y => { g.line(0, y, 1, y, 'soft', 1); g.text(-0.015, y, fa(y), 'muted', 'right', 0); });
    g.line(0, 0, 1.02, 0, 'line', 2);
    g.line(0, 0, 0, 1.08, 'line', 2);
    g.fn(MMSE_gLog, 'orange', 4, 0, 1);
    g.fn(MMSE_gMse, 'muted', 4, 0, 1);
    g.text(0.03, 1.03, 'هُلِ خطای لگاریتمی', 'orange', 'left', 0);
    g.text(0.36, 0.36, 'هُلِ MSE', 'muted', 'left', 0);
    g.line(s.p, 0, s.p, MMSE_gLog(s.p), 'green', 2, [4, 4]);
    g.dot(s.p, MMSE_gLog(s.p), 'orange', 7);
    g.dot(s.p, MMSE_gMse(s.p), 'muted', 7);
  },
  read: s => {
    const a = MMSE_gLog(s.p), b = MMSE_gMse(s.p), r = a / b;
    return `جوابِ درست: <b style="color:var(--blue)">y = ۱</b>. مدل گفت: <b>p = ${fa(s.p)}</b><br>` +
      `خطا: <b style="color:var(--orange)">لگاریتمی ${MMSE_dec(-Math.log(s.p), 3)}</b> · <b style="color:var(--muted)">MSE ${MMSE_dec((1 - s.p) ** 2, 4)}</b><br>` +
      `اندازه‌ی گرادیان (هُل): <b style="color:var(--orange)">${MMSE_dec(a, 3)}</b> در برابرِ <b style="color:var(--muted)">${MMSE_dec(b, 4)}</b>` +
      ` ← خطای لگاریتمی <b>${fa(Math.round(r * 10) / 10)}</b> برابر محکم‌تر هُل می‌دهد.` +
      (s.p >= 0.9 ? '<br><span class="muted">هر دو هُل کوچک‌اند؛ مدل تقریباً درست گفته و کارِ زیادی نمانده.</span>' : '') +
      (s.p <= 0.05 ? '<br><span style="color:var(--red)">اشتباهِ با اطمینان: MSE تقریباً هیچ هُلی نمی‌دهد، درست وقتی که بیشترین نیاز را داریم.</span>' : '');
  },
});

// ---- Picture 2: both losses against the score z (y = 1): a smooth slide vs a plateau ----
const MMSE_W_SHAPE = h => plane(h, {
  x: [-5.3, 5.3], y: [-0.4, 5.4], ratio: 0.8,
  state: { z: -4 },
  sliders: [{ key: 'z', label: 'z (امتیازِ مدل):', min: -5, max: 5, step: 0.5 }],
  draw: (g, s) => {
    for (let k = -4; k <= 4; k += 2) { g.line(k, 0, k, 5.3, 'soft', 1); g.text(k, 0, fa(k), 'muted', 'center', 13); }
    [1, 2, 3, 4, 5].forEach(y => { g.line(-5.3, y, 5.3, y, 'soft', 1); g.text(-5.2, y, fa(y), 'muted', 'left', -8); });
    g.line(-5.3, 0, 5.3, 0, 'line', 2);
    g.fn(z => Math.log(1 + Math.exp(-z)), 'orange', 4);
    g.fn(z => (1 - MMSE_sig(z)) ** 2, 'muted', 4);
    g.text(-1.6, 3.3, 'خطای لگاریتمی', 'orange', 'left', 0);
    g.text(-5, 1.35, 'MSE: فلات', 'muted', 'left', 0);
    const l = Math.log(1 + Math.exp(-s.z)), q = (1 - MMSE_sig(s.z)) ** 2;
    g.dot(s.z, l, 'orange', 7);
    g.dot(s.z, q, 'muted', 7);
  },
  read: s => {
    const p = MMSE_sig(s.z);
    return `${E(`p = σ(${String(s.z).replace('-', '−')})`)} = <b>${MMSE_dec(p, 3)}</b> (جوابِ درست y = ۱)<br>` +
      `شیب نسبت به z: <b style="color:var(--orange)">لگاریتمی ${MMSE_dec(p - 1, 3)}</b> · <b style="color:var(--muted)">MSE ${MMSE_dec(-2 * p * (1 - p) ** 2, 4)}</b><br>` +
      (s.z <= -2 ? 'سمتِ چپ (اشتباهِ با اطمینان): منحنیِ MSE روی فلاتی نزدیکِ ۱ صاف شده؛ گرادیان کاهشی آن‌جا قدمی برنمی‌دارد.'
        : 'منحنیِ نارنجی همه‌جا رو به بالا خم است (محدب). منحنیِ خاکستری یک‌جا رو به پایین خم است و یک‌جا رو به بالا: محدب نیست.');
  },
});

