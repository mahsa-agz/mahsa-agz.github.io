// ---------- Interview mission: What is a p-value? ----------
// (names start with MPV_ because all lesson files share one global scope)

// A fair coin, 100 flips. P(k heads) = C(100, k) / 2^100 (exact). Two-sided p = P(|K − 50| ≥ |k − 50|).
// Checked in node: k 55 → 0.368, 58 → 0.133, 59 → 0.089, 60 → 0.057, 61 → 0.035, 62 → 0.021, 65 → 0.0035, 70 → 0.0001
// So the α = 0.05 border falls between 60 and 61 (and between 39 and 40).
// Elsewhere: 20 flips, 16+ or 4− heads = 2 × 6196 = 12392 / 1048576 ≈ 0.012 (two-sided, same as the picture); 20 tests at α = 0.05: 1 − 0.95^20 ≈ 0.64.
const MPV_N = 100;
const MPV_PK = (() => { const p = [1]; for (let k = 1; k <= MPV_N; k++) p.push(p[k - 1] * (MPV_N - k + 1) / k); return p.map(v => v / 2 ** MPV_N); })();
const MPV_p = k => { const d = Math.abs(k - 50); let s = 0; MPV_PK.forEach((v, j) => { if (Math.abs(j - 50) >= d) s += v; }); return Math.min(1, s); };
const MPV_dig = str => str.replace('.', '٫').replace(/\d/g, d => '۰۱۲۳۴۵۶۷۸۹'[d]);
const MPV_show = v => (v < 0.001 ? 'کمتر از ۰٫۰۰۱' : MPV_dig(v.toFixed(3)));
const MPV_bell = x => Math.exp(-((x - 50) ** 2) / 50) / (5 * Math.sqrt(2 * Math.PI)); // normal curve, mean 50, σ = 5

// ---- Picture: drag the observed number of heads; bars as far from 50 or farther (both sides) are red ----
const MPV_W_BELL = h => plane(h, {
  x: [27, 73], y: [-0.014, 0.092], ratio: 0.62,
  state: { k: 58 },
  handles: [{ get: s => [s.k, 0], set: (s, x) => { s.k = Math.max(30, Math.min(70, Math.round(x))); }, color: 'red' }],
  draw: (g, s) => {
    const d = Math.abs(s.k - 50);
    for (let k = 30; k <= 70; k++) {
      const far = Math.abs(k - 50) >= d;
      g.rect(k - 0.4, 0, k + 0.4, MPV_PK[k], far ? 'red' : 'blue', far ? 0.85 : 0.3);
    }
    g.fn(MPV_bell, 'orange', 2, 28, 72);
    g.line(27, 0, 73, 0, 'line', 2);
    [39.5, 60.5].forEach(c => g.line(c, 0, c, 0.088, 'muted', 1.5, [5, 4]));
    [30, 40, 50, 60, 70].forEach(v => g.text(v, 0, fa(v), 'muted', 'center', 24));
    g.text(s.k, MPV_PK[s.k], `${fa(s.k)} شیر`, 'red', 'center', -14);
  },
  read: s => {
    const p = MPV_p(s.k), d = Math.abs(s.k - 50);
    const verdict = p <= 0.05 ? 'p ≤ ۰٫۰۵ ← «معنادار»: فقط شانس، توضیحِ ضعیفی است.' : 'p > ۰٫۰۵ ← «معنادار نیست»: شانسِ تنها به‌راحتی این را می‌سازد.';
    return `اگر سکه سالم باشد، سهمِ آزمایش‌هایی که دست‌کم ${fa(d)} تا از ۵۰ دورند (هر دو سمت، <b style="color:var(--red)">قرمز</b>): <b>p ≈ ${MPV_show(p)}</b><br>` +
      `${verdict}<br><span class="muted">خطِ‌چین = مرزِ ۰٫۰۵ (بین ۶۰ و ۶۱، و بین ۳۹ و ۴۰).</span>`;
  },
});

