// softmax with a temperature T: scores are divided by T first
const TRF_softmax = (z, T = 1) => { const v = z.map(x => x / T), m = Math.max(...v), e = v.map(x => Math.exp(x - m)), s = e.reduce((a, b) => a + b, 0); return e.map(x => x / s); };
const TRF_pct = p => (p < 0.005 ? 'کمتر از ۱٪' : fa(Math.round(p * 100)) + '٪');

