// hand-made scores (not from a real model); every candidate fits after any word of the previous step
const TRF_PROMPT = 'امروز هوا خیلی';
const TRF_STEPS = [
  { w: ['گرم', 'سرد', 'خوب', 'ابری', 'بد', 'شیرین'], z: [2, 1.6, 1.2, 0.6, 0.2, -2] },
  { w: ['است', 'بود', 'شده', 'نیست', 'می‌شود', 'شد'], z: [2.2, 1.5, 0.8, 0.3, 0, -0.3] },
  { w: ['.', 'و', '!', 'اما', 'پس', 'که'], z: [2, 1.4, 0.8, 0.5, 0, -0.5] },
];
const TRF_LABEL = { '.': 'نقطه', '!': 'تعجب' };
const TRF_rowY = i => 5.9 - i;
const TRF_pick = (s, greedy) => {
  if (s.step >= TRF_STEPS.length) return;
  const st = TRF_STEPS[s.step], p = TRF_softmax(st.z, s.T);
  let k = 0;
  if (greedy) k = p.indexOf(Math.max(...p));
  else { let r = Math.random(); k = p.length - 1; for (let i = 0; i < p.length; i++) { r -= p[i]; if (r < 0) { k = i; break; } } }
  s.words.push(st.w[k]); s.last = { w: st.w[k], p: p[k] }; s.step++;
};

