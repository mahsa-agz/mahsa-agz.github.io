// ---------- Vectors & Matrices: Eigenvalues ----------
// uses vecPlane from lessons/vectors.js
const EIG_SPAN = (c, t) => `<span style="color:var(--${c})">${t}</span>`;
// a matrix (list of rows) drawn as a small grid with brackets
const EIG_G = rows => `<span class="eq" style="display:inline-grid;grid-template-columns:repeat(${rows[0].length},auto);gap:0 .6em;padding:0 .35em;` +
  `border-left:2px solid currentColor;border-right:2px solid currentColor;border-radius:4px;vertical-align:middle;line-height:1.25;text-align:center">` +
  rows.flat().map(x => `<span>${typeof x === 'number' ? fa(x) : x}</span>`).join('') + '</span>';

// the lesson's machine A = [[2, 1], [1, 2]]: eigenvalue 3 along [1, 1], eigenvalue 1 along [1, −1]
const EIG_A = [2, 1, 1, 2];
const EIG_AM = EIG_G([[2, 1], [1, 2]]);
const EIG_apply = (x, y) => [EIG_A[0] * x + EIG_A[1] * y, EIG_A[2] * x + EIG_A[3] * y];
const EIG_rad = d => d * Math.PI / 180;
// angle (0..90) between direction `deg` and the line through angle `lineDeg`
const EIG_toLine = (deg, lineDeg) => { const d = ((deg - lineDeg) % 180 + 180) % 180; return Math.min(d, 180 - d); };
// the four eigen-directions of A, as slider angles
const EIG_DIRS = { 45: [3, V(1, 1)], 135: [1, V(-1, 1)], 225: [3, V(-1, -1)], 315: [1, V(1, -1)] };
// faint eigen-lines: λ = 3 along [1, 1] (green), λ = 1 along [1, −1] (muted)
const EIG_lines = (g, which) => {
  if (which.has(3)) { g.line(-4.4, -4.4, 4.4, 4.4, 'green', 2, [6, 6]); g.text(3.6, 3.6, 'λ = ۳', 'green', 'right', -4); }
  if (which.has(1)) { g.line(-4.4, 4.4, 4.4, -4.4, 'muted', 2, [6, 6]); g.text(-3.6, 3.6, 'λ = ۱', 'muted', 'left', -4); }
};

// picture 1: turn v with a slider; Av is drawn; on an eigen-direction both arrows lie on one line
const EIG_L = 1.4;
const EIG_W_FIND = h => vecPlane(h, {
  labels: true,
  state: { deg: 0, show: false, found: new Set() },
  sliders: [{ key: 'deg', label: 'زاویه‌ی v:', min: 0, max: 345, step: 15 }],
  buttons: [{ label: 'خط‌های ویژه را نشان بده', on: s => { s.show = !s.show; }, active: s => s.show }],
  draw: (g, s) => {
    g.grid();
    const e = EIG_DIRS[s.deg];
    if (e) s.found.add(e[0]);
    EIG_lines(g, s.show ? new Set([1, 3]) : s.found);
    const x = EIG_L * Math.cos(EIG_rad(s.deg)), y = EIG_L * Math.sin(EIG_rad(s.deg));
    const [ax, ay] = EIG_apply(x, y);
    g.arrow(0, 0, ax, ay, 'green', 9);
    g.arrow(0, 0, x, y, 'blue', 4);
    g.text(ax, ay, 'Av', 'green', 'center', ay >= 0 ? -14 : 14);
    if (!e || e[0] !== 1) g.text(x, y, 'v', 'blue', 'center', y >= 0 ? -14 : 14);
    g.dot(0, 0, 'ink', 5);
  },
  read: s => {
    const e = EIG_DIRS[s.deg];
    const A = EIG_SPAN('orange', EIG_AM);
    if (e) return `<b style="color:var(--green)">بردار ویژه!</b> v در جهت ${E(e[1])} است و ${E(`${A} · v = ${fa(e[0])} · v`)}<br>` +
      (e[0] === 3 ? 'Av روی همان خط ماند و <b>۳ برابر</b> بلندتر شد: <b>λ = ۳</b>.' : 'Av روی همان خط ماند و طولش هم عوض نشد: <b>λ = ۱</b>.') +
      ` پیدا کرده‌اید: ${fa(s.found.size)} خط از ۲ خط.`;
    const x = Math.cos(EIG_rad(s.deg)), y = Math.sin(EIG_rad(s.deg));
    const [ax, ay] = EIG_apply(x, y);
    let d = Math.atan2(ay, ax) * 180 / Math.PI - s.deg;
    d = ((d % 360) + 540) % 360 - 180;
    return `${E(`${A} · v`)}<br>Av نسبت به v حدود <b>${fa(Math.round(Math.abs(d)))} درجه</b> چرخید؛ هنوز روی یک خط نیستند.`;
  },
});

// picture 2: multiply by A again and again; the arrow (drawn at one fixed length) swings toward the λ = 3 line
const EIG_start = s => {
  let a;
  do a = Math.random() * 360; while (EIG_toLine(a, 135) < 20 || EIG_toLine(a, 45) < 25);
  s.x = Math.cos(EIG_rad(a)); s.y = Math.sin(EIG_rad(a)); s.k = 0; s.hist = []; s.r = 0;
};
const EIG_step = s => {
  const [ax, ay] = EIG_apply(s.x, s.y), r = Math.hypot(ax, ay);
  s.hist.push([s.x, s.y]); if (s.hist.length > 6) s.hist.shift();
  s.x = ax / r; s.y = ay / r; s.k++; s.r = r;
};
const EIG_W_POWER = h => vecPlane(h, {
  labels: true,
  state: { x: Math.cos(EIG_rad(340)), y: Math.sin(EIG_rad(340)), k: 0, hist: [], r: 0 },
  buttons: [{ label: 'دوباره در A ضرب کن', on: EIG_step }, { label: 'پیکان تازه', on: EIG_start }],
  draw: (g, s) => {
    g.grid();
    EIG_lines(g, new Set([1, 3]));
    g.ctx.globalAlpha = 0.35;
    s.hist.forEach(([x, y]) => g.arrow(0, 0, 3 * x, 3 * y, 'muted', 3));
    g.ctx.globalAlpha = 1;
    g.arrow(0, 0, 3 * s.x, 3 * s.y, 'blue', 6);
    g.dot(0, 0, 'ink', 5);
  },
  read: s => {
    const a = EIG_toLine(Math.atan2(s.y, s.x) * 180 / Math.PI, 45);
    const where = a < 0.5 ? '<b style="color:var(--green)">روی خط λ = ۳ نشست. قوی‌ترین جهت برنده شد.</b>'
      : `فاصله تا خط سبز: <b>${fa(a < 10 ? Math.round(a * 10) / 10 : Math.round(a))} درجه</b>`;
    return `تعداد ضرب‌ها: <b>${fa(s.k)}</b>. ${where}` +
      (s.k ? `<br>در این ضرب، طول واقعی پیکان <b>${fa(s.r)}</b> برابر شد (در تصویر، طول را ثابت نگه می‌داریم).` : '');
  },
});

