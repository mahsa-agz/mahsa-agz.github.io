// ---------- Probability: Maximum Likelihood ----------
// (names start with MLE_ because all lesson files share one global scope)

// decimal with Persian digits and d places (fa() rounds to 2 places, too coarse for tiny likelihoods)
const MLE_dec = (x, d) => x.toFixed(d).replace('-', '−').replace('.', '٫').replace(/\d/g, k => '۰۱۲۳۴۵۶۷۸۹'[k]);
// scientific form for inside E(), as LaTeX: "2.2 \times 10^{-27}"
const MLE_sci = x => {
  if (!x) return '0';
  const e = Math.floor(Math.log10(x)), m = x / 10 ** e;
  return String.raw`${m.toFixed(1)} \times 10^{${e}}`;
};

// ---- Picture 1: likelihood curve L(p) = p^h (1−p)^t for fixed coin data; slider = candidate p ----
const MLE_DATA = [{ h: 7, t: 3, label: '۷ شیر از ۱۰' }, { h: 2, t: 8, label: '۲ شیر از ۱۰' }, { h: 70, t: 30, label: '۷۰ شیر از ۱۰۰' }];
// log-likelihood (works for 100 flips without underflow); log(0) = −Infinity gives L = 0
const MLE_logL = (p, h, t) => h * Math.log(p) + t * Math.log(1 - p);

const MLE_W_COIN = h => plane(h, {
  x: [-0.14, 1.06], y: [-0.2, 1.18], ratio: 0.7,
  state: { p: 0.5, d: 0 },
  sliders: [{ key: 'p', label: 'p (شانسِ شیرِ نامزد):', min: 0, max: 1, step: 0.01 }],
  buttons: MLE_DATA.map((d, k) => ({ label: d.label, on: s => { s.d = k; }, active: s => s.d === k })),
  draw: (g, s) => {
    const { h: H, t: T } = MLE_DATA[s.d], top = H / (H + T), lmax = MLE_logL(top, H, T);
    const rel = p => Math.exp(MLE_logL(p, H, T) - lmax); // height scaled so the peak = 1
    [0, 0.25, 0.5, 0.75, 1].forEach(x => { g.line(x, 0, x, 1.05, 'soft', 1); g.text(x, 0, fa(x), 'muted', 'center', 13); });
    g.line(-0.02, 0, 1.02, 0, 'line', 2);
    g.text(-0.03, 1, 'قله', 'muted', 'right', 0);
    g.line(0, 1, 1, 1, 'soft', 1, [4, 5]);
    g.line(top, 0, top, 1, 'red', 2, [6, 5]);
    g.fn(rel, 'orange', 3, 0, 1);
    const y = rel(s.p);
    g.line(s.p, 0, s.p, y, 'green', 3);
    g.dot(s.p, y, 'green', 7);
  },
  read: s => {
    const { h: H, t: T } = MLE_DATA[s.d], n = H + T, top = H / n;
    const L = Math.exp(MLE_logL(s.p, H, T)), rel = Math.exp(MLE_logL(s.p, H, T) - MLE_logL(top, H, T));
    const val = n <= 10 ? MLE_dec(L, 6) : E(MLE_sci(L));
    return `داده: <b style="color:var(--blue)">${fa(H)} شیر، ${fa(T)} خط</b>. اگر شانسِ شیر <b>${fa(s.p)}</b> بود:<br>` +
      `${E('L(p)')} = <b style="color:var(--green)">${val}</b> ؛ یعنی <b>${rel > 0 && rel < 0.005 ? "کمتر از ۱" : fa(Math.round(rel * 100))}٪</b> قله.<br>` +
      `قله (خط‌چینِ <b style="color:var(--red)">قرمز</b>) در ${E(String.raw`p = \frac{h}{n}`)} = ${fa(H)} ÷ ${fa(n)} = <b>${fa(top)}</b>؛ همان سهمِ شیرها.` +
      (Math.abs(s.p - top) < 0.005 ? '<br>همین‌جا قله است: بهترین حدس.' : '');
  },
});

// ---- Picture 2: 8 fixed data points under a bell with fixed σ; slider = μ ----
const MLE_PTS = [1.5, 2.5, 3, 3.5, 4, 4.5, 5, 8]; // mean = 4
const MLE_SD = 1.5;

const MLE_W_BELL = h => plane(h, {
  x: [-0.6, 9.2], y: [-0.08, 0.33], ratio: 0.65,
  state: { mu: 2 },
  sliders: [{ key: 'mu', label: 'μ (مرکزِ زنگوله):', min: 0, max: 8, step: 0.25 }],
  draw: (g, s) => {
    g.line(-0.5, 0, 9.1, 0, 'line', 2);
    for (let k = 0; k <= 9; k++) g.text(k, 0, fa(k), 'muted', 'center', 30);
    g.fn(x => ST.normal(x, s.mu, MLE_SD), 'orange', 3);
    MLE_PTS.forEach(x => {
      const y = ST.normal(x, s.mu, MLE_SD);
      g.line(x, 0, x, y, 'green', 3);
      g.dot(x, y, 'green', 4);
      g.dot(x, 0, 'blue', 6);
    });
    drawMarker(g, s.mu, 0, 'red');
  },
  read: s => {
    const hs = MLE_PTS.map(x => ST.normal(x, s.mu, MLE_SD));
    const ll = ST.sum(hs.map(Math.log)), prod = hs.reduce((a, b) => a * b, 1);
    const sq = ST.sum(MLE_PTS.map(x => (x - s.mu) ** 2));
    return `درست‌نمایی = ضربِ ۸ ارتفاعِ سبز: ${E(MLE_sci(prod))}<br>` +
      `جمعِ لگاریتمِ ارتفاع‌ها: ${E(String.raw`\ln L`)} = <b style="color:var(--green)">${MLE_dec(ll, 2)}</b> <span class="muted">(بزرگ‌تر = جورتر)</span><br>` +
      `جمعِ مربعِ فاصله‌ها تا مرکز: ${E(String.raw`\sum (x - \mu)^2`)} = <b>${fa(sq)}</b> <span class="muted">(کوچک‌تر = نزدیک‌تر)</span>` +
      (s.mu === 4 ? `<br>اینجا قله است: ${E(String.raw`\mu = 4`)}، یعنی <b>میانگینِ داده‌ها</b>. کمترین جمعِ مربع‌ها هم همین‌جاست.` : '');
  },
});

