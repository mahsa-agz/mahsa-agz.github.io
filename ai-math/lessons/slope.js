// ---------- Foundations: Slope ----------
const clamp = (v, a, b) => Math.max(a, Math.min(b, v));
const signed = n => (n ? (n < 0 ? '− ' : '+ ') + fa(Math.abs(n)) : '');
// numbers inside LaTeX use Latin digits
const SLOPE_n = n => String(Math.round(n * 100) / 100);
// f(x) = ax + b as LaTeX, without "1x", "+ 0" or "+ -2"
const SLOPE_line = (a, b) => {
  const ax = a === 0 ? '' : a === 1 ? 'x' : a === -1 ? '-x' : `${SLOPE_n(a)}x`;
  const bs = b === 0 ? '' : ax ? (b > 0 ? ` + ${b}` : ` - ${-b}`) : String(b);
  return `f(x) = ${ax}${bs}` + (ax || bs ? '' : '0');
};

// two draggable points with the rise / run triangle
const W_TWO = h => plane(h, {
  x: [-0.6, 8.6], y: [-0.6, 6.6], equal: true, snap: 1, labels: true,
  state: { ax: 1, ay: 1, bx: 5, by: 3 },
  handles: [
    { get: s => [s.ax, s.ay], set: (s, x, y) => { s.ax = clamp(x, 0, 8); s.ay = clamp(y, 0, 6); }, color: 'ink' },
    { get: s => [s.bx, s.by], set: (s, x, y) => { s.bx = clamp(x, 0, 8); s.by = clamp(y, 0, 6); }, color: 'orange' },
  ],
  draw: (g, s) => {
    g.grid();
    const dx = s.bx - s.ax, dy = s.by - s.ay;
    if (dx) { const m = dy / dx; g.fn(x => s.ay + m * (x - s.ax), 'orange', 2); }
    else g.line(s.ax, -1, s.ax, 7, 'orange', 2);
    g.line(s.ax, s.ay, s.bx, s.ay, 'blue', 4);
    g.line(s.bx, s.ay, s.bx, s.by, 'green', 4);
    if (dx) g.text((s.ax + s.bx) / 2, s.ay, `جلو ${fa(dx)}`, 'blue', 'center', dy > 0 ? 14 : -14);
    if (dy) g.text(s.bx + (dx >= 0 ? 0.2 : -0.2), (s.ay + s.by) / 2, `${dy > 0 ? 'بالا' : 'پایین'} ${fa(Math.abs(dy))}`, 'green', dx >= 0 ? 'left' : 'right', 0);
  },
  read: s => {
    const dx = s.bx - s.ax, dy = s.by - s.ay;
    if (!dx) return 'خط عمودی: اصلاً جلو نرفته‌ایم. هیچ عددی را نمی‌شود بر صفر تقسیم کرد، پس برای خط عمودی <b>شیب تعریف نمی‌شود</b>.';
    const m = dy / dx, exact = Math.abs(m * 100 - Math.round(m * 100)) < 1e-9;
    const note = m > 0 ? 'مثبت: سربالایی' : m < 0 ? 'منفی: سرازیری' : 'صفر: کاملاً صاف';
    const say = m ? `با هر ۱ قدم جلو، ${fa(Math.abs(m))} ${m > 0 ? 'بالا' : 'پایین'} می‌رویم` : 'با جلو رفتن، اصلاً بالا و پایین نمی‌رویم';
    return `شیب = <b style="color:var(--green)">بالا</b> تقسیم بر <b style="color:var(--blue)">جلو</b> = ${E(String.raw`\frac{${dy}}{${dx}} ${exact ? '=' : '\\approx'} ${SLOPE_n(m)}`)}<br>${say}. (${note})`;
  },
});

// a line f(x) = ax + b with sliders; the same 1-step triangle drawn in two places
const W_LINE = h => plane(h, {
  x: [-4.5, 4.5], y: [-4.5, 4.5], equal: true, labels: true,
  state: { a: 1, b: 0 },
  sliders: [{ key: 'a', label: 'a (شیب):', min: -3, max: 3, step: 0.5 }, { key: 'b', label: 'b (شروع):', min: -2, max: 2, step: 1 }],
  draw: (g, s) => {
    g.grid();
    g.fn(x => s.a * x + s.b, 'orange', 4);
    [-3, 1].forEach(x => { const y = s.a * x + s.b; g.line(x, y, x + 1, y, 'blue', 4); g.line(x + 1, y, x + 1, y + s.a, 'green', 4); });
    g.dot(0, s.b, 'red', 7);
  },
  read: s => `${E(SLOPE_line(s.a, s.b))}<br>با هر <b style="color:var(--blue)">۱ قدم به راست</b>، ` +
    (s.a ? `<b style="color:var(--green)">${fa(Math.abs(s.a))} ${s.a > 0 ? 'بالا' : 'پایین'}</b> می‌رویم.` : 'هیچ بالا و پایینی نداریم.') +
    ` هر دو مثلث یک اندازه‌اند. خط در ارتفاع ${fa(s.b)} از محور عمودی رد می‌شود.`,
});

