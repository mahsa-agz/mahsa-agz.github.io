// ---------- Chapter: Vectors ----------
const clampV = (x, y) => [Math.max(-5, Math.min(5, x)), Math.max(-4, Math.min(4, y))];
const vecPlane = (h, extra) => plane(h, { x: [-5.5, 5.5], y: [-4.4, 4.4], equal: true, snap: 1, ...extra });

const W_VEC_ONE = h => vecPlane(h, {
  state: { ax: 3, ay: 2 },
  handles: [{ get: s => [s.ax, s.ay], set: (s, x, y) => { [s.ax, s.ay] = clampV(x, y); }, color: 'blue' }],
  draw: (g, s) => {
    g.grid();
    g.line(0, 0, s.ax, 0, 'muted', 2, [6, 6]); g.line(s.ax, 0, s.ax, s.ay, 'muted', 2, [6, 6]);
    g.arrow(0, 0, s.ax, s.ay, 'blue', 5); g.dot(0, 0, 'ink', 4);
  },
  read: s => {
    const h = s.ax ? `${fa(Math.abs(s.ax))} قدم به ${s.ax > 0 ? 'راست' : 'چپ'}` : '';
    const v = s.ay ? `${fa(Math.abs(s.ay))} قدم به ${s.ay > 0 ? 'بالا' : 'پایین'}` : '';
    return `${[h, v].filter(Boolean).join(' و ') || 'هیچ جابه‌جایی (بردار صفر)'}<br>این پیکان = ${V(s.ax, s.ay)}`;
  },
});

const W_VEC_ADD = h => vecPlane(h, {
  state: { ax: 3, ay: 2, bx: 1, by: 2 },
  handles: [
    { get: s => [s.ax, s.ay], set: (s, x, y) => { [s.ax, s.ay] = clampV(x, y); }, color: 'blue' },
    { get: s => [s.ax + s.bx, s.ay + s.by], set: (s, x, y) => { const [cx, cy] = clampV(x, y); s.bx = cx - s.ax; s.by = cy - s.ay; }, color: 'orange' },
  ],
  draw: (g, s) => {
    g.grid();
    const sx = s.ax + s.bx, sy = s.ay + s.by;
    g.arrow(0, 0, sx, sy, 'green', 7); g.arrow(0, 0, s.ax, s.ay, 'blue', 5); g.arrow(s.ax, s.ay, sx, sy, 'orange', 5);
  },
  read: s => E(`<span style="color:var(--blue)">${V(s.ax, s.ay)}</span> + <span style="color:var(--orange)">${V(s.bx, s.by)}</span> = <span style="color:var(--green)">${V(s.ax + s.bx, s.ay + s.by)}</span>`),
});

const W_VEC_SCALE = h => vecPlane(h, {
  state: { ax: 2, ay: 1, k: 2 },
  sliders: [{ key: 'k', label: 'عدد:', min: -2, max: 3, step: 0.5 }],
  handles: [{ get: s => [s.ax, s.ay], set: (s, x, y) => { [s.ax, s.ay] = clampV(x, y); }, color: 'blue' }],
  draw: (g, s) => { g.grid(); g.arrow(0, 0, s.k * s.ax, s.k * s.ay, 'green', 9); g.arrow(0, 0, s.ax, s.ay, 'blue', 4); },
  read: s => {
    const k = s.k, note = k === 0 ? 'صفر شد: هیچ جابه‌جایی' : k < 0 ? 'جهت برعکس شد' : k < 1 ? 'کوتاه‌تر شد' : k === 1 ? 'تغییری نکرد' : 'بلندتر شد';
    return E(`${fa(k)} × <span style="color:var(--blue)">${V(s.ax, s.ay)}</span> = <span style="color:var(--green)">${V(k * s.ax, k * s.ay)}</span>`) + `<br><b>${note}</b>`;
  },
});

