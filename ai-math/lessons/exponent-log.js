// ---------- Foundations: Exponent & Log ----------
// whole numbers with Persian digits and thousands separators: 1048576 -> ۱٬۰۴۸٬۵۷۶
const EXPLOG_num = n => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, '٬').replace(/\d/g, d => '۰۱۲۳۴۵۶۷۸۹'[d]);
// the same number inside LaTeX: 1048576 -> 1{,}048{,}576
const EXPLOG_tex = n => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, '{,}');
const EXPLOG_MAX = 20; // the slider goes up to 2^20 = 1,048,576

// 2^n as a bar on a normal axis (explodes) or a log axis (a straight line)
const EXPLOG_W_GROW = h => plane(h, {
  x: [-0.8, 21], y: [-0.1, 1.12], ratio: 0.8,
  state: { n: 10, log: false },
  sliders: [{ key: 'n', label: 'چند بار دو برابر (n):', min: 0, max: EXPLOG_MAX, step: 1 }],
  buttons: [
    { label: 'محور معمولی', on: s => { s.log = false; }, active: s => !s.log },
    { label: 'محور لگاریتمی', on: s => { s.log = true; }, active: s => s.log },
  ],
  draw: (g, s) => {
    // height on the canvas: normal = value / 2^20, log = (number of doublings) / 20
    const Yv = v => (s.log ? Math.log2(v) / EXPLOG_MAX : v / 2 ** EXPLOG_MAX);
    const marks = s.log
      ? [[1, '۱'], [10, '۱۰'], [100, '۱۰۰'], [1e3, 'هزار'], [1e4, '۱۰ هزار'], [1e5, '۱۰۰ هزار'], [1e6, '۱ میلیون']]
      : [[25e4, '۲۵۰ هزار'], [5e5, '۵۰۰ هزار'], [75e4, '۷۵۰ هزار'], [1e6, '۱ میلیون']];
    marks.forEach(([v, t]) => { g.line(0, Yv(v), 21, Yv(v), 'soft', 1); g.text(0.2, Yv(v), t, 'muted', 'left', -8); });
    g.line(0, 0, 21, 0, 'line', 2);
    [0, 5, 10, 15, 20].forEach(k => g.text(k, 0, fa(k), 'muted', 'center', 12));
    g.fn(x => Yv(2 ** x), 'orange', 3, 0, EXPLOG_MAX);
    const v = 2 ** s.n, y = Yv(v);
    g.rect(s.n - 0.3, 0, s.n + 0.3, y, 'green', 0.45);
    g.dot(s.n, y, 'red', 6);
    g.text(s.n, y, EXPLOG_num(v), 'red', s.n > 15 ? 'right' : 'center', -14);
  },
  read: s => {
    const v = 2 ** s.n;
    const say = s.log
      ? 'روی محور لگاریتمی، هر دو برابر شدن یک پله‌ی <b>هم‌اندازه</b> است؛ برای همین منحنی انفجاری، یک <b>خط صاف</b> شد.'
      : s.n <= 14 ? 'روی محور معمولی، این هنوز تقریباً <b>صفر</b> دیده می‌شود. n را جلوتر ببرید!'
      : 'حالا منحنی ناگهان بالا رفت: هر قدم، به اندازه‌ی <b>کل مقدار قبلی</b> اضافه می‌کند.';
    return `از ۱ شروع کردیم و ${fa(s.n)} بار دو برابر کردیم: ${E(`2^{${s.n}} = ${EXPLOG_tex(v)}`)} یعنی <b style="color:var(--green)">${EXPLOG_num(v)}</b><br>` +
      `سؤال برعکس (لگاریتم): ${E(String.raw`\log_2(${EXPLOG_tex(v)}) = ${s.n}`)}، یعنی «${fa(s.n)} بار دو برابر»<br>${say}`;
  },
});

// y = 2^x and y = log2(x): the same pair of numbers, swapped; mirror images across y = x
const EXPLOG_W_MIRROR = h => plane(h, {
  x: [-3, 6.2], y: [-3, 6.2], equal: true, labels: true,
  state: { a: 1 },
  sliders: [{ key: 'a', label: 'توان a:', min: -2, max: 2, step: 1 }],
  draw: (g, s) => {
    g.grid();
    g.line(-3, -3, 6.2, 6.2, 'muted', 2, [6, 6]);
    g.fn(x => 2 ** x, 'orange', 4);
    g.fn(x => Math.log2(x), 'green', 4, 0.01, 6.2);
    const b = 2 ** s.a;
    g.line(s.a, b, b, s.a, 'ink', 1.5, [3, 4]);
    g.dot(s.a, b, 'orange', 7);
    g.dot(b, s.a, 'green', 7);
    g.text(1.9, 5.6, '2ˣ', 'orange', 'right', 0);
    g.text(5.6, Math.log2(5.6), 'log₂ x', 'green', 'center', -16);
    g.text(4.6, 4.6, 'y = x', 'muted', 'left', 12);
  },
  read: s => {
    const b = 2 ** s.a, exact = Math.abs(b - +b.toFixed(2)) < 1e-9;
    const bs = exact ? String(+b.toFixed(2)) : b.toFixed(2), eq = exact ? '=' : String.raw`\approx`;
    return `<b style="color:var(--orange)">نارنجی</b>: ${E(`2^{${s.a}} ${eq} ${bs}`)}، نقطه‌ی ${E(`(${s.a}, ${bs})`)}<br>` +
      `<b style="color:var(--green)">سبز</b>: ${E(String.raw`\log_2(${bs}) ${eq} ${s.a}`)}، نقطه‌ی ${E(`(${bs}, ${s.a})`)}<br>` +
      'همان دو عدد، فقط جای ورودی و خروجی عوض شده.' + (s.a < 0 ? ' توان منفی: نتیجه کوچک‌تر از ۱ است، ولی هنوز <b>مثبت</b>.' : '');
  },
});

