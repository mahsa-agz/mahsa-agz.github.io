// ---------- Foundations: Derivative ----------
const dClamp = (v, a, b) => Math.max(a, Math.min(b, v));
// like fa() but keeps up to 4 decimals, so tiny changes stay visible
const fa4 = n => String(+n.toFixed(4)).replace('-', '−').replace('.', '٫').replace(/\d/g, d => '۰۱۲۳۴۵۶۷۸۹'[d]);
// the same for inside LaTeX (Latin digits); negative numbers in brackets when multiplied
const DERIV_n4 = n => String(+n.toFixed(4));
const DERIV_p = n => (n < 0 ? `(${DERIV_n4(n)})` : DERIV_n4(n));
const sq = x => x * x;
const bowl = x => (x - 2) * (x - 2) + 1;

// f(x) = x²: a point P, a gap h, the line through P and P+h; shrink h and the slope goes to 2x
const W_SECANT = h => plane(h, {
  x: [-3, 4], y: [-1.5, 13], step: [1, 2], labels: true, ratio: 0.85,
  state: { p: 1, h: 1.5 },
  sliders: [{ key: 'h', label: 'فاصله h:', min: 0.01, max: 2, step: 0.01 }],
  handles: [{ get: s => [s.p, sq(s.p)], set: (s, x) => { s.p = dClamp(Math.round(x * 2) / 2, -2.5, 1.5); }, color: 'red' }],
  draw: (g, s) => {
    g.grid();
    const q = s.p + s.h, m = (sq(q) - sq(s.p)) / s.h;
    g.fn(x => sq(s.p) + 2 * s.p * (x - s.p), 'muted', 2);
    g.fn(sq, 'orange', 4);
    g.fn(x => sq(s.p) + m * (x - s.p), 'ink', 2);
    g.line(s.p, sq(s.p), q, sq(s.p), 'blue', 4);
    g.line(q, sq(s.p), q, sq(q), 'green', 4);
    g.dot(q, sq(q), 'ink', 6);
    g.text(s.p - 0.25, sq(s.p), 'P', 'red', 'center', -14);
  },
  read: s => {
    const q = s.p + s.h, rise = sq(q) - sq(s.p), m = rise / s.h, n = DERIV_n4;
    return `P روی ${E('x = ' + n(s.p))}، فاصله ${E('h = ' + n(s.h))}<br>` +
      `<b style="color:var(--green)">بالا رفتن</b>: ${E(`${n(sq(q))} - ${n(sq(s.p))} = ${n(rise)}`)}<br>` +
      `شیب خط سیاه: ${E(String.raw`\frac{${n(rise)}}{${n(s.h)}} = ${n(m)}`)}<br>` +
      `شیب دقیق در P (خط کم‌رنگ): ${E(String.raw`2 \times ${DERIV_p(s.p)} = ${n(2 * s.p)}`)}<br>هرچه h کوچک‌تر، این دو شیب به هم نزدیک‌ترند.`;
  },
});

// a bowl-shaped error curve; the tangent's slope says which way is downhill
const W_BOWL = h => plane(h, {
  x: [-1, 5], y: [-0.5, 9.5], step: [1, 1], labels: true, ratio: 0.85,
  state: { p: -0.5 },
  handles: [{ get: s => [s.p, bowl(s.p)], set: (s, x) => { s.p = dClamp(Math.round(x * 2) / 2, -0.5, 4.5); }, color: 'red' }],
  buttons: [
    { label: 'یک قدم سرازیری', on: s => { s.p -= 0.25 * 2 * (s.p - 2); } },
    { label: 'از نو', on: s => { s.p = -0.5; } },
  ],
  draw: (g, s) => {
    g.grid();
    g.fn(bowl, 'orange', 4);
    const m = 2 * (s.p - 2), y = bowl(s.p);
    g.fn(x => y + m * (x - s.p), 'ink', 3, s.p - 1.2, s.p + 1.2);
    if (Math.abs(m) > 0.005) {
      const t = s.p - Math.sign(m) * 0.7;
      g.arrow(s.p, y, t, bowl(t), 'green', 4);
    } else g.text(s.p, y, 'کف', 'green', 'center', 22);
  },
  read: s => {
    const m = 2 * (s.p - 2);
    const say = Math.abs(m) < 0.005 ? 'شیب صفر: این‌جا <b>کف</b> است؛ کمترین خطا.'
      : m < 0 ? 'شیب منفی: منحنی به راست پایین می‌رود ← <b>به راست برو</b>.'
      : 'شیب مثبت: منحنی به راست بالا می‌رود ← <b>به چپ برو</b>.';
    return `جای فعلی: x = ${fa4(s.p)}، خطا = ${fa4(bowl(s.p))}<br>شیب در این نقطه = <b>${fa4(m)}</b>؛ قدم بعدی = ۰٫۲۵ × شیب، خلاف جهتش<br>${say}`;
  },
});

