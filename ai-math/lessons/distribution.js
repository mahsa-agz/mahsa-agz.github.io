// one random student height: around 165 cm, spread 8, whole cm, kept between 145 and 185
const DIST_height = () => { let h; do h = Math.round(ST.randn(165, 8)); while (h < 145 || h > 185); return h; };

const DIST_BINS = [2, 4, 5, 8, 10, 20, 40];
const DIST_SETTLE = '<br><span class="muted">با ۴۰ نفر شکل می‌لرزد؛ با ۴۰۰ نفر آرام می‌گیرد. چون شکل مالِ خودِ پدیده است (قدِ آدم‌ها)، نه مالِ این چند نفر.</span>';

// heights of a class: dot plot that grows, or the same data as a histogram with N bars
const W_DIST_BUILD = h => plane(h, {
  x: [143.5, 186.5], y: [-1.8, 10.6], step: [5, 100], labels: true, ratio: 0.8,
  state: { data: Array.from({ length: 40 }, DIST_height), bars: false, bins: 8 },
  sliders: [{ key: 'bins', label: 'تعداد میله‌ها:', min: 2, max: 40, step: 1 }],
  // only counts that split 145..185 into whole-cm widths: 20, 10, 8, 5, 4, 2, 1 cm
  onSlide: s => { s.bins = DIST_BINS.reduce((a, b) => (Math.abs(b - s.bins) < Math.abs(a - s.bins) ? b : a)); },
  buttons: [
    { label: '۱۰ نفر دیگر', on: s => { if (s.data.length < 400) for (let i = 0; i < 10; i++) s.data.push(DIST_height()); } },
    { label: 'نقطه‌ها', on: s => { s.bars = false; }, active: s => !s.bars },
    { label: 'میله‌ها', on: s => { s.bars = true; }, active: s => s.bars },
  ],
  draw: (g, s) => {
    g.grid();
    if (s.bars) {
      const c = ST.hist(s.data, 145, 185, s.bins);
      drawHist(g, s.data, 145, 185, s.bins, 'blue', 10 / Math.max(...c));
      return;
    }
    const pts = ST.stack(s.data), top = Math.max(...pts.map(p => p.y));
    const base = g.Y(0), room = base - g.Y(10);
    const sp = Math.min(room / top, 2 * Math.min(6, (g.X(1) - g.X(0)) * 0.48) + 1);
    const r = Math.max(1.5, Math.min(6, (g.X(1) - g.X(0)) * 0.48, sp / 2 - 0.4));
    g.ctx.fillStyle = g.css('blue');
    pts.forEach(p => { g.ctx.beginPath(); g.ctx.arc(g.X(p.x), base - (p.y - 0.5) * sp, r, 0, 7); g.ctx.fill(); });
  },
  read: s => {
    const n = s.data.length;
    if (s.bars) {
      const c = ST.hist(s.data, 145, 185, s.bins), w = 40 / s.bins, k = c.indexOf(Math.max(...c));
      return `<b>${fa(n)}</b> دانش‌آموز در <b>${fa(s.bins)}</b> میله. پهنای هر میله: ${fa(w)} سانتی‌متر.<br>` +
        `بلندترین میله: قد ${fa(145 + k * w)} تا ${fa(145 + (k + 1) * w)}، با <b>${fa(c[k])}</b> نفر.` + DIST_SETTLE;
    }
    const cnt = {};
    s.data.forEach(x => { cnt[x] = (cnt[x] || 0) + 1; });
    const best = Object.keys(cnt).reduce((a, b) => (cnt[b] > cnt[a] ? b : a));
    return `<b>${fa(n)}</b> دانش‌آموز. هر نقطه = یک نفر. قدهای برابر روی هم می‌روند.<br>` +
      `رایج‌ترین قد: <b>${fa(+best)}</b> سانتی‌متر (${fa(cnt[best])} نفر). از ${fa(Math.min(...s.data))} تا ${fa(Math.max(...s.data))} پخش شده‌اند.` + DIST_SETTLE;
  },
});

// three typical shapes, from fixed (seeded) data so the text below always matches
const DIST_rng = seed => () => { seed = (seed + 0x6D2B79F5) | 0; let t = Math.imul(seed ^ (seed >>> 15), 1 | seed); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
const DIST_normal = (rnd, m, sd) => m + sd * Math.sqrt(-2 * Math.log(1 - rnd())) * Math.cos(2 * Math.PI * rnd());
const DIST_make = (seed, n, gen, lo, hi) => { const rnd = DIST_rng(seed), a = []; while (a.length < n) { const v = gen(rnd, a.length); if (v >= lo && v <= hi) a.push(v); } return a; };
const DIST_SHAPES = [
  { label: 'قرینه (Symmetric)', lo: 140, hi: 190, unit: 'قدِ ۳۰۰ زن (سانتی‌متر)',
    data: DIST_make(7, 300, r => DIST_normal(r, 162, 6), 140, 190) },
  { label: 'چوله (Skewed)', lo: 0, hi: 30, unit: 'زمان انتظار در بانک برای ۳۰۰ نفر (دقیقه)',
    data: DIST_make(11, 300, r => -5 * Math.log(1 - r()), 0, 30) },
  { label: 'دو قله (Bimodal)', lo: 100, hi: 200, unit: 'قدِ ۱۵۰ بچه‌ی ۷ ساله و ۱۵۰ پدر و مادر (سانتی‌متر)',
    data: DIST_make(5, 300, (r, i) => (i % 2 ? DIST_normal(r, 168, 8) : DIST_normal(r, 122, 5)), 100, 200) },
];

const W_DIST_SHAPES = h => plane(h, {
  x: [-0.6, 10.6], y: [-2.4, 10.6], ratio: 0.8,
  state: { k: 0 },
  buttons: DIST_SHAPES.map((d, i) => ({ label: d.label, on: s => { s.k = i; }, active: s => s.k === i })),
  draw: (g, s) => {
    const d = DIST_SHAPES[s.k], u = d.data.map(v => (v - d.lo) / (d.hi - d.lo) * 10);
    const c = ST.hist(u, 0, 10, 20);
    drawHist(g, u, 0, 10, 20, 'blue', 10 / Math.max(...c));
    g.line(-0.6, 0, 10.6, 0, 'line', 2);
    for (let t = 0; t <= 10; t += 2) { g.line(t, 0, t, -0.3, 'muted', 1); g.text(t, 0, fa(d.lo + (d.hi - d.lo) * t / 10), 'muted', 'center', 30); }
    drawMarker(g, (ST.mean(d.data) - d.lo) / (d.hi - d.lo) * 10, 0, 'red');
  },
  read: s => {
    const d = DIST_SHAPES[s.k], m = ST.mean(d.data), mr = Math.round(m);
    const c = ST.hist(d.data, d.lo, d.hi, 20), top = Math.max(...c);
    const head = `${d.unit}. مثلث <b style="color:var(--red)">قرمز</b> = میانگین (${fa(mr)}).<br>` +
      `بلندترین میله: ${fa(top)} نفر از ${fa(d.data.length)} نفر، یعنی فراوانی نسبیِ <b>${fa(Math.round(100 * top / d.data.length))}٪</b>.<br>`;
    if (s.k === 0) return head + 'یک قله در وسط و دو طرفِ تقریباً یک‌شکل. قدِ خیلی کوتاه و خیلی بلند، هر دو کمیاب‌اند. میانگین درست زیر قله است. <b>چرا این شکل؟</b> قد حاصلِ خیلی عاملِ کوچک است (ژن‌ها، غذا، خواب...) و اثرِ بیشترشان همدیگر را خنثی می‌کنند.';
    if (s.k === 1) {
      const below = Math.round(100 * d.data.filter(v => v < m).length / d.data.length);
      return head + `بیشتر مردم کم منتظر می‌مانند، چند نفر خیلی زیاد: یک <b>دُم بلند به راست</b>. <b>چرا؟</b> انتظار از صفر کمتر نمی‌شود، ولی گاهی خیلی طول می‌کشد. همین چند نفر میانگین را بالا می‌کشند: <b>${fa(below)}٪</b> مردم کمتر از میانگین منتظر ماندند. درآمد و قیمت خانه هم همین شکل را دارند.`;
    }
    const near = d.data.filter(v => Math.abs(v - m) <= 5).length;
    return head + `دو قله، چون <b>دو گروه</b> قاطی شده‌اند: بچه‌ها و بزرگ‌ترها. میانگین در دره‌ی بین دو قله افتاده؛ قدِ فقط <b>${fa(near)}</b> نفر از ۳۰۰ نفر حداکثر ۵ سانتی‌متر با میانگین تفاوت دارد. دو قله یعنی: دنبال گروه‌های پنهان بگردید.`;
  },
});

