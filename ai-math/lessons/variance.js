// ---------- Statistics: Variance & Quartiles ----------
// (names start with VAR_ because all lesson files share one global scope)
// variance divides by n; quartiles use the "median of each half" method (ST in js/stats.js)

const VAR_clamp = (v, a, b) => Math.max(a, Math.min(b, v));
// one decimal; says «حدود» when the value was rounded
const VAR_fa1 = v => { const r = Math.round(v * 10) / 10; return (Math.abs(r - v) > 1e-9 ? 'حدود ' : '') + fa(r); };
// equal values stack upward: how many earlier points share this x
const VAR_level = (p, i) => p.slice(0, i).filter(v => v === p[i]).length;

// two classes, both mean 15: class A fixed and tight, class B stretched by a slider
const VAR_D = [-2, -1, -1, 0, 0, 0, 1, 1, 2];
const VAR_class = k => VAR_D.map(d => 15 + k * d);

const W_VAR_TWO = h => plane(h, {
  x: [7.4, 21], y: [-1.6, 10], ratio: 0.8,
  state: { k: 2 },
  sliders: [{ key: 'k', label: 'پراکندگیِ کلاس ب:', min: 0.5, max: 2.5, step: 0.5 }],
  draw: (g, s) => {
    [[VAR_class(1), 5.6, 'کلاس الف'], [VAR_class(s.k), 0, 'کلاس ب']].forEach(([a, base, name]) => {
      const m = ST.mean(a), sd = ST.std(a);
      g.rect(m - sd, base + 0.1, m + sd, base + 3.1, 'green', 0.15);
      g.line(m - sd, base, m - sd, base + 3.1, 'green', 2, [5, 4]);
      g.line(m + sd, base, m + sd, base + 3.1, 'green', 2, [5, 4]);
      g.line(8, base, 20, base, 'line', 2);
      for (let t = 8; t <= 20; t += 2) g.text(t, base, fa(t), 'muted', 'center', 26);
      a.forEach((x, i) => g.dot(x, base + 0.45 + 0.75 * VAR_level(a, i), 'blue', 7));
      drawMarker(g, m, base, 'red');
      g.text(7.6, base + 3.4, name, 'ink', 'left', 0);
    });
  },
  read: s => {
    const A = VAR_class(1), B = VAR_class(s.k);
    const inA = A.filter(x => Math.abs(x - 15) <= ST.std(A) + 1e-9).length, inB = B.filter(x => Math.abs(x - 15) <= ST.std(B) + 1e-9).length;
    return `میانگینِ هر دو کلاس: <b style="color:var(--red)">۱۵</b>.<br>` +
      `کلاس الف: <b style="color:var(--green)">${E(String.raw`\sigma`)} = ${VAR_fa1(ST.std(A))}</b> &nbsp;|&nbsp; کلاس ب: <b style="color:var(--green)">${E(String.raw`\sigma`)} = ${VAR_fa1(ST.std(B))}</b><br>` +
      `یعنی نمره‌های الف معمولاً ${VAR_fa1(ST.std(A))} نمره و نمره‌های ب ${VAR_fa1(ST.std(B))} نمره از ۱۵ دورند (ب ${fa(s.k)} برابرِ الف).<br>داخل نوار سبز: الف ${fa(inA)} نفر، ب ${fa(inB)} نفر (از ۹ نفر).`;
  },
});

// one dataset with draggable points and its boxplot underneath; points beyond 1.5 × IQR turn red
const VAR_START = [3, 5, 6, 7, 8, 9, 10, 12, 14];
const VAR_out = (p, v) => { const [q1, , q3] = ST.quartiles(p), r = q3 - q1; return v < q1 - 1.5 * r || v > q3 + 1.5 * r; };

const W_VAR_BOX = h => {
  const st = { p: [...VAR_START] };
  return plane(h, {
    x: [-1.2, 31.2], y: [-3.2, 6.6], ratio: 0.6, snap: 1,
    state: st,
    handles: VAR_START.map((_, i) => ({
      get: s => [s.p[i], 1 + 0.9 * VAR_level(s.p, i)],
      set: (s, x) => { s.p[i] = VAR_clamp(x, 0, 30); },
      get color() { return VAR_out(st.p, st.p[i]) ? 'red' : 'blue'; },
    })),
    buttons: [
      { label: 'یکی را خیلی دور ببر', on: s => { const k = s.p.indexOf(Math.max(...s.p)); s.p[k] = 30; } },
      { label: 'از اول', on: s => { s.p = [...VAR_START]; } },
    ],
    draw: (g, s) => {
      for (let t = 0; t <= 30; t++) g.line(t, 0, t, -0.2, 'muted', 1);
      for (let t = 0; t <= 30; t += 5) g.text(t, 0, fa(t), 'muted', 'center', 20);
      g.line(0, 0, 30, 0, 'ink', 2);
      drawBox(g, s.p, -2.1, 0.5, 'blue');
    },
    read: s => {
      const [q1, q2, q3] = ST.quartiles(s.p), lo = Math.min(...s.p), hi = Math.max(...s.p);
      const outs = s.p.filter(v => VAR_out(s.p, v));
      return `دامنه (کلِ پهنا) = ${fa(hi)} − ${fa(lo)} = <b>${fa(hi - lo)}</b> &nbsp;|&nbsp; IQR (پهنای جعبه) = ${fa(q3)} − ${fa(q1)} = <b style="color:var(--blue)">${fa(q3 - q1)}</b><br>` +
        `جعبه از Q1 = ${fa(q1)} تا Q3 = ${fa(q3)}؛ خطِ وسطش میانه = ${fa(q2)}<br>` +
        (outs.length ? `<b style="color:var(--red)">داده‌ی پرت: ${outs.map(fa).join('، ')}</b> (بیش از ${fa(1.5 * (q3 - q1))} واحد بیرونِ جعبه)` : 'داده‌ی پرتی نیست.');
    },
  });
};

