// ---------- Probability: Conditional Probability & Bayes' Rule ----------
// (names start with BAYES_ because all lesson files share one global scope)

const BAYES_pct = p => fa(Math.round(p * 1000) / 10) + '٪';

// ---- Picture 1: 1000 people as small squares; sliders for disease rate, sensitivity, false positives ----
// counts are rounded to whole people
const BAYES_COLS = 40, BAYES_ROWS = 25, BAYES_N = 1000;
const BAYES_count = s => {
  const sick = Math.round(BAYES_N * s.rate / 100), healthy = BAYES_N - sick;
  const sickPos = Math.round(sick * s.sens / 100), healthyPos = Math.round(healthy * s.fp / 100);
  return { sick, healthy, sickPos, sickNeg: sick - sickPos, healthyPos, healthyNeg: healthy - healthyPos };
};

const BAYES_W_GRID = h => plane(h, {
  x: [0, BAYES_COLS], y: [0, BAYES_ROWS], equal: true,
  state: { rate: 1, sens: 99, fp: 5 },
  sliders: [
    { key: 'rate', label: 'بیماری در جمعیت (٪)', min: 1, max: 30, step: 1 },
    { key: 'sens', label: 'آزمایش، بیمار را می‌گیرد (٪)', min: 50, max: 100, step: 1 },
    { key: 'fp', label: 'آزمایش، سالم را مثبت می‌کند (٪)', min: 0, max: 20, step: 1 },
  ],
  draw: (g, s) => {
    const c = BAYES_count(s);
    // order: sick+, sick−, healthy+, healthy−
    const groups = [[c.sickPos, 'green'], [c.sickNeg, 'accent'], [c.healthyPos, 'red'], [c.healthyNeg, 'soft']];
    let k = 0;
    groups.forEach(([n, color]) => {
      for (let i = 0; i < n; i++, k++) {
        const col = k % BAYES_COLS, row = BAYES_ROWS - 1 - Math.floor(k / BAYES_COLS);
        g.rect(col + 0.12, row + 0.12, col + 0.88, row + 0.88, color, 1);
      }
    });
  },
  read: s => {
    const c = BAYES_count(s), pos = c.sickPos + c.healthyPos;
    const head = `از ۱۰۰۰ نفر: <b>${fa(c.sick)}</b> بیمار، <b>${fa(c.healthy)}</b> سالم.<br>` +
      `<b style="color:var(--green)">${fa(c.sickPos)} بیمارِ مثبت</b>، <b style="color:var(--accent)">${fa(c.sickNeg)} بیمارِ جاافتاده</b>، <b style="color:var(--red)">${fa(c.healthyPos)} سالمِ مثبت</b>، بقیه سالمِ منفی.<br>`;
    if (!pos) return head + 'هیچ‌کس مثبت نشده.';
    return head + `همه‌ی مثبت‌ها: ${fa(c.sickPos)} + ${fa(c.healthyPos)} = <b>${fa(pos)}</b><br>` +
      `${E('P(sick | +)')} = ${fa(c.sickPos)} ÷ ${fa(pos)} ≈ <b style="color:var(--green)">${BAYES_pct(c.sickPos / pos)}</b>`;
  },
});

// ---- Picture 2: belief meter; each positive test turns the posterior into the next prior ----
// test fixed: catches 99% of sick people, wrongly flags 5% of healthy people
const BAYES_MAX = 6;
const BAYES_update = p => 0.99 * p / (0.99 * p + 0.05 * (1 - p));

const BAYES_W_METER = h => plane(h, {
  x: [-1.3, 7.2], y: [-0.16, 1.12], ratio: 0.75,
  state: { prior: 1, hist: [0.01] },
  sliders: [{ key: 'prior', label: 'باورِ اول (٪)', min: 0.5, max: 50, step: 0.5 }],
  onSlide: s => { s.hist = [s.prior / 100]; },
  buttons: [
    { label: 'یک آزمایشِ مثبتِ دیگر', on: s => { if (s.hist.length <= BAYES_MAX) s.hist.push(BAYES_update(s.hist[s.hist.length - 1])); } },
    { label: 'از نو', on: s => { s.hist = [s.prior / 100]; } },
  ],
  draw: (g, s) => {
    [0, 0.25, 0.5, 0.75, 1].forEach(y => { g.line(0, y, 7, y, y ? 'soft' : 'line', y ? 1 : 2); g.text(-0.15, y, fa(y * 100) + '٪', 'muted', 'right', 0); });
    s.hist.forEach((p, k) => {
      g.rect(k + 0.2, 0, k + 0.8, p, k ? 'green' : 'blue', 0.85);
      g.text(k + 0.5, p, BAYES_pct(p), k ? 'green' : 'blue', 'center', -10);
      g.text(k + 0.5, 0, k ? fa(k) : 'اول', 'muted', 'center', 13);
    });
  },
  read: s => {
    const n = s.hist.length - 1, now = s.hist[n];
    if (!n) return `باورِ اول (پیشین): <b style="color:var(--blue)">${BAYES_pct(now)}</b> بیمار. هنوز آزمایشی نداده‌ایم. دکمه را بزنید.`;
    return `بعد از <b>${fa(n)}</b> آزمایشِ مثبت: باور از ${BAYES_pct(s.hist[n - 1])} شد <b style="color:var(--green)">${BAYES_pct(now)}</b>.<br>` +
      `<span class="muted">پسینِ این مرحله، پیشینِ مرحله‌ی بعد است.</span>` +
      (n >= BAYES_MAX ? '<br>بیشتر از ۶ آزمایش جا نمی‌شود؛ «از نو» را بزنید.' : '');
  },
});

