// ---------- Statistics: Mean & Median ----------
// (names start with MEAN_ because all lesson files share one global scope)

const MEAN_clamp = (v, a, b) => Math.max(a, Math.min(b, v));
// one decimal; says «حدود» when the value was rounded
const MEAN_fa1 = v => { const r = Math.round(v * 10) / 10; return (Math.abs(r - v) > 1e-9 ? 'حدود ' : '') + fa(r); };
const MEAN_START = [2, 3, 4, 5, 6, 7, 8];
// equal values stack upward: how many earlier points share this x
const MEAN_level = (p, i) => p.slice(0, i).filter(v => v === p[i]).length;

// 7 draggable points on a ruler: red triangle = mean (balance point), green line = median
const W_MEAN_BALANCE = h => plane(h, {
  x: [-0.8, 20.8], y: [-2.4, 7.6], ratio: 0.6, snap: 1,
  state: { p: [...MEAN_START] },
  handles: MEAN_START.map((_, i) => ({
    get: s => [s.p[i], 1 + 0.9 * MEAN_level(s.p, i)],
    set: (s, x) => { s.p[i] = MEAN_clamp(x, 0, 20); },
    color: 'blue',
  })),
  buttons: [
    { label: 'یکی را خیلی دور ببر', on: s => { const k = s.p.indexOf(Math.max(...s.p)); s.p[k] = 20; } },
    { label: 'از اول', on: s => { s.p = [...MEAN_START]; } },
  ],
  draw: (g, s) => {
    for (let t = 0; t <= 20; t++) g.line(t, 0, t, -0.25, 'muted', 1);
    for (let t = 0; t <= 20; t += 2) g.text(t, 0, fa(t), 'muted', 'center', 26);
    g.line(0, 0, 20, 0, 'ink', 3);
    const m = ST.mean(s.p), md = ST.median(s.p);
    g.line(md, 0, md, 6.9, 'green', 2, [6, 5]);
    g.text(md, 6.9, 'میانه', 'green', 'center', -4);
    drawMarker(g, m, 0, 'red');
    g.text(m, -1.9, 'میانگین', 'red', 'center', 0);
  },
  read: s => {
    const srt = ST.sorted(s.p), m = ST.mean(s.p), md = ST.median(s.p);
    const line = srt.map((v, i) => (i === 3 ? `<b style="color:var(--green)">${fa(v)}</b>` : fa(v))).join('، ');
    const gap = m - md;
    const note = Math.abs(gap) < 0.5 ? 'این دو تقریباً روی هم‌اند.'
      : `میانگین ${MEAN_fa1(Math.abs(gap))} واحد ${gap > 0 ? 'به راست' : 'به چپ'}ِ میانه است؛ دنبالِ نقطه‌ی دور رفته.`;
    return `صفِ مرتب: ${line}<br>` +
      `<b style="color:var(--red)">میانگین (تعادل) = ${MEAN_fa1(m)}</b> &nbsp;|&nbsp; <b style="color:var(--green)">میانه (نفرِ وسط) = ${fa(md)}</b><br>${note}`;
  },
});

// 49 monthly incomes (million toman), fixed shape: median always 10, slider stretches only the right tail (mean ~20 at max)
const MEAN_N = 49;
const MEAN_z = i => { const p = (i + 0.5) / MEAN_N; return 4.91 * (p ** 0.14 - (1 - p) ** 0.14); }; // symmetric, middle one is 0
const MEAN_incomes = k => Array.from({ length: MEAN_N }, (_, i) => { const z = MEAN_z(i); return 10 * Math.exp(k / 10 * (z > 0 ? 1.32 * z : z)); });

const W_MEAN_SKEW = h => plane(h, {
  x: [-4, 174], y: [-2.9, 10.8], ratio: 0.75,
  state: { k: 1 },
  sliders: [{ key: 'k', label: 'طولِ دُم:', min: 1, max: 9, step: 1 }],
  draw: (g, s) => {
    const a = MEAN_incomes(s.k), c = ST.hist(a, 0, 170, 34);
    drawHist(g, a, 0, 170, 34, 'blue', 9 / Math.max(...c));
    g.line(0, 0, 170, 0, 'line', 2);
    for (let t = 0; t <= 160; t += 20) { g.line(t, 0, t, -0.3, 'muted', 1); g.text(t, 0, fa(t), 'muted', 'center', 26); }
    const m = ST.mean(a), md = ST.median(a);
    g.line(md, 0, md, 9.8, 'green', 2, [6, 5]);
    g.text(md, 9.8, 'میانه', 'green', 'left', -4);
    drawMarker(g, m, 0, 'red');
    g.text(m, -2.3, 'میانگین', 'red', 'left', 0);
  },
  read: s => {
    const a = MEAN_incomes(s.k), m = ST.mean(a), md = ST.median(a);
    const below = a.filter(v => v < m).length;
    return `درآمد ماهانه‌ی ${fa(MEAN_N)} نفر (میلیون تومان).<br>` +
      `<b style="color:var(--red)">میانگین = ${MEAN_fa1(m)}</b> &nbsp;|&nbsp; <b style="color:var(--green)">میانه = ${fa(md)}</b><br>` +
      `میانگین <b>${MEAN_fa1(m - md)}</b> واحد بالاترِ میانه است.<br>` +
      `<b>${fa(below)}</b> نفر از ${fa(MEAN_N)} نفر، کمتر از میانگین درآمد دارند.`;
  },
});

