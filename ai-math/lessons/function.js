// ---------- Foundations: Function & Graph ----------
const taxi = k => 10 + 2 * k;

const W_TAXI = h => plane(h, {
  x: [-0.7, 8.6], y: [-2.5, 30], step: [1, 5], labels: true, names: ['کیلومتر', 'کرایه (هزار تومان)'], ratio: 0.8,
  state: { k: 3, seen: new Set([3]), all: false },
  sliders: [{ key: 'k', label: 'کیلومتر:', min: 0, max: 8, step: 1 }],
  onSlide: s => s.seen.add(s.k),
  buttons: [{ label: 'همه‌ی حالت‌ها را نشان بده', on: s => { s.all = !s.all; }, active: s => s.all }],
  draw: (g, s) => {
    g.grid();
    if (s.all) g.fn(taxi, 'orange', 3, 0, 8.6);
    s.seen.forEach(k => g.dot(k, taxi(k), 'orange', 5));
    g.line(s.k, 0, s.k, taxi(s.k), 'blue', 2, [5, 5]);
    g.line(0, taxi(s.k), s.k, taxi(s.k), 'green', 2, [5, 5]);
    g.dot(s.k, taxi(s.k), 'ink', 8);
  },
  read: s => `ورودی: <b style="color:var(--blue)">${fa(s.k)} کیلومتر</b> ← دستگاه ← خروجی: <b style="color:var(--green)">${fa(taxi(s.k))} هزار تومان</b><br>` +
    (s.all ? 'همه‌ی نقطه‌ها روی یک خط صاف‌اند. این خط، <b>نمودارِ</b> دستگاه است.' : `${fa(s.seen.size)} حالت از ۹ حالت را دیده‌اید.`),
});

const FNS = [
  ['2x + 1', x => 2 * x + 1, 'خط صاف: با هر یک قدم به راست، ۲ تا بالا می‌رود.'],
  ['x²', x => x * x, 'x² یعنی x × x. اول پایین می‌آید، بعد بالا می‌رود؛ مثل یک کاسه. −۲ و ۲ هر دو خروجی ۴ دارند و اشکالی ندارد.'],
  ['3', () => 3, 'ورودی هرچه باشد، خروجی ۳ است. این هم تابع است!'],
];
const W_EXPLORE = h => plane(h, {
  x: [-3.6, 3.6], y: [-2.5, 10], labels: true, ratio: 0.9, snap: 0.5,
  state: { x: 2, k: 1 },
  buttons: FNS.map(([n], i) => ({ label: E('f(x) = ' + n), on: s => { s.k = i; }, active: s => s.k === i })),
  handles: [{ get: s => [s.x, FNS[s.k][1](s.x)], set: (s, x) => { s.x = Math.max(-3, Math.min(3, x)); }, color: 'orange' }],
  draw: (g, s) => {
    g.grid();
    const f = FNS[s.k][1], y = f(s.x);
    g.fn(f, 'orange', 4);
    g.line(s.x, 0, s.x, y, 'blue', 2, [5, 5]); g.line(0, y, s.x, y, 'green', 2, [5, 5]);
    g.dot(s.x, 0, 'blue', 6); g.dot(0, y, 'green', 6);
  },
  read: s => {
    const y = FNS[s.k][1](s.x);
    return `ورودی <b style="color:var(--blue)">${E('x = ' + fa(s.x))}</b> ← خروجی <b style="color:var(--green)">${E('f(x) = ' + fa(y))}</b><br>${FNS[s.k][2]}`;
  },
});

