// ---------- Classical ML: K-Means Clustering ----------
// (names start with KMEANS_ because all lesson files share one global scope)

// 30 customers, no labels: x = visits per month, y = spend per visit (hundred thousand toman). Three blobs.
const KMEANS_OFF = [[0, 0], [0.9, 0.4], [-0.8, 0.6], [0.3, -1], [-0.5, -0.7], [1.2, -0.3], [-1.1, -0.2], [0.4, 1.1], [-0.2, 0.9], [0.7, -0.6]];
const KMEANS_P = [[2, 2], [8, 2.5], [5, 8]].flatMap(([cx, cy], b) => KMEANS_OFF.map(([dx, dy]) => {
  const [rx, ry] = b === 1 ? [-dy, dx] : b === 2 ? [dx, -dy] : [dx, dy];
  return [Math.round((cx + rx) * 10) / 10, Math.round((cy + ry) * 10) / 10];
}));
const KMEANS_COL = ['blue', 'orange', 'green', 'red', 'accent'];
const KMEANS_fa1 = v => fa(Math.round(v * 10) / 10);

// fixed pseudo-random generator, so «new random start» gives the same starts every time
const KMEANS_rnd = seed => () => {
  seed |= 0; seed = seed + 0x6D2B79F5 | 0;
  let t = Math.imul(seed ^ seed >>> 15, 1 | seed);
  t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
  return ((t ^ t >>> 14) >>> 0) / 4294967296;
};
// start: k different data points, chosen by the seed, become the first centres
const KMEANS_start = (k, seed) => {
  const r = KMEANS_rnd(seed * 7 + k), idx = [];
  while (idx.length < k) { const i = Math.floor(r() * KMEANS_P.length); if (!idx.includes(i)) idx.push(i); }
  return idx.map(i => [...KMEANS_P[i]]);
};
const KMEANS_d2 = (a, b) => (a[0] - b[0]) ** 2 + (a[1] - b[1]) ** 2;
// step 1: every point joins its nearest centre
const KMEANS_assign = C => KMEANS_P.map(p => { let b = 0; C.forEach((c, j) => { if (KMEANS_d2(p, c) < KMEANS_d2(p, C[b])) b = j; }); return b; });
// step 2: every centre moves to the mean of its points (an empty group keeps its centre)
const KMEANS_move = (C, A) => C.map((c, j) => {
  const g = KMEANS_P.filter((_, i) => A[i] === j);
  return g.length ? [g.reduce((t, p) => t + p[0], 0) / g.length, g.reduce((t, p) => t + p[1], 0) / g.length] : c;
});
// J: sum of squared distances from each point to its own centre
const KMEANS_J = (C, A) => KMEANS_P.reduce((t, p, i) => t + KMEANS_d2(p, C[A[i]]), 0);
const KMEANS_run = (k, seed) => {
  let C = KMEANS_start(k, seed), A = KMEANS_assign(C);
  for (let n = 0; n < 100; n++) { C = KMEANS_move(C, A); const B = KMEANS_assign(C); if (B.join() === A.join()) break; A = B; }
  return KMEANS_J(C, A);
};

const KMEANS_reset = s => { s.C = KMEANS_start(s.k, s.seed); s.A = null; s.round = 0; s.phase = 'start'; s.done = false; s.msg = 'مرکزها به‌تصادف روی چند مشتری نشسته‌اند. «گروه‌بندی» را بزنید.'; };
const KMEANS_doAssign = s => {
  if (s.done) return;
  if (s.phase === 'assigned') { s.msg = 'نقطه‌ها گروهشان را انتخاب کرده‌اند؛ حالا «جابه‌جایی مرکزها».'; return; }
  const B = KMEANS_assign(s.C);
  if (s.A && B.join() === s.A.join()) { s.done = true; s.msg = '<b>تمام!</b> هیچ نقطه‌ای گروهش را عوض نکرد.'; return; }
  s.A = B; s.round++; s.phase = 'assigned';
  s.msg = 'هر نقطه به <b>نزدیک‌ترین</b> مرکز پیوست. حالا «جابه‌جایی مرکزها».';
};
const KMEANS_doMove = s => {
  if (s.done) return;
  if (s.phase !== 'assigned') { s.msg = 'اول «گروه‌بندی»: هر نقطه باید نزدیک‌ترین مرکز را انتخاب کند.'; return; }
  s.C = KMEANS_move(s.C, s.A); s.phase = 'moved';
  s.msg = 'هر مرکز به <b>میانگینِ</b> نقطه‌های گروهش رفت. دوباره «گروه‌بندی».';
};

// picture 1: the two steps by hand
const KMEANS_W_STEPS = h => {
  const st = { k: 3, seed: 1 };
  KMEANS_reset(st);
  return plane(h, {
    x: [-0.6, 10.6], y: [-0.6, 10.6], ratio: 0.85, labels: true, step: [2, 2], names: ['دفعه در ماه', 'خرید هر بار'],
    state: st,
    sliders: [{ key: 'k', label: 'k (تعداد گروه):', min: 2, max: 5, step: 1 }],
    onSlide: KMEANS_reset,
    buttons: [
      { label: 'گروه‌بندی', on: KMEANS_doAssign },
      { label: 'جابه‌جایی مرکزها', on: KMEANS_doMove },
      { label: 'تا آخر', on: s => { for (let n = 0; n < 200 && !s.done; n++) s.phase === 'assigned' ? KMEANS_doMove(s) : KMEANS_doAssign(s); } },
      { label: 'شروع تصادفی تازه', on: s => { s.seed = s.seed % 10 + 1; KMEANS_reset(s); } },
    ],
    draw: (g, s) => {
      g.grid();
      if (s.A) KMEANS_P.forEach((p, i) => { const c = s.C[s.A[i]]; g.line(p[0], p[1], c[0], c[1], 'line', 1); });
      KMEANS_P.forEach((p, i) => g.dot(p[0], p[1], s.A ? KMEANS_COL[s.A[i]] : 'muted', 5));
      s.C.forEach((c, j) => { g.dot(c[0], c[1], 'ink', 11); g.dot(c[0], c[1], KMEANS_COL[j], 7); });
    },
    read: s => `شروعِ شماره‌ی ${fa(s.seed)} &nbsp;|&nbsp; دور ${fa(s.round)}<br>${s.msg}<br>` +
      (s.A ? `مجموعِ مربعِ فاصله‌ها تا مرکز: <b style="color:var(--red)">${KMEANS_fa1(KMEANS_J(s.C, s.A))}</b> (کمتر = گروه‌های جمع‌وجورتر)` : 'هنوز گروهی نداریم.'),
  });
};

// picture 2: the elbow. Best J of 20 starts for k = 1..6 (computed once)
const KMEANS_ELBOW = [1, 2, 3, 4, 5, 6].map(k => Math.min(...Array.from({ length: 20 }, (_, i) => KMEANS_run(k, i + 1))));
// the elbow = where the drop suddenly gets small (largest bend)
const KMEANS_BEND = (() => { let b = 2, m = -1; for (let k = 2; k <= 5; k++) { const d = KMEANS_ELBOW[k - 2] - 2 * KMEANS_ELBOW[k - 1] + KMEANS_ELBOW[k]; if (d > m) { m = d; b = k; } } return b; })();

const KMEANS_W_ELBOW = h => plane(h, {
  x: [0.3, 6.7], y: [-45, 470], ratio: 0.75, labels: true, step: [1, 100], names: ['k', 'J'],
  state: { k: 2 },
  sliders: [{ key: 'k', label: 'k:', min: 1, max: 6, step: 1 }],
  draw: (g, s) => {
    g.grid();
    for (let k = 1; k < 6; k++) g.line(k, KMEANS_ELBOW[k - 1], k + 1, KMEANS_ELBOW[k], 'orange', 3);
    KMEANS_ELBOW.forEach((v, i) => g.dot(i + 1, v, 'orange', 5));
    const e = KMEANS_BEND, ve = KMEANS_ELBOW[e - 1];
    g.dot(e, ve, 'red', 12); g.dot(e, ve, 'card', 8); g.dot(e, ve, 'red', 5);
    g.text(e, ve, 'آرنج', 'red', 'left', -22);
    g.line(s.k, 0, s.k, KMEANS_ELBOW[s.k - 1], 'green', 2, [5, 5]);
    g.dot(s.k, KMEANS_ELBOW[s.k - 1], 'green', 7);
  },
  read: s => {
    const v = KMEANS_ELBOW[s.k - 1];
    let t = `k = ${fa(s.k)}: J = <b style="color:var(--green)">${KMEANS_fa1(v)}</b>`;
    if (s.k > 1) {
      const drop = KMEANS_ELBOW[s.k - 2] - v;
      t += `<br>از k = ${fa(s.k - 1)} تا ${fa(s.k)}، J به اندازه‌ی <b>${KMEANS_fa1(drop)}</b> کم شد.`;
    }
    return t + (s.k === KMEANS_BEND ? '<br><b style="color:var(--red)">این‌جا آرنج است:</b> بعد از این، گروهِ بیشتر کمکِ زیادی نمی‌کند.' : '');
  },
});

