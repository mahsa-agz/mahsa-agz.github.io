// ---------- Vectors: Length (Norm) and Distance ----------
// uses vecPlane / clampV from lessons/vectors.js
const VLEN_sign = n => (n < 0 ? -1 : 1);
// √n as text: exact when it is a whole number, otherwise ≈ rounded to 2 decimals
const VLEN_root = n => { const r = Math.sqrt(n); return Number.isInteger(r) ? `√${fa(n)} = ${fa(r)}` : `√${fa(n)} ≈ ${fa(r)}`; };

// drag the tip; the right triangle under the arrow gives its length
const VLEN_W_ONE = h => vecPlane(h, {
  labels: true,
  state: { ax: 3, ay: 4 },
  handles: [{ get: s => [s.ax, s.ay], set: (s, x, y) => { [s.ax, s.ay] = clampV(x, y); }, color: 'orange' }],
  draw: (g, s) => {
    g.grid();
    const x = s.ax, y = s.ay, sx = VLEN_sign(x), sy = VLEN_sign(y);
    if (x && y) g.rect(x - 0.4 * sx, 0, x, 0.4 * sy, 'muted', 0.35);
    g.line(0, 0, x, 0, 'blue', 5);
    g.line(x, 0, x, y, 'green', 5);
    g.arrow(0, 0, x, y, 'orange', 5);
    g.dot(0, 0, 'ink', 5);
    if (x) g.text(x / 2, 0, fa(Math.abs(x)), 'blue', 'center', y > 0 ? 16 : -16);
    if (y) g.text(x + 0.25 * sx, y / 2, fa(Math.abs(y)), 'green', sx > 0 ? 'left' : 'right', 0);
  },
  read: s => {
    const a = s.ax * s.ax, b = s.ay * s.ay;
    if (!a && !b) return 'هیچ جابه‌جایی نداریم (بردار صفر). طولش <b>۰</b> است.';
    return `<b style="color:var(--blue)">افقی ${fa(Math.abs(s.ax))}</b> ← مربعش ${fa(a)}<br>` +
      `<b style="color:var(--green)">عمودی ${fa(Math.abs(s.ay))}</b> ← مربعش ${fa(b)}<br>` +
      `جمع مربع‌ها: ${fa(a)} + ${fa(b)} = ${fa(a + b)}<br>` +
      `<b style="color:var(--orange)">طول</b> = ${E(VLEN_root(a + b))}`;
  },
});

// two points A and B; the arrow from A to B is B − A, its length is the distance
const VLEN_W_DIST = h => vecPlane(h, {
  labels: true,
  state: { ax: -2, ay: -1, bx: 1, by: 3 },
  handles: [
    { get: s => [s.ax, s.ay], set: (s, x, y) => { [s.ax, s.ay] = clampV(x, y); }, color: 'ink' },
    { get: s => [s.bx, s.by], set: (s, x, y) => { [s.bx, s.by] = clampV(x, y); }, color: 'ink' },
  ],
  draw: (g, s) => {
    g.grid();
    g.line(s.ax, s.ay, s.bx, s.ay, 'blue', 3, [6, 6]);
    g.line(s.bx, s.ay, s.bx, s.by, 'green', 3, [6, 6]);
    g.arrow(s.ax, s.ay, s.bx, s.by, 'orange', 5);
    g.text(s.ax, s.ay, 'A', 'ink', 'center', -20);
    g.text(s.bx, s.by, 'B', 'ink', 'center', -20);
  },
  read: s => {
    const dx = s.bx - s.ax, dy = s.by - s.ay, a = dx * dx, b = dy * dy;
    const sq = n => (n < 0 ? `(${fa(n)})²` : `${fa(n)}²`);
    return `B − A = ${V(dx, dy)}<br>` +
      `مربع‌ها: ${E(`${sq(dx)} = ${fa(a)}`)} و ${E(`${sq(dy)} = ${fa(b)}`)}<br>` +
      `فاصله = ${E(`√(${fa(a)} + ${fa(b)}) = ${VLEN_root(a + b)}`)}` +
      (a + b ? '' : '<br>دو نقطه روی هم‌اند: فاصله صفر.');
  },
});

