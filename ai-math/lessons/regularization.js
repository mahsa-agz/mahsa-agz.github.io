// ---- picture 1: degree-9 polynomial on 10 noisy points, fitted with ridge (L2) ----
// Data: y = sin(0.9πx) + noise, rounded to 2 decimals. x is already scaled to [−1, 1].
// Train: x = −1 + 2i/9 (i = 0..9). New data: the 9 midpoints, with their own small noise.
// Fit: solve (XᵀX + λI)w = Xᵀy by Gaussian elimination (all 10 weights penalized, w₀ too).
// Checked in node (train MSE / new-data MSE / largest |w|):
//   λ=0: 0 / 3.232 / 513    λ=0.001: 0.040 / 0.020 / 3.9   λ=0.01: 0.048 / 0.019 / 2.2
//   λ=0.1: 0.058 / 0.032 / 1.7   λ=1: 0.164 / 0.120 / 0.95   λ=10: 0.425 / 0.385 / 0.23
const REG_DEG = 9;
const REG_XS = [...Array(10)].map((_, i) => -1 + 2 * i / 9);
const REG_YS = [-0.06, -1.01, -0.7, -1.06, -0.11, 0.01, 1.06, 0.8, 1.11, 0.06];
const REG_XT = [...Array(9)].map((_, i) => -1 + 2 * (i + 0.5) / 9);
const REG_YT = [-0.69, -0.8, -1, -0.49, -0.15, 0.64, 0.85, 1.1, 0.54];
const REG_LAMBDAS = [0, 0.001, 0.01, 0.1, 1, 10];
const REG_LNAMES = ['۰', '۰٫۰۰۱', '۰٫۰۱', '۰٫۱', '۱', '۱۰'];

const REG_powers = x => [...Array(REG_DEG + 1)].map((_, k) => x ** k);
const REG_solve = (A, b) => {
  const n = b.length, M = A.map((r, i) => [...r, b[i]]);
  for (let c = 0; c < n; c++) {
    let p = c;
    for (let r = c + 1; r < n; r++) if (Math.abs(M[r][c]) > Math.abs(M[p][c])) p = r;
    [M[c], M[p]] = [M[p], M[c]];
    for (let r = c + 1; r < n; r++) { const m = M[r][c] / M[c][c]; for (let k = c; k <= n; k++) M[r][k] -= m * M[c][k]; }
  }
  const w = Array(n).fill(0);
  for (let r = n - 1; r >= 0; r--) { let t = M[r][n]; for (let k = r + 1; k < n; k++) t -= M[r][k] * w[k]; w[r] = t / M[r][r]; }
  return w;
};
const REG_fit = lam => {
  const P = REG_XS.map(REG_powers), K = REG_DEG + 1;
  const A = [...Array(K)].map((_, i) => [...Array(K)].map((_, j) => P.reduce((t, r) => t + r[i] * r[j], 0) + (i === j ? lam : 0)));
  const b = [...Array(K)].map((_, i) => P.reduce((t, r, n) => t + r[i] * REG_YS[n], 0));
  return REG_solve(A, b);
};
const REG_eval = (w, x) => w.reduce((t, c, k) => t + c * x ** k, 0);
const REG_mse = (w, X, Y) => X.reduce((t, x, i) => t + (Y[i] - REG_eval(w, x)) ** 2, 0) / X.length;
// 3 decimals in Persian digits (fa rounds to 2)
const REG_n = v => String(Math.round(v * 1000) / 1000); // Latin digits, for inside LaTeX
const REG_f3 = v => String(Math.round(v * 1000) / 1000).replace('-', '−').replace('.', '٫').replace(/\d/g, d => '۰۱۲۳۴۵۶۷۸۹'[d]);

const W_REG_POLY = h => {
  const fits = REG_LAMBDAS.map(REG_fit);
  return plane(h, {
    x: [-1.15, 1.15], y: [-2.2, 2.2], step: [0.5, 0.5], ratio: 0.8,
    state: { k: 0 },
    buttons: REG_LAMBDAS.map((_, k) => ({ label: `λ = ${REG_LNAMES[k]}`, on: s => { s.k = k; }, active: s => s.k === k })),
    draw: (g, s) => {
      g.grid();
      g.fn(x => REG_eval(fits[s.k], x), 'orange', 3, -1.05, 1.05);
      REG_XT.forEach((x, i) => g.dot(x, REG_YT[i], 'muted', 5));
      REG_XS.forEach((x, i) => g.dot(x, REG_YS[i], 'blue', 7));
    },
    read: s => {
      const w = fits[s.k], big = Math.max(...w.map(Math.abs));
      const tr = REG_mse(w, REG_XS, REG_YS), te = REG_mse(w, REG_XT, REG_YT);
      const note = [
        'بدون مالیات: منحنی از همه‌ی نقطه‌ها رد شده، ولی وسطشان دیوانه‌وار بالا و پایین می‌رود. وزن‌ها صدها هستند.',
        'یک مالیاتِ کوچک کافی بود: وزن‌ها کوچک شدند و منحنی آرام شد.',
        'این‌جا خطای داده‌ی جدید از همه کمتر است: بهترین تعادل.',
        'هنوز خوب است، ولی کم‌کم ساده‌تر از لازم می‌شود.',
        'مالیات زیاد است: منحنی دیگر به نقطه‌ها نمی‌رسد.',
        `مالیات آن‌قدر سنگین است که منحنی تقریباً صاف شده: <b>کم‌برازش</b> ${EN('Underfitting')}. هر دو خطا بالا هستند.`,
      ][s.k];
      return `خطای آموزش (MSE روی نقطه‌های آبی): <b>${REG_f3(tr)}</b><br>` +
        `خطای داده‌ی جدید (نقطه‌های خاکستری): <b style="color:var(--red)">${REG_f3(te)}</b><br>` +
        `بزرگ‌ترین وزن (بدون علامت): <b style="color:var(--green)">${big >= 10 ? fa(Math.round(big)) : fa(big)}</b><br>${note}`;
    },
  });
};

// ---- picture 2: one weight w. data error (w − c)², penalty λw² or λ|w|, total = sum ----
// best w: L2 → c / (1 + λ)  (from 2(w − c) + 2λw = 0)
//         L1 → sign(c)·(|c| − λ/2) if |c| > λ/2, else exactly 0  (from 2(w − c) + λ·sign(w) = 0)
// c = 0.3: L1 hits 0 at λ = 0.6; L2 at λ = 2 is only 0.1.
const REG_best = s => s.m === 2 ? s.c / (1 + s.lam)
  : (Math.abs(s.c) <= s.lam / 2 + 1e-9 ? 0 : Math.sign(s.c) * (Math.abs(s.c) - s.lam / 2));
const REG_pen = (s, w) => s.m === 2 ? s.lam * w * w : s.lam * Math.abs(w);

const W_REG_ONE = h => plane(h, {
  x: [-1.2, 1.2], y: [-0.15, 1.6], step: [0.5, 0.5], labels: true, names: ['w', 'خطا'], ratio: 0.8,
  state: { m: 1, lam: 0.4, c: 0.3 },
  sliders: [{ key: 'lam', label: 'λ (سخت‌گیری):', min: 0, max: 2, step: 0.1 }, { key: 'c', label: 'کفِ کاسه‌ی داده:', min: -1, max: 1, step: 0.1 }],
  buttons: [
    { label: 'L1 (قدرِ مطلق)', on: s => { s.m = 1; }, active: s => s.m === 1 },
    { label: 'L2 (مربع)', on: s => { s.m = 2; }, active: s => s.m === 2 },
  ],
  draw: (g, s) => {
    g.grid();
    g.fn(w => (w - s.c) ** 2, 'red', 2);
    g.fn(w => REG_pen(s, w), 'ink', 2);
    g.fn(w => (w - s.c) ** 2 + REG_pen(s, w), 'orange', 4);
    g.dot(s.c, 0, 'red', 5);
    const b = REG_best(s), t = (b - s.c) ** 2 + REG_pen(s, b);
    g.line(b, 0, b, t, 'green', 2);
    g.dot(b, t, 'green', 7);
  },
  read: s => {
    const b = REG_best(s), c = REG_n(s.c), l = REG_n(s.lam);
    if (!s.lam) return `${E(String.raw`\lambda = 0`)}: جریمه‌ای در کار نیست، پس بهترین w همان کفِ کاسه است: <b style="color:var(--green)">${fa(s.c)}</b>. λ را بالا ببرید.`;
    if (s.m === 2) return `L2: بهترین وزن ${E(String.raw`w = \frac{c}{1 + \lambda} = \frac{${c}}{1 + ${l}} = ${REG_n(b)}`)}<br>` +
      (s.c ? `وزن فقط <b>کوچک‌تر</b> شد. λ را تا ۲ ببرید: باز هم دقیقاً صفر نمی‌شود، چون نزدیکِ صفر کششِ جریمه (${E(String.raw`2\lambda w`)}) هم تقریباً صفر است.` : 'کفِ کاسه خودش روی صفر است. c را عوض کنید.');
    if (!b) return `L1: بهترین وزن = <b style="color:var(--green)">دقیقاً ۰</b><br>` +
      `کششِ داده در صفر: ${E(String.raw`2 \times ${REG_n(Math.abs(s.c))} = ${REG_n(2 * Math.abs(s.c))}`)}؛ کششِ جریمه: ${E(String.raw`\lambda = ${l}`)}. زورِ داده از جریمه بیشتر نیست، پس وزن روی صفر می‌نشیند و همان‌جا می‌ماند.`;
    return `L1: بهترین وزن ${E(String.raw`w = c ${s.c > 0 ? '-' : '+'} \frac{\lambda}{2} = ${c} ${s.c > 0 ? '-' : '+'} \frac{${l}}{2} = ${REG_n(b)}`)}<br>` +
      `هنوز صفر نیست: کششِ داده در صفر (${fa(2 * Math.abs(s.c))}) از کششِ جریمه (${fa(s.lam)}) بیشتر است. λ را بالاتر ببرید.`;
  },
});

