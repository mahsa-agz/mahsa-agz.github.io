// ---------- Foundations: Gradient ----------
// the valley in both pictures: height z = x² + 2y², so ∂z/∂x = 2x and ∂z/∂y = 4y
const GRAD_clamp = (v, a, b) => Math.max(a, Math.min(b, v));
const GRAD_p = n => (n < 0 ? `(${fa(n)})` : fa(n));
const GRAD_z = (x, y) => x * x + 2 * y * y;
const GRAD_grad = (x, y) => [2 * x, 4 * y];
const GRAD_ARROW = 0.2; // arrows are drawn 5 times smaller so they fit
const GRAD_LR = 0.1;    // step size in picture 2

// valley seen from above: each orange oval = one height (2, 4, 6, … 24)
const GRAD_contours = g => {
  const c = g.ctx;
  c.save(); c.globalAlpha = 0.55; c.strokeStyle = g.css('orange'); c.lineWidth = 1.5; c.setLineDash([]);
  for (let h = 2; h <= 24; h += 2) {
    c.beginPath();
    c.ellipse(g.X(0), g.Y(0), g.X(Math.sqrt(h)) - g.X(0), g.Y(0) - g.Y(Math.sqrt(h / 2)), 0, 0, 2 * Math.PI);
    c.stroke();
  }
  c.restore();
  g.dot(0, 0, 'muted', 4);
  g.text(4.9, 0, 'شرق', 'muted', 'right', -10);
  g.text(0.15, 3.45, 'شمال', 'muted', 'left', 0);
};
const GRAD_box = { x: [-5, 5], y: [-3.75, 3.75], equal: true, snap: 0.5 };

// picture 1: drag a point; east slope (blue) + north slope (orange), end to end = gradient (green)
const GRAD_W_HILL = h => plane(h, {
  ...GRAD_box,
  state: { x: 2, y: 1 },
  handles: [{ get: s => [s.x, s.y], set: (s, x, y) => { s.x = GRAD_clamp(x, -3, 3); s.y = GRAD_clamp(y, -2, 2); }, color: 'red' }],
  draw: (g, s) => {
    g.grid();
    GRAD_contours(g);
    const [gx, gy] = GRAD_grad(s.x, s.y), ex = s.x + GRAD_ARROW * gx, ny = s.y + GRAD_ARROW * gy;
    g.arrow(s.x, s.y, ex, s.y, 'blue', 4);
    g.arrow(ex, s.y, ex, ny, 'orange', 4);
    g.arrow(s.x, s.y, ex, ny, 'green', 6);
  },
  read: s => {
    const [gx, gy] = GRAD_grad(s.x, s.y);
    const flat = !gx && !gy ? '<br>هر دو شیب صفر است: این‌جا <b>کفِ دره</b> است؛ زمین زیر پا لحظه‌ای صاف است و پیکانی نمی‌ماند.' : '';
    return `نقطه: شرق ${fa(s.x)}، شمال ${fa(s.y)} ← ارتفاع = ${GRAD_p(s.x)}² + ۲ × ${GRAD_p(s.y)}² = <b>${fa(GRAD_z(s.x, s.y))}</b><br>` +
      `<b style="color:var(--blue)">شیبِ رو به شرق</b> (فقط x عوض شود) = ${E('2x')} = <b>${fa(gx)}</b><br>` +
      `<b style="color:var(--orange)">شیبِ رو به شمال</b> (فقط y عوض شود) = ${E('4y')} = <b>${fa(gy)}</b><br>` +
      `<b style="color:var(--green)">گرادیان</b> = ${E(V(gx, gy))}؛ تندیِ سربالایی (طول پیکان سبز) ≈ <b>${fa(Math.hypot(gx, gy))}</b>${flat}`;
  },
});

// picture 2: the same valley; each press moves the point by −0.1 × gradient and draws the path
const GRAD_W_DOWN = h => plane(h, {
  ...GRAD_box,
  state: { x: 4, y: 2.5, path: [[4, 2.5]] },
  handles: [{ get: s => [s.x, s.y], set: (s, x, y) => { s.x = GRAD_clamp(x, -4, 4); s.y = GRAD_clamp(y, -3, 3); s.path = [[s.x, s.y]]; }, color: 'red' }],
  buttons: [
    { label: 'یک قدم سرازیری', on: s => { const [gx, gy] = GRAD_grad(s.x, s.y); s.x -= GRAD_LR * gx; s.y -= GRAD_LR * gy; s.path.push([s.x, s.y]); } },
    { label: 'از نو', on: s => { s.x = 4; s.y = 2.5; s.path = [[4, 2.5]]; } },
  ],
  draw: (g, s) => {
    g.grid();
    GRAD_contours(g);
    for (let i = 1; i < s.path.length; i++) g.line(s.path[i - 1][0], s.path[i - 1][1], s.path[i][0], s.path[i][1], 'green', 3);
    s.path.forEach(([x, y]) => g.dot(x, y, 'green', 4));
    const [gx, gy] = GRAD_grad(s.x, s.y);
    g.arrow(s.x, s.y, s.x - GRAD_ARROW * gx, s.y - GRAD_ARROW * gy, 'ink', 3);
  },
  read: s => {
    const [gx, gy] = GRAD_grad(s.x, s.y), n = s.path.length - 1;
    const end = Math.hypot(gx, gy) < 0.05 ? '<br>گرادیان تقریباً صفر شد: به <b>کفِ دره</b> رسیده‌ایم.' : '';
    return `قدم‌ها: <b>${fa(n)}</b> ← نقطه: شرق ${fa(s.x)}، شمال ${fa(s.y)}، ارتفاع = <b>${fa(GRAD_z(s.x, s.y))}</b><br>` +
      `<b style="color:var(--green)">گرادیان</b> این‌جا = ${E(V(gx, gy))}<br>` +
      `قدم بعدی = ${E('−0.1 ×')} گرادیان = ${E(V(-GRAD_LR * gx, -GRAD_LR * gy))}${end}`;
  },
});

