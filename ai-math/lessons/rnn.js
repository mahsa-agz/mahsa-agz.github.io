// ---------- Deep Learning: RNN ----------
// (names start with RNN_ because all lesson files share one global scope)

const RNN_SPAN = (c, t) => `<span style="color:var(--${c})">${t}</span>`;
// a share (0…1) as a Persian percent
const RNN_pct = v => (v < 0.001 ? 'کمتر از ۰٫۱٪' : v < 1 + 1e-9 ? fa(v * 100) + '٪' : fa(v) + ' برابر');

// ---- Picture 1: read a sentence word by word; each step the old memory is kept at 60% and the new word gets 40% ----
const RNN_WORDS = ['علی', 'کتاب', 'را', 'به', 'مریم', 'داد'];
const RNN_KEEP = 0.6, RNN_NEW = 0.4;
// shares in the memory after reading t words: [word1, …, word t], plus the empty start (h₀)
const RNN_shares = t => ({ w: RNN_WORDS.slice(0, t).map((_, k) => RNN_NEW * RNN_KEEP ** (t - 1 - k)), empty: RNN_KEEP ** t });

const RNN_W_READ = h => plane(h, {
  x: [0, 6], y: [0.3, 4.1], ratio: 0.62,
  state: { t: 0 },
  buttons: [
    { label: 'کلمه‌ی بعد', on: s => { if (s.t < RNN_WORDS.length) s.t++; } },
    { label: 'از اول', on: s => { s.t = 0; } },
  ],
  draw: (g, s) => {
    // the sentence, right to left
    RNN_WORDS.forEach((w, i) => {
      const a = 5 - i, cur = i === s.t - 1;
      g.rect(a + 0.06, 3, a + 0.94, 3.9, 'soft', 1);
      if (i === 0) g.rect(a + 0.06, 3, a + 0.94, 3.9, 'red', 0.3);
      else if (i < s.t) g.rect(a + 0.06, 3, a + 0.94, 3.9, 'blue', 0.2);
      if (cur) g.rect(a + 0.06, 3, a + 0.94, 3.9, 'orange', 0.45);
      g.text(a + 0.5, 3.45, w, i < s.t ? 'ink' : 'muted', 'center', 0);
    });
    if (s.t) g.arrow(6.5 - s.t, 2.95, 6.5 - s.t, 2.3, 'orange', 3);
    // the memory bar: word 1 at the right, newer words to its left, the empty start at the far left
    const sh = RNN_shares(s.t);
    let right = 6;
    sh.w.forEach((v, k) => {
      const left = right - 6 * v;
      g.rect(left, 1.2, right, 2.2, k === 0 ? 'red' : 'blue', k === 0 ? 0.85 : (k % 2 ? 0.75 : 0.4));
      if (right - left > 0.55) g.text((left + right) / 2, 1.7, fa(v * 100) + '٪', 'card', 'center', 0);
      right = left;
    });
    if (right > 0.01) g.rect(0, 1.2, right, 2.2, 'soft', 1);
    if (right > 0.9) g.text(right / 2, 1.7, 'خالی', 'muted', 'center', 0);
    g.text(3, 0.75, 'حافظه (h): سهم هر کلمه', 'muted', 'center', 0);
  },
  read: s => {
    if (!s.t) return 'حافظه هنوز خالی است. «کلمه‌ی بعد» را بزنید.';
    const first = RNN_shares(s.t).w[0];
    return `کلمه‌ی «${RNN_WORDS[s.t - 1]}» خوانده شد. حافظه‌ی تازه = ${fa(RNN_KEEP)} × حافظه‌ی قدیم + ${fa(RNN_NEW)} × کلمه‌ی تازه<br>` +
      `سهم کلمه‌ی اول «${RNN_SPAN('red', 'علی')}» در حافظه: <b style="color:var(--red)">${fa(first * 100)}٪</b>` +
      (s.t === RNN_WORDS.length ? '<br>جمله تمام شد. «چه کسی داد؟» جوابش کلمه‌ی اول بود، ولی فقط حدودِ <b>۳٪</b> از آن مانده.' : '');
  },
});

// ---- Picture 2: how much of the first input survives after t steps: about Wᵗ (or fᵗ with a gate) ----
const RNN_GATE = 0.99;
const RNN_W_FADE = h => plane(h, {
  x: [0, 21], y: [0, 2.2], ratio: 0.6, step: [5, 0.5], labels: true, names: ['گام', 'سهم'],
  state: { w: 0.5, gate: false },
  sliders: [{ key: 'w', label: 'W (وزنِ حافظه):', min: 0.1, max: 1.5, step: 0.1 }],
  buttons: [{ label: 'دریچه‌ی اسباب‌بازیِ LSTM', on: s => { s.gate = !s.gate; }, active: s => s.gate }],
  draw: (g, s) => {
    g.grid();
    g.line(0, 1, 21, 1, 'ink', 2, [6, 5]);
    const m = s.gate ? RNN_GATE : s.w;
    for (let t = 1; t <= 20; t++) {
      const v = m ** t;
      g.rect(t - 0.35, 0, t + 0.35, Math.min(v, 2.2), v > 2.2 ? 'red' : s.gate ? 'green' : 'orange', 0.85);
    }
  },
  read: s => {
    const m = s.gate ? RNN_GATE : s.w, at = t => RNN_pct(m ** t);
    const note = s.gate ? `با دریچه، راهِ حافظه به‌جای W در «دریچه‌ی فراموشی» ضرب می‌شود که مدل یاد گرفته نزدیکِ ۱ باشد (این‌جا ${fa(RNN_GATE)}). بعد از ۲۰ گام هنوز بیشترش مانده.<br><span style="color:var(--muted)">ساده‌سازی: در LSTM واقعی دریچه ثابت نیست و برای هر ورودی عوض می‌شود.</span>`
      : Math.abs(s.w - 1) < 1e-9 ? `${E('W = 1')}: نه کم می‌شود نه زیاد. ولی tanh هم کمی کوچکش می‌کند، و پیدا کردنِ دقیقاً ۱ با آموزش تقریباً ناممکن است.`
      : s.w < 1 ? '<b>محو شدن</b> (Vanishing): هر گام کوچک‌تر. اولِ جمله تقریباً فراموش می‌شود.'
      : '<b>انفجار</b> (Exploding): هر گام بزرگ‌تر. ستون‌های <b style="color:var(--red)">قرمز</b> از سقفِ تصویر بیرون زده‌اند.';
    return `سهمِ مانده از ورودیِ اول بعد از t گام: ${E(`${Math.round(m * 100) / 100}^{t}`)}<br>بعد از ۵ گام: <b>${at(5)}</b> · ۱۰ گام: <b>${at(10)}</b> · ۲۰ گام: <b>${at(20)}</b><br>${note}`;
  },
});

